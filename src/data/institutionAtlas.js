/** The number of transcribed entries — the completeness figure a walker pins against. */
export const ATLAS_ENTRY_COUNT = ATLAS_ROWS.length;

/** Look an institution up by its exact catalog name. Returns null when the entry is not
 * in the atlas (a custom institution, or one minted after the transcription) — the caller
 * then falls back to the name rules, which is a DERIVATION and is recorded as one.
 * @param {string} name @returns {ReturnType<typeof BY_NAME.get> | null} */
export function atlasRow(name) {
  if (typeof name !== 'string' || !name) return null;
  return BY_NAME.get(name.toLowerCase()) || null;
}
