/**
 * replay.template.mjs — THE CAPSULE'S ONE-COMMAND REPRO, RENDERED (SK-2B; ODQ §143.5).
 *
 * A capsule that cannot be replayed is a note, not an artifact. This module renders the
 * `replay.mjs` that ships inside every capsule directory, so the reproduction path is
 * generated from the capsule's own recorded facts rather than reconstructed by hand at
 * dispatch time.
 *
 * ⛔ THE REPLAY RE-EXECUTES AGAINST A FRESH `git archive` OF THE RECORDED TIP, with the
 * archive's OWN lockfile install. A dependency bump is a mint trigger in this estate
 * (`package.json`/`package-lock.json` are governed), so a replay that ran against
 * whatever `node_modules` happened to be present would be reproducing a different
 * substrate and calling it the same finding.
 *
 * ⛔ AND IT REFUSES ON A NODE-MAJOR MISMATCH. Same-engine byte identity is guaranteed;
 * cross-engine identity is NOT — `scripts/count-transcendental-math.mjs` grandfathers a
 * non-zero transcendental baseline in its own header, so implementation-approximated
 * `Math` can fork same-seed worlds ACROSS engines while every same-engine golden stays
 * green. A hash mismatch under a mismatched engine is reported as ENGINE-VARIANCE, never
 * as a finding. An explicit override flag runs anyway and prints the caveat.
 *
 * Rendering is a PURE string build: no filesystem, no clock, no rng.
 */

/** The verdict vocabulary, closed. */
export const REPLAY_VERDICTS = Object.freeze(['REPRODUCED', 'NOT_REPRODUCED', 'ENGINE_VARIANCE']);

/**
 * @param {{capsuleId: string, sourceSha: string, nodeVersion: string, platform: string,
 *          arch: string, tripwireId: string, seed: string, years: number,
 *          settlements: number, tick: number, soakArgv: string[]}} capsule
 * @returns {string} the source of the capsule's `replay.mjs`
 */
export function renderReplayScript(capsule) {
  const argv = JSON.stringify(capsule.soakArgv || []);
  return `#!/usr/bin/env node
// GENERATED BY scripts/soak/replay.template.mjs — do not edit by hand.
// Capsule ${capsule.capsuleId}: tripwire ${capsule.tripwireId} at tick ${capsule.tick},
// seed ${capsule.seed}, ${capsule.years}y x ${capsule.settlements} settlements.
//
// Reproduces against a FRESH archive of ${capsule.sourceSha} with that archive's own
// lockfile install, so a dependency bump cannot silently change the replay substrate.
import { execFileSync } from 'node:child_process';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const RECORDED = ${JSON.stringify({
    sourceSha: capsule.sourceSha,
    nodeVersion: capsule.nodeVersion,
    platform: capsule.platform,
    arch: capsule.arch,
  }, null, 2)};
const OVERRIDE = process.argv.includes('--allow-engine-mismatch');
const major = (version) => String(version).replace(/^v/, '').split('.')[0];

if (major(process.version) !== major(RECORDED.nodeVersion)) {
  const line = \`node major \${major(process.version)} != recorded \${major(RECORDED.nodeVersion)}\`;
  if (!OVERRIDE) {
    console.error(\`REFUSED: \${line}. Same-engine byte identity is guaranteed; cross-engine is not.\`);
    console.error('Re-run under the recorded major, or pass --allow-engine-mismatch to accept ENGINE_VARIANCE.');
    process.exit(2);
  }
  console.warn(\`CAVEAT: \${line} — a hash mismatch here is ENGINE_VARIANCE, never a finding.\`);
}

const work = mkdtempSync(join(tmpdir(), 'soak-replay-'));
execFileSync('sh', ['-c', \`git archive --format=tar \${RECORDED.sourceSha} | tar -x -C \${work}\`], { stdio: 'inherit' });
execFileSync('npm', ['ci', '--ignore-scripts'], { cwd: work, stdio: 'inherit' });
execFileSync(process.execPath, ['scripts/audit/whole-world-soak.mjs', ...${argv}], { cwd: work, stdio: 'inherit' });
`;
}

/**
 * Classify a replay outcome. The engine-mismatch case is its OWN verdict rather than a
 * failure, because calling it a finding would send a fix lane after a difference the
 * engine's own floating-point implementation is entitled to.
 */
export function replayVerdict({ hashMatched, engineMatched }) {
  if (hashMatched) return 'REPRODUCED';
  return engineMatched ? 'NOT_REPRODUCED' : 'ENGINE_VARIANCE';
}
