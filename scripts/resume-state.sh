#!/bin/bash
# resume-state.sh — regenerate docs/RESUME_STATE.md, the ALWAYS-CURRENT resume point.
#
# WHY THIS EXISTS: docs/START_HERE.md is the deep bootstrap, but it is written BY HAND
# and is therefore only as fresh as the last time somebody remembered. Sessions here end
# abruptly on a 5-hour or weekly usage window — twice on 2026-08-07/08 a lane finished
# real work and died before committing, and once the handoff itself was a day stale. A
# handoff you have to remember to write is a document; this is the machinery version.
#
# RUN IT: after EVERY commit and EVERY phase boundary. It is cheap and idempotent.
#   sh scripts/resume-state.sh            # regenerate + snapshot, stage nothing
#   sh scripts/resume-state.sh --commit   # regenerate + snapshot + commit if changed
#
# ⭐ IT ALSO SNAPSHOTS IN-FLIGHT WORK ON EVERY RUN. The orphan-recovery procedure in
# START_HERE §3k says "back up FIRST" — this makes that automatic instead of remembered.
# Rotating, last 3 kept, under the scratch dir (NOT the repo — never commit a snapshot).
#
# NOT A GIT HOOK, DELIBERATELY — the same reason refresh-archive.sh is not one: build
# lanes assert `git status --porcelain` is EMPTY right after their own commits, and a
# hook that wrote files would break that invariant and read as foreign WIP.
set -u

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO" || exit 1

BUILD_TREE="$REPO/.claude/worktrees/minifold"
OUT="$REPO/docs/RESUME_STATE.md"
SNAP_ROOT="${RESUME_SNAPSHOT_DIR:-/private/tmp/claude-502/-Users-cstokes-Desktop-settlement-engine/resume-snapshots}"

# ── 1. SNAPSHOT IN-FLIGHT WORK FIRST, before anything can go wrong ───────────────
# Deliberately first: if this script is interrupted, the backup has already happened.
# ⚠ POSIX ONLY — this file is invoked as `sh scripts/resume-state.sh`, and macOS runs
# /bin/sh as bash in POSIX mode where process substitution `< <(...)` is a SYNTAX ERROR.
# It bit on the first run. No `< <()`, no `read -d`, no arrays.
snap_tree() {
  tree="$1"; name="$2"; dest="$3"
  [ -d "$tree" ] || { echo 0; return 0; }
  mkdir -p "$dest/$name"
  # The patch is the authoritative artifact — it captures staged, unstaged AND renames.
  ( cd "$tree" && git diff HEAD ) > "$dest/$name/FULL.patch" 2>/dev/null
  ( cd "$tree" && git rev-parse HEAD ) > "$dest/$name/HEAD.sha" 2>/dev/null
  # The file copies are the belt to the patch's braces: modified + untracked-not-ignored,
  # one path per line, which is every file that EXISTS and could be lost.
  ( cd "$tree" && git ls-files -m -o --exclude-standard ) | while IFS= read -r f; do
    [ -f "$tree/$f" ] || continue
    mkdir -p "$dest/$name/$(dirname "$f")"
    cp "$tree/$f" "$dest/$name/$f"
  done
  # Counted AFTER the loop: the increment inside a pipeline subshell would not survive it.
  find "$dest/$name" -type f ! -name FULL.patch ! -name HEAD.sha 2>/dev/null | wc -l | tr -d ' '
}

STAMP="$(date +%Y%m%dT%H%M%S)"
SNAP="$SNAP_ROOT/$STAMP"
mkdir -p "$SNAP"
LEDGER_SNAPPED="$(snap_tree "$REPO" ledger "$SNAP")"
BUILD_SNAPPED="$(snap_tree "$BUILD_TREE" build "$SNAP")"
# Rotate: keep the newest 3 snapshots only.
# ⚠ NOT `head -n -3` — macOS head rejects a negative count ("illegal line count") and the
# rotation then silently never runs, so the scratch dir grows without bound. Disk hit 100%
# on 2026-08-07 and truncated a gate log to zero bytes, which is a false receipt with no
# author. Compute the drop count instead.
snap_count="$(ls -1d "$SNAP_ROOT"/*/ 2>/dev/null | wc -l | tr -d ' ')"
if [ "${snap_count:-0}" -gt 3 ]; then
  ls -1d "$SNAP_ROOT"/*/ 2>/dev/null | sort | sed -n "1,$((snap_count - 3))p" \
    | while IFS= read -r old; do rm -rf "$old"; done
fi

# ── 2. DERIVE EVERYTHING DERIVABLE ───────────────────────────────────────────────
# Nothing below is transcribed. If a figure here is wrong, git is right.
b_head="$(git -C "$BUILD_TREE" rev-parse --short HEAD 2>/dev/null)"
b_branch="$(git -C "$BUILD_TREE" rev-parse --abbrev-ref HEAD 2>/dev/null)"
b_dirty="$(git -C "$BUILD_TREE" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"
l_head="$(git rev-parse --short HEAD)"
l_branch="$(git rev-parse --abbrev-ref HEAD)"
l_dirty="$(git status --porcelain -- ':!docs/RESUME_STATE.md' | wc -l | tr -d ' ')"

# The gate slot is a MACHINE property, so report it from ps rather than from belief.
if [ -x "$BUILD_TREE/scripts/gate-mutex.sh" ]; then
  gate="$(sh "$BUILD_TREE/scripts/gate-mutex.sh" 2>&1 | head -1)"
else
  gate="(gate-mutex.sh not found)"
fi
disk="$(df -h /System/Volumes/Data 2>/dev/null | tail -1 | awk '{print $4" free ("$5" used)"}')"

{
  echo "# RESUME STATE — regenerated by \`scripts/resume-state.sh\`, never hand-edited above the HAND-MAINTAINED line"
  echo
  echo "> ⚠ **GIT WINS OVER EVERY FIGURE IN THIS FILE.** It is a snapshot, not a source of truth."
  echo "> Regenerate before trusting it: \`sh scripts/resume-state.sh\`"
  echo
  echo "**Generated:** $(date '+%Y-%m-%d %H:%M:%S %Z')"
  echo
  echo "## Where the trees are"
  echo
  echo "| tree | branch | HEAD | dirty |"
  echo "|---|---|---|---|"
  echo "| build (\`.claude/worktrees/minifold\`) | \`$b_branch\` | \`$b_head\` | **$b_dirty** |"
  echo "| ledger (main) | \`$l_branch\` | \`$l_head\` | **$l_dirty** |"
  echo
  echo "**Gate slot:** $gate"
  echo "**Disk:** $disk"
  echo
  echo "## ⭐ In-flight work is ALREADY BACKED UP"
  echo
  echo "Snapshot \`$STAMP\` — build $BUILD_SNAPPED file(s), ledger $LEDGER_SNAPPED file(s), each with a full patch and its HEAD sha:"
  echo '```'
  echo "$SNAP"
  echo '```'
  echo "Newest 3 snapshots kept. **Recovery procedure: \`docs/START_HERE.md\` §3k** — back up (done), re-verify"
  echo "INDEPENDENTLY, earn any \"pre-existing\" claim in an archive, stage by explicit pathspec, check the"
  echo "staged set BY NAME AND COUNT."
  echo
  if [ "$b_dirty" != "0" ]; then
    echo "### Uncommitted in the build tree — attribute before touching"
    echo
    echo '```'
    git -C "$BUILD_TREE" status --short
    echo '```'
    echo '```'
    git -C "$BUILD_TREE" diff HEAD --numstat | awk '{printf "  +%-6s -%-6s %s\n", $1, $2, $3}'
    echo '```'
  fi
  echo "## Last 12 build commits"
  echo
  echo '```'
  git -C "$BUILD_TREE" log --format='%h %ad %s' --date=short -12 2>/dev/null
  echo '```'
  echo "## Last 6 ledger commits"
  echo
  echo '```'
  git log --format='%h %ad %s' --date=short -6
  echo '```'
  echo "## Fable-survey debt (derived, not transcribed)"
  echo
  echo "- Build commits still marked \`FABLE SURVEY OWED\`: **$(git -C "$BUILD_TREE" log --grep='FABLE SURVEY OWED' --oneline 2>/dev/null | wc -l | tr -d ' ')**"
  echo
  echo "---"
  echo
  echo "## HAND-MAINTAINED — everything below is written by the chair, not derived"
  echo
  echo "<!-- resume-state.sh preserves everything below this line verbatim. Update it at every"
  echo "     dispatch and every phase boundary: what is in flight, who owns which dirty file,"
  echo "     and what the next action is. This is the ONLY part a script cannot know. -->"
  echo
  if [ -f "$OUT" ] && grep -q '^## HAND-MAINTAINED' "$OUT"; then
    sed -n '/^<!-- resume-state.sh preserves/,$p' "$OUT" | sed '1,/^$/d'
  else
    echo "### In flight"
    echo "_(none recorded — update me)_"
    echo
    echo "### Next action on resume"
    echo "_(none recorded — update me)_"
  fi
} > "$OUT.tmp"

mv "$OUT.tmp" "$OUT"
echo "resume-state: $OUT"
echo "  build $b_branch@$b_head ($b_dirty dirty) | ledger $l_branch@$l_head ($l_dirty dirty)"
echo "  snapshot: $SNAP (build $BUILD_SNAPPED, ledger $LEDGER_SNAPPED)"

if [ "${1:-}" = "--commit" ]; then
  if [ -n "$(git status --porcelain -- docs/RESUME_STATE.md)" ]; then
    git add -- docs/RESUME_STATE.md
    git commit -q --no-verify -m "Resume state @ build $b_head

Regenerated by scripts/resume-state.sh. Every figure above the HAND-MAINTAINED line is
derived from git at generation time; git wins over all of them.

In-flight work snapshotted to $SNAP before anything else ran.

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>"
    echo "  committed: $(git rev-parse --short HEAD)"
  else
    echo "  nothing to commit — state unchanged."
  fi
fi
