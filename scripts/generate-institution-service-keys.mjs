/**
 * Generate the compact institution-service key projection used at store boot.
 *
 * The complete service catalog is a large product vocabulary and belongs to
 * generator/detail surfaces. Persisted toggle migration needs only its ordered
 * institution keys. Emitting those keys from the catalog preserves one
 * authority and, critically, preserves insertion order because fuzzy-match
 * tie-breaking follows the catalog's order.
 *
 * Run with --check in CI-style gates.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'src/data/institutionServices.js');
const outputPath = resolve(
  root,
  'src/data/institutionServiceKeys.generated.js',
);
const checkOnly = process.argv.includes('--check');

const sourceModule = await import(
  `${pathToFileURL(sourcePath).href}?projection=${Date.now()}`
);
const serviceKeys = Object.keys(sourceModule.INSTITUTION_SERVICES || {});

if (serviceKeys.length === 0) {
  throw new Error('institution service key projection: source catalog is empty');
}
if (new Set(serviceKeys).size !== serviceKeys.length) {
  throw new Error(
    'institution service key projection: source catalog contains duplicate keys',
  );
}

const generated =
  `// GENERATED by scripts/generate-institution-service-keys.mjs. Do not edit by hand.\n`
  + `// Order is authoritative: fuzzy service-key tie-breaking follows catalog insertion order.\n\n`
  + `export const INSTITUTION_SERVICE_KEYS = Object.freeze(${
    JSON.stringify(serviceKeys, null, 2)
  });\n`;

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => null);
  if (current !== generated) {
    throw new Error(
      'institution service key projection is stale; run '
      + '`npm run gen:institution-service-keys`.',
    );
  }
  console.log(
    `[institution-service-keys] verified ${serviceKeys.length} ordered keys`,
  );
} else {
  await writeFile(outputPath, generated);
  console.log(
    `[institution-service-keys] wrote ${serviceKeys.length} ordered keys`,
  );
}
