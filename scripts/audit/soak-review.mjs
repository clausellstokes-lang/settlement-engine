#!/usr/bin/env node
/**
 * scripts/audit/soak-review.mjs — THE SOAK BATTERY (lane SOAK-1000, 2026-11-03).
 *
 * The owner, 2026-11-03: "run 1000 generated settlements and review each in depth and in
 * aggregate and tune" · "then do it at 10,000" · "After 10,000 do 100,000 …" · "Also look at
 * the distribution of every aspect in each of these both individually and in relationship to
 * other facts of the dossier and tune". One script for every rung.
 *
 *   node scripts/audit/soak-review.mjs --count 1000 --workers 4 --out artifacts/soak-1000
 *        [--rendered-subset 1] [--resume] [--from 0]
 *
 * Settlement i is seed `soak1k-<i>` with the config `soak-review/corpus.mjs :: cellFor(i)`, so
 * any one is regenerated by its index alone. Each worker takes the indices ≡ w (mod K), writes
 * one line per settlement to `<out>/shards/shard-<w>.jsonl` as it goes, and on `--resume`
 * skips every index already on disk. Settlements are never written; only findings, roll-ups,
 * flattened facts and (for the chair's read) sixty plain-text dossiers under `<out>/sample/`.
 *
 * Outputs: findings.jsonl · settlements.jsonl · features.jsonl · sentences.json ·
 * aggregates/*.{json,md} · sample/<seed>.txt · run.json.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, appendFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { execFileSync } from 'node:child_process';

const SELF = fileURLToPath(import.meta.url);

function parseArgs(argv) {
  const o = { count: 1000, workers: 4, out: 'artifacts/soak-1000', renderedSubset: 1, resume: false, from: 0 };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--count') o.count = Number(argv[++i]);
    else if (a === '--workers') o.workers = Number(argv[++i]);
    else if (a === '--out') o.out = argv[++i];
    else if (a === '--rendered-subset') o.renderedSubset = Number(argv[++i]);
    else if (a === '--resume') o.resume = true;
    else if (a === '--from') o.from = Number(argv[++i]);
    else throw new Error(`unknown argument ${a}`);
  }
  if (!(o.count > 0) || !(o.workers > 0) || !(o.renderedSubset >= 0 && o.renderedSubset <= 1)) throw new Error('bad arguments');
  return o;
}

/** Is index i rendered at this subset fraction? Deterministic: an even stride. */
export const isRendered = (i, f) => f >= 1 || (f > 0 && i % Math.round(1 / f) === 0);

/** The chair's read: ten per tier, evenly spaced (every 100th once a tier holds 1,000+). */
export function sampleStride(count) { return Math.max(1, Math.min(100, Math.floor(count / 6 / 10))); }
export function isSampled(i, count, tierCount = 6) {
  const p = Math.floor(i / tierCount); const stride = sampleStride(count);
  return p % stride === 0 && p / stride < 10;
}

// ─────────────────────────────── worker ───────────────────────────────
async function runWorker({ indices, out, w, renderedSubset, count }) {
  const { birth, ensureLaws, sha } = await import('./soak-review/corpus.mjs');
  const { reviewSettlement } = await import('./soak-review/checks.mjs');
  const { walkRecord, chainFacts } = await import('./soak-review/features.mjs');
  const { sentencesOf } = await import('./soak-review/checks.mjs');
  const { normalizeRenderedSentence } = await import('./phrase-repetition.mjs');
  await ensureLaws();
  const needRender = indices.some((i) => isRendered(i, renderedSubset) || isSampled(i, count));
  const H = needRender ? await import('./soak-review/renderHarness.mjs') : null;
  const harness = needRender ? await H.bootHarness() : null;
  // ⚠ appendFileSync, never a write stream: this loop never yields, so a stream would not even
  // open until the end, and a cut run would leave nothing on disk to resume from.
  const shardPath = join(out, 'shards', `shard-${w}.jsonl`);
  const seenText = new Set();
  let done = 0;
  for (const i of indices) {
    let line;
    try {
      const b = birth(i);
      const s = b.settlement;
      let replay = null;
      if (i % 100 === 0) replay = sha(birth(i).settlement) === sha(s);
      const rendered = isRendered(i, renderedSubset) || isSampled(i, count);
      const r = rendered ? H.renderSurfaces(harness, s) : null;
      const findings = reviewSettlement(s, b.config, r);
      if (replay === false) findings.push({ check: 'cert:replay_mismatch', surface: 'record', quote: '', detail: 'same seed, different bytes' });
      // corpus repetition: every screen sentence, exact and with this place's own names masked
      const sentences = [];
      const texts = {};
      if (r) {
        const names = [s.name, ...(s.npcs || []).map((n) => n?.name), ...(s.powerStructure?.factions || []).map((f) => f?.faction ?? f?.name)]
          .filter((n) => typeof n === 'string' && n.length > 2).sort((a, z) => z.length - a.length);
        const screen = [...Object.values(r.tabs), r.tonight].join('\n');
        for (const sent of new Set(sentencesOf(screen).filter((x) => x.split(/\s+/).length >= 6).map(normalizeRenderedSentence))) {
          let skel = sent;
          for (const n of names) skel = skel.split(n.toLowerCase()).join('@');
          skel = skel.replace(/\d[\d,.]*/g, '#');
          const h = sha(skel);
          sentences.push(h);
          if (!seenText.has(h)) { seenText.add(h); texts[h] = skel.slice(0, 300); }
        }
      }
      const features = walkRecord(s);
      const chains = chainFacts(s, { stressCell: b.stressCell, findings });
      line = {
        i, seed: b.seed, tier: s.tier, population: s.population, stressCell: b.stressCell, matrix: b.matrix,
        hashes: { record: sha(s), config: sha(b.config) }, rendered, replay,
        findings, chains, features, sentences, texts,
      };
      if (isSampled(i, count) && r) {
        const body = [
          `${s.name} — ${s.tier}, ${s.population} people · seed ${b.seed} · stress ${b.stressCell}`,
          `config ${JSON.stringify(b.matrix)}`, '',
          ...Object.entries(r.tabs).map(([tab, text]) => `════ ${tab.toUpperCase()} ════\n${text}\n`),
          `════ TONIGHT ════\n${r.tonight}\n`, `════ PDF TEXT ════\n${r.pdf}\n`, `════ FOUNDRY JOURNAL ════\n${r.foundry}\n`,
        ].join('\n');
        writeFileSync(join(out, 'sample', `${b.seed}.txt`), body);
      }
    } catch (error) {
      line = { i, seed: `soak1k-${i}`, error: String(error?.stack ?? error).slice(0, 1200), findings: [{ check: 'cert:generation_error', surface: 'record', quote: '', detail: String(error?.message ?? error).slice(0, 300) }] };
    }
    appendFileSync(shardPath, `${JSON.stringify(line)}\n`);
    done += 1;
    if (done % 25 === 0) parentPort.postMessage({ w, done });
  }
  if (harness) await harness.server.close();
  parentPort.postMessage({ w, done, finished: true });
}

// ─────────────────────────────── main ───────────────────────────────
function doneIndices(out) {
  const dir = join(out, 'shards');
  const set = new Set();
  if (!existsSync(dir)) return set;
  for (const f of readdirSync(dir)) {
    for (const l of readFileSync(join(dir, f), 'utf-8').split('\n')) {
      if (!l) continue;
      try { set.add(JSON.parse(l).i); } catch { /* a torn last line is redone */ }
    }
  }
  return set;
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  const out = resolve(o.out);
  for (const d of ['shards', 'sample', 'aggregates']) mkdirSync(join(out, d), { recursive: true });
  const done = o.resume ? doneIndices(out) : new Set();
  if (!o.resume && existsSync(join(out, 'shards')) && readdirSync(join(out, 'shards')).length) throw new Error(`${out}/shards is not empty: pass --resume or a fresh --out`);
  const todo = [];
  for (let i = o.from; i < o.count; i += 1) if (!done.has(i)) todo.push(i);
  const started = Date.now();
  console.log(`[soak-review] ${todo.length} to run (${done.size} on disk) with ${o.workers} workers → ${out}`);
  const per = Array.from({ length: o.workers }, () => []);
  todo.forEach((i, k) => per[k % o.workers].push(i));
  const shardBase = o.resume ? readdirSync(join(out, 'shards')).length : 0;
  let total = 0;
  await Promise.all(per.map((indices, w) => new Promise((ok, fail) => {
    if (!indices.length) { ok(); return; }
    const worker = new Worker(SELF, { workerData: { indices, out, w: shardBase + w, renderedSubset: o.renderedSubset, count: o.count } });
    worker.on('message', (m) => { if (m.finished) return; total += 25; if (total % 100 === 0) console.log(`[soak-review] ${total}/${todo.length} · ${Math.round((Date.now() - started) / 1000)}s`); });
    worker.on('error', fail);
    worker.on('exit', (code) => (code === 0 ? ok() : fail(new Error(`worker ${w} exit ${code}`))));
  })));
  const { aggregate } = await import('./soak-review/aggregate.mjs');
  let tip = 'unknown';
  try { tip = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf-8' }).trim(); } catch { /* no git */ }
  const summary = aggregate(out, { count: o.count, tip, durationMs: Date.now() - started, args: o });
  console.log(`[soak-review] done in ${Math.round((Date.now() - started) / 1000)}s: ${summary.settlements} settlements, ${summary.findings} findings, ${summary.errors} errors · ${summary.verdict}`);
}

if (!isMainThread) {
  runWorker(workerData).catch((e) => { console.error(e); process.exit(1); });
} else if (process.argv[1] && resolve(process.argv[1]) === SELF) {
  main().catch((e) => { console.error('[soak-review] fatal:', e); process.exitCode = 1; });
}
