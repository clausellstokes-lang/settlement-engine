import { readFileSync, writeFileSync } from 'node:fs';
const R = JSON.parse(readFileSync('report.json', 'utf8'));
const hi = R.outliers.filter((o) => o.dir !== 'low');
hi.sort((a, b) => (b.ratio === null ? 1e9 : b.ratio) - (a.ratio === null ? 1e9 : a.ratio));
const lo = R.outliers.filter((o) => o.dir === 'low');
lo.sort((a, b) => a.ratio - b.ratio);
const out = [];
out.push('');
out.push('---');
out.push('');
out.push('## 6. (d) EVERY METRIC WHERE A REGISTER IS AN OUTLIER BY MORE THAN DOUBLE THE CORPUS MEDIAN');
out.push('');
out.push('The median is taken across the nineteen register columns (A-W, the control, is excluded;');
out.push('so are size-scaled counts, which say only that a register is large). Both directions are');
out.push(`reported: **${hi.length} high** (> 2x median) and **${lo.length} low** (< 0.5x median).`);
out.push('');
out.push('### HIGH — above double the median');
out.push('');
out.push('| x median | register | metric | value | median |');
out.push('|---:|---|---|---:|---:|');
for (const o of hi) out.push(`| ${o.ratio === null ? '∞ (median 0)' : o.ratio + 'x'} | ${o.register} | ${o.metric} | ${o.value} | ${o.median} |`);
out.push('');
out.push('### LOW — below half the median');
out.push('');
out.push('| x median | register | metric | value | median |');
out.push('|---:|---|---|---:|---:|');
for (const o of lo) out.push(`| ${o.ratio}x | ${o.register} | ${o.metric} | ${o.value} | ${o.median} |`);
writeFileSync('/tmp/s6.md', out.join('\n') + '\n');
console.log('high', hi.length, 'low', lo.length);
