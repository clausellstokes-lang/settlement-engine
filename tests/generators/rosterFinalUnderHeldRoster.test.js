const GOLDEN_MANIFEST = resolve(process.cwd(), 'tests', 'fixtures', 'generator-golden-master.json');
const SEED = 'em-r2-roster-final';
const CONFIG = {
  settType: 'town',
  culture: 'germanic',
  terrainOverride: 'riverside',
  tradeRouteAccess: 'river',
  monsterThreat: 'civilized',
};
/** The record paths `generatePopulation` provides. The runner refuses a PARTIAL pin, so a bag
 *  that holds the roster holds all four (`pipeline.js :: runPipeline`'s chooser rule). */
const POPULATION_KEYS = ['npcs', 'relationships', 'factions', 'conflicts'];
/** The coherence tail's five child streams, in the order `generateCoherence` forks them. */
const COHERENCE_LABELS = [
  'npc-enrichment', 'historical-character', 'prominent-relationship',
  'coherence-notes', 'siege-capability',
];
/** The label the held roster retires. Read from the register in A7, spelled here for the forks. */
const HELD_ROSTER_LABEL = 'npc-enrichment';
/** A sibling label that travels the SAME fork path, so an absence cannot pass vacuously. */
const ANCHOR_LABEL = 'prominent-relationship';
/** Planted by the arms; it appears nowhere in the generator's own vocabulary. */
const SENTINEL_ROLE = 'EM-R2 SENTINEL SEAT';
const SENTINEL_TITLE = 'EM-R2 SENTINEL TITLE';
/** The synthesised office-holder's own stamp (`factionRoles.js :: ensureFactionStructuralNpcs`). */
const STRUCTURAL_STAMP = 'faction_structural';

/** The golden master's own hash, spelled exactly as `generatorGoldenMaster.test.js` spells it. */
function hashFor(config) {
  const { _seed, ...cfg } = config;
  const settlement = generateSettlementPipeline(cfg, null, { seed: _seed, customContent: {} });
  return createHash('sha256').update(JSON.stringify(settlement)).digest('hex');
}

/** The initial context `generateSettlementPipeline` builds, so a direct runner call is honest. */
function initialContextFor(seed) {
  return {
    config: resolveConfigWithUserContentTunables({ ...CONFIG }, {}),
    importedNeighbour: null,
    _seed: seed,
    _traceClock: 0,
  };
}

/** Run the REAL registered pipeline headlessly, with an optional pins bag. */
function runHeadless(rng, options = {}) {
  return withCustomContent({}, () => runPipeline(initialContextFor(SEED), rng, options));
}

/** Every chooser of `generatePopulation`, pinned from a run's own record. */
function pinsFromContext(ctx) {
  const bag = {};
  for (const key of POPULATION_KEYS) bag[key] = ctx[key];
  return bag;
}

/**
 * A coherence RNG whose FORKS are observable: every child stream is proxied, so the labels
 * forked and the raw draws taken under each label are both measured. A stream that is never
 * forked leaves no label and no count, which is exactly what a skipped producer looks like.
 */
function forkRecorder(seed) {
  const base = createPRNG(`${seed}::canonical-coherence`);
  const record = { labels: [], draws: {} };
  const proxyChild = (child, label) => {
    const proxy = {};
    for (const key of Object.keys(child)) {
      const value = child[key];
      if (typeof value !== 'function') proxy[key] = value;
      else proxy[key] = (...args) => { record.draws[label] += 1; return value(...args); };
    }
    return proxy;
  };
  const rng = {
    ...base,
    fork: (label) => {
      record.labels.push(label);
      record.draws[label] = 0;
      return proxyChild(base.fork(label), label);
    },
  };
  return { rng, record };
}

/** The four sibling outputs A3 holds byte-identical, read off one `generateCoherence` result. */
function siblingOutputs(out) {
  return JSON.stringify({
    prominentRelationship: out.prominentRelationship,
    coherenceNotes: out.coherenceNotes,
    historicalCharacter: out.history?.historicalCharacter,
    siegeNarrative: out.history?.siegeNarrative,
  });
}

/** The faction-linkage trace entry `generatePopulation` records, or `null` when none was. */
function linkageTrace(ctx) {
  const rows = Array.isArray(ctx.simulationTrace) ? ctx.simulationTrace : [];
  return rows.find((row) => row?.targetId === 'factions.npcGroupLinkage') || null;
}

describe('EM-R2 — the roster is final inside enrichNpcCoherence under a held roster', () => {
  it('A1 — inert with no pins: the golden corpus and the coherence tail are byte-unmoved', () => {
    // (1) THE COMMITTED FIXTURE is the authority: a stride of the golden master's own corpus,
    // hashed the way `generatorGoldenMaster.test.js` hashes it. A byte this member moved on the
    // unpinned path reds here.
    const rows = goldenCorpus();
    const manifest = JSON.parse(readFileSync(GOLDEN_MANIFEST, 'utf-8'));
    const stride = Math.max(1, Math.floor(rows.length / 40));
    const moved = [];
    let checked = 0;
    for (let index = 0; index < rows.length; index += stride) {
      const row = rows[index];
      checked += 1;
      if (manifest[keyOf(row)] !== hashFor(row)) moved.push(keyOf(row));
    }
    expect(checked).toBeGreaterThanOrEqual(40);
    expect(moved, 'a golden row moved with no pin bag anywhere').toEqual([]);

    // (2) THE NEW PARAMETER IS INERT WHEN ABSENT OR NULL, at the seam itself.
    const settlement = generateSettlementPipeline({ ...CONFIG }, null, {
      seed: SEED, customContent: {},
    });
    const arity = generateCoherence(structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'));
    const explicitNull = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'), null,
    );
    expect(JSON.stringify(explicitNull.npcs)).toBe(JSON.stringify(arity.npcs));
    expect(JSON.stringify(explicitNull.factions)).toBe(JSON.stringify(arity.factions));

    // (3) THE COUNTERFORCE (§P6). This arm's claim holds at the base, so it is proved by a
    // PERTURBED INPUT rather than red-first: the same comparison against a planted pin must
    // DIFFER. An arm that cannot tell a held roster from an unheld one proves nothing here.
    const planted = structuredClone(settlement.npcs || []).slice(0, 1)
      .map((npc) => ({ ...npc, role: SENTINEL_ROLE }));
    const pinned = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'),
      { ...pinsFromContext(settlement), npcs: planted },
    );
    expect(JSON.stringify(pinned.npcs) === JSON.stringify(arity.npcs),
      'the counterforce is vacuous: a planted pin produced the unpinned roster').toBe(false);
  }, 600_000);

  it('A2 — the skip and its site: a held roster returns itself and never forks npc-enrichment', () => {
    const settlement = generateSettlementPipeline({ ...CONFIG }, null, {
      seed: SEED, customContent: {},
    });
    // THE PIN IS DELIBERATELY ALTERED (§9a rule 2). A pin equal to the record's own roster is
    // satisfied by the enrichment's own output on many rows; only an altered roster tells a
    // gated producer from an ungated one.
    const held = structuredClone(settlement.npcs || []).map((npc, index) => (
      index === 0 ? { ...npc, role: SENTINEL_ROLE, title: SENTINEL_TITLE } : npc
    ));
    expect(held.length, 'the fixture roster is live').toBeGreaterThan(0);

    const unpinned = forkRecorder(SEED);
    const before = generateCoherence(structuredClone(settlement), unpinned.rng);
    // THE ANTI-VACUITY READING: at the base the enrichment runs unconditionally, so this label
    // IS forked and this count IS nonzero. That is the state the gate has to change.
    expect(unpinned.record.labels).toEqual(COHERENCE_LABELS);
    expect(unpinned.record.draws[HELD_ROSTER_LABEL],
      'the unpinned enrichment draws on its own child stream').toBeGreaterThan(0);

    const gated = forkRecorder(SEED);
    const after = generateCoherence(structuredClone(settlement), gated.rng, {
      ...pinsFromContext(settlement), npcs: held,
    });

    expect(JSON.stringify(after.npcs), 'the held roster is the roster that comes back')
      .toBe(JSON.stringify(held));
    expectAbsentWithAnchor(gated.record.labels, HELD_ROSTER_LABEL, ANCHOR_LABEL,
      'A2: a gated producer never forks its named child stream');
    expect(gated.record.draws[HELD_ROSTER_LABEL],
      'a skipped child stream takes no draw at all').toBeUndefined();
    // The other four are forked in the same order and take the SAME counts, which is A3's
    // subject and is re-asserted here so this arm cannot pass by having broken them.
    expect(gated.record.labels).toEqual(COHERENCE_LABELS.filter((l) => l !== HELD_ROSTER_LABEL));
    const sameCounts = COHERENCE_LABELS
      .filter((label) => label !== HELD_ROSTER_LABEL)
      .map((label) => [label, unpinned.record.draws[label], gated.record.draws[label]]);
    expect(sameCounts.filter(([, u, g]) => u !== g), 'a sibling stream moved').toEqual([]);
    expect(before.prominentRelationship).toBeDefined();
  }, 600_000);

  it('A3 — the four sibling streams are unmoved, and a parent draw is the control that moves one', () => {
    const settlement = generateSettlementPipeline({ ...CONFIG }, null, {
      seed: SEED, customContent: {},
    });
    const held = structuredClone(settlement.npcs || []).map((npc, index) => (
      index === 0 ? { ...npc, role: SENTINEL_ROLE } : npc
    ));
    const plain = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'),
    );
    const withHeld = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'),
      { ...pinsFromContext(settlement), npcs: held },
    );
    // ANTI-VACUITY FIRST: the roster really was HELD in that run. Two runs that both enrich
    // are trivially identical, so without this the sibling comparison below proves nothing.
    expect(JSON.stringify(withHeld.npcs), 'the run this arm compares did not hold the roster')
      .toBe(JSON.stringify(held));
    expect(siblingOutputs(withHeld), 'a sibling coherence output moved under a held roster')
      .toBe(siblingOutputs(plain));

    // THE FORK LAW, EXECUTED (`src/kernel/prng.js :: fork`): a fork is a pure function of
    // (seed, label), so a child that is never created cannot move a sibling.
    const first = createPRNG(SEED).fork(ANCHOR_LABEL).random();
    const afterSkippedSibling = (() => {
      const parent = createPRNG(SEED);
      parent.fork(HELD_ROSTER_LABEL);
      return parent.fork(ANCHOR_LABEL).random();
    })();
    expect(afterSkippedSibling, 'forking a sibling moved the fork this arm measures').toBe(first);

    // THE CONTROL THAT CAN SEE A MOVED STREAM (§9a rule 3). A PARENT DRAW does move the
    // parent's next value, so an instrument that reported "unmoved" for everything would red.
    const drawn = (() => {
      const parent = createPRNG(SEED);
      parent.random();
      return parent.fork(ANCHOR_LABEL).random();
    })();
    const parentSequence = (() => {
      const parent = createPRNG(SEED);
      return [parent.random(), parent.random()];
    })();
    expect(parentSequence[1] === parentSequence[0],
      'the control is vacuous: the parent stream repeats its own value').toBe(false);
    expect(typeof drawn).toBe('number');
  }, 600_000);

  it('A4 — the mirror always runs: a held roster carries its edit into every member chip', () => {
    const settlement = generateSettlementPipeline({ ...CONFIG }, null, {
      seed: SEED, customContent: {},
    });
    const chipIds = (settlement.factions || [])
      .flatMap((faction) => (Array.isArray(faction.members) ? faction.members : []))
      .map((member) => member?.id)
      .filter(Boolean);
    const rosterIds = new Set((settlement.npcs || []).map((npc) => npc?.id));
    const targetId = chipIds.find((id) => rosterIds.has(id));
    expect(targetId, 'the fixture carries a member chip whose id is in the roster').toBeDefined();

    const held = structuredClone(settlement.npcs || []).map((npc) => (
      npc?.id === targetId ? { ...npc, role: SENTINEL_ROLE, title: SENTINEL_TITLE } : npc
    ));
    const out = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'),
      { ...pinsFromContext(settlement), npcs: held },
    );
    const carried = (out.factions || [])
      .flatMap((faction) => (Array.isArray(faction.members) ? faction.members : []))
      .filter((member) => member?.id === targetId);
    expect(carried.length, 'the mirror kept the chip this arm edits').toBeGreaterThan(0);
    expect(carried.filter((member) => member.role !== SENTINEL_ROLE),
      'a member chip did not follow the held roster: the mirror was gated').toEqual([]);

    // THE POSITIVE CONTROL: the chip a GATED mirror would leave behind still reads the
    // pre-edit role, so "it carries the edit" is a measurement and not a tautology.
    const stale = (settlement.factions || [])
      .flatMap((faction) => (Array.isArray(faction.members) ? faction.members : []))
      .filter((member) => member?.id === targetId);
    expect(stale.filter((member) => member.role === SENTINEL_ROLE),
      'the control is vacuous: the pre-edit chip already carried the sentinel').toEqual([]);
  }, 600_000);

  it('A5 — the appender must not add: a held roster short an office-holder stays exactly as held', () => {
    const record = runHeadless(createPRNG(SEED));
    const roster = record.npcs || [];
    expect(roster.length, 'the unpinned run produced a roster').toBeGreaterThan(1);

    // AN UNCOVERED ROSTER (§9a rule 1). At this tip the appender adds +0 to a covered roster,
    // so an arm that only asserts "the roster did not grow" would pass against a member that
    // did nothing at all. The control below shows this roster is genuinely uncovered.
    const short = structuredClone(roster).slice(0, 1);
    const control = ensureFactionStructuralNpcs(
      { ...structuredClone(record.settlement), npcs: structuredClone(short) },
      record.generationContext,
    );
    const mintedUnpinned = (control.npcs || []).filter((npc) => npc?.generatedAs === STRUCTURAL_STAMP);
    expect(mintedUnpinned.length,
      'the control is vacuous: the appender adds nothing to this roster even unheld')
      .toBeGreaterThan(0);

    const heldRun = runHeadless(createPRNG(SEED), {
      pins: { ...pinsFromContext(record), npcs: short },
    });
    const finalRoster = heldRun.settlement?.npcs || [];
    expect(finalRoster.length, 'the roster grew under a held key').toBe(short.length);
    expect(finalRoster.filter((npc) => npc?.generatedAs === STRUCTURAL_STAMP),
      'an office-holder was minted into a roster the record calls final').toEqual([]);
  }, 900_000);

  it('A6 — the linkage-only outputs are retired while the trace keeps its own category index', () => {
    const record = runHeadless(createPRNG(SEED));
    const groups = record.factions || [];
    expect(groups.length, 'the unpinned run produced npc faction groups').toBeGreaterThan(0);
    // LIVENESS: the unpinned run DOES link, so "nothing was linked" below is a measurement.
    expect(groups.filter((group) => group?.powerFactionName).length,
      'the unpinned linkage stamped no group: the control cannot see a live linkage')
      .toBeGreaterThan(0);

    // (1) THE RETIREMENT ITSELF, AT THE SEAM. The four linkage-only outputs (`pfList`,
    // `governingPF`, `pfAttractionMap`, `totalPower`) are built by `powerLinkage`, and the
    // SPLIT is exactly that its one call site moved INSIDE the `factions` draw thunk while the
    // category index the trace reads stayed OUTSIDE it. A held key never enters the thunk, so
    // the position of those two calls IS the retirement; the behaviour halves below cannot see
    // it, because a dead object nobody reads leaves no trace in the output.
    const stepSource = readFileSync(
      resolve(process.cwd(), 'src', 'generators', 'steps', 'generatePopulation.js'), 'utf-8',
    );
    const thunkStart = stepSource.indexOf("chooseOrPin(pins, 'factions'");
    const nextChooser = stepSource.indexOf("chooseOrPin(pins, 'conflicts'");
    expect(thunkStart, 'the factions chooser is where this arm says it is').toBeGreaterThan(0);
    expect(nextChooser, 'the next chooser bounds the thunk').toBeGreaterThan(thunkStart);
    const indexSite = stepSource.indexOf('powerFactionsByCategory(powerStructure');
    // The CALL, not the declaration: `indexOf('powerLinkage(')` alone finds the `function`
    // line and would report the retirement from the wrong site.
    const linkageSite = stepSource.indexOf('const power = powerLinkage(');
    expect(indexSite, 'the category index the trace reads is built at all').toBeGreaterThan(0);
    expect(indexSite, 'the category index is built OUTSIDE the draw thunk').toBeLessThan(thunkStart);
    expect(linkageSite, 'the four linkage-only lookups are built INSIDE the draw thunk')
      .toBeGreaterThan(thunkStart);
    expect(linkageSite, 'and inside THIS thunk, not a later one').toBeLessThan(nextChooser);

    // (2) WITH THE GROUPS HELD, `linkFactions` NEVER RUNS. Held groups stripped of the
    // linkage's own stamps come back still stripped.
    const stripped = structuredClone(groups).map((group) => {
      const { powerFactionName, powerFactionPower, powerFactionCat, powerFactionFallback, ...rest } = group;
      return rest;
    });
    const strippedRun = runHeadless(createPRNG(SEED), {
      pins: { ...pinsFromContext(record), factions: stripped },
    });
    const strippedOut = strippedRun.factions || [];
    expect(strippedOut.length).toBe(stripped.length);
    expect(strippedOut.filter((group) => group?.powerFactionName),
      'a held group was re-linked: the dead run is still running').toEqual([]);

    // (3) AND THE TRACE'S OWN CLASSIFIER IS UNMOVED, BOTH DIRECTIONS. The category index the
    // classifier reads is built OUTSIDE the chooser, so a held roster keeps the direct /
    // attraction / scatter reading it had. A whole-`powerLinkage` retirement would throw here.
    const heldRun = runHeadless(createPRNG(SEED), { pins: pinsFromContext(record) });
    const plainTrace = linkageTrace(record);
    const heldTrace = linkageTrace(heldRun);
    expect(plainTrace, 'the unpinned run recorded the faction-linkage trace').toBeTruthy();
    expect(heldTrace, 'the held run recorded the faction-linkage trace').toBeTruthy();
    expect(heldTrace.causes[0].reason, 'the linkage classification moved under a held roster')
      .toBe(plainTrace.causes[0].reason);
    expect(heldTrace.result).toBe(plainTrace.result);
  }, 900_000);

  it('A7 — the class register is the source: the gated key and the ungated mirror are imported', () => {
    // THE KEYS ARE READ FROM THE REGISTER, never re-typed (`recordRegister.js`, EM-R0a).
    const heldKeys = Object.keys(RECORD_CLASSES).filter((key) => RECORD_CLASSES[key] === 'HELD');
    expect(heldKeys, 'the roster is a HELD key of the record').toContain('npcs');
    expect(RECORD_CLASSES.npcs).toBe('HELD');
    expect(CLASS_EXCEPTIONS['factions[].members[]']).toBe('MIRROR');

    const settlement = generateSettlementPipeline({ ...CONFIG }, null, {
      seed: SEED, customContent: {},
    });
    const gatedKey = heldKeys.find((key) => key === 'npcs');
    const held = structuredClone(settlement.npcs || []).map((npc, index) => (
      index === 0 ? { ...npc, role: SENTINEL_ROLE } : npc
    ));
    const byRegister = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'),
      { ...pinsFromContext(settlement), [gatedKey]: held },
    );
    expect(JSON.stringify(byRegister.npcs), 'the register-named key did not gate the producer')
      .toBe(JSON.stringify(held));

    // THE PERTURBED-INPUT COUNTERFORCE (§P6). This arm's register readings hold at the base, so
    // it is proved by perturbing the key: a bag that holds every OTHER chooser but not the
    // register's HELD roster key must let the producer run and return its own roster.
    const withoutRoster = { ...pinsFromContext(settlement) };
    delete withoutRoster[gatedKey];
    const perturbed = generateCoherence(
      structuredClone(settlement), createPRNG(SEED).fork('canonical-coherence'), withoutRoster,
    );
    expect(JSON.stringify(perturbed.npcs) === JSON.stringify(held),
      'the counterforce is vacuous: an unheld roster returned the planted one').toBe(false);
    // And the MIRROR is never gated by any of it: the chips still follow whatever roster ran.
    expect(Array.isArray(perturbed.factions) || perturbed.factions === undefined).toBe(true);
  }, 600_000);
});
