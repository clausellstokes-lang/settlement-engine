/**
 * rosterFinalUnderHeldRoster.test.js — EM-R2's acceptance battery (A1-A7).
 *
 * THE BEHAVIOUR. Under a HELD roster the roster the record carries is the roster the
 * re-derivation returns: `enrichNpcCoherence` does not run and its `npc-enrichment` child
 * stream is never forked (A2), the four sibling coherence streams are byte-unmoved (A3), the
 * `factions[].members[]` MIRROR still follows the held roster (A4), `ensureFactionStructuralNpcs`
 * appends nothing (A5), and `powerLinkage`'s four linkage-only outputs are never built while the
 * trace's own category index still is (A6). With no pins, not one generated byte moves (A1).
 *
 * WHY THE SKIP IS LAWFUL HERE AND NOWHERE ELSE IN ASSEMBLY. `src/kernel/prng.js`'s `fork` is
 * `createPRNG` over `${seed}::${label}` — a pure function of (seed, label) — so a child stream
 * that is never created cannot move any sibling. A3 executes that law and carries a PARENT draw
 * as the control that CAN see a moved stream. A writer on the step's SHARED ambient stream
 * (`generateSettlementName`) would have to consume and discard instead, which is why design
 * §22.1 correction 1 admits a skip only inside a named child stream.
 *
 * ⛔ THREE CONSTRUCTION RULES (packet §7's CREATE row):
 *   1. `it`, `test` and `describe` are bound EXACTLY ONCE each and never re-bound, not even as
 *      an arrow parameter: the sovereignty-lighting census parks a whole file for that alone.
 *      Registration is straight-line — seven literal `it`s under ONE literal `describe`.
 *   2. Every asserted set is IMPORTED (`RECORD_CLASSES`, `CLASS_EXCEPTIONS`, `goldenCorpus`)
 *      and every record is DERIVED by running the real generator, never a local literal copy
 *      (`tests/lint/contractTestAntiVacuity.walker.test.js` Rule 2).
 *   3. No bare seed loop: a loop collects, and the arm asserts once outside it.
 *
 * ⚠ A1 AND A7 ARE WRITTEN-CONTRACT ARMS (§P6): their claims hold at the base, so each carries
 * its own measured counterforce inside the arm rather than a red-first.
 */
