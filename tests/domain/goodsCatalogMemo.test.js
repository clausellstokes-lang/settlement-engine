/**
 * tests/domain/goodsCatalogMemo.test.js — perf-advance surface fix (goodsCatalog).
 *
 * normalizeGood's fuzzy fallback is on the per-tick hot path (the regional
 * graph normalizes every settlement's trade lists every kernel tick), so
 * fuzzyMatch (1) tokenizes the static catalog ONCE (FUZZY_CANDIDATES) and
 * (2) memoizes results per comparable-label key (FUZZY_MEMO, misses included,
 * bounded). The cache must be INVISIBLE: identical results for identical
 * inputs, fresh result objects every call, no drift after the memo's bound
 * clears. These tests pin that equivalence contract.
 *
 * ⛔⛔ WHY THIS FILE CARRIES A DISCRIMINATING GUARD, AND WHY IT MUST KEEP ONE.
 * The two-part memoization above landed 2026-07-02, survived to 07-05, and was
 * DESTROYED on 2026-07-15 by a master-merge resolution that took the memo-less
 * parent (568 conflicts). THIS FILE SURVIVED THAT MERGE BYTE-IDENTICALLY, and
 * for six weeks its header described a cache the module no longer had. Nothing
 * reported the loss, because the five equivalence titles below are — correctly
 * and by design — EQUIVALENCE pins: every one of them PASSES against an
 * un-memoized matcher (measured, 5/5, against a git archive of the pre-cure
 * base). They can prove the cache is invisible; they cannot prove it EXISTS.
 * That is the vacuous-pin class, and it is why a ~5x per-tick regression lived
 * unreported until a performance audit went looking.
 *
 * The last test in this file is the answer: it is the one arm here that would
 * have gone RED at the destroying merge. It pushes an alias onto a catalog
 * entry at runtime and then resolves a label the memo has NEVER seen — a
 * re-tokenizing matcher reads the mutation and moves; a matcher holding a
 * module-init snapshot does not. Keep it last (it mutates shared module state
 * and restores it in a `finally`), and keep its probe label memo-COLD: resolve
 * that label before the push and FUZZY_MEMO answers from cache, which would
 * make the arm pass with FUZZY_CANDIDATES deleted.
 */

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, test } from 'vitest';

import { normalizeGood, normalizeGoodsList } from '../../src/domain/region/goodsCatalog.js';

// The PRE-FEATURE golden: generated by running this corpus through a `git archive`
// of the pre-cure module, so it cannot mirror the code it pins. Regenerating it
// from the cured tree destroys its only property.
const FIXTURE = JSON.parse(readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), '../fixtures/goods-matcher-identity-corpus.json'),
  'utf8',
));

describe('goodsCatalog — fuzzyMatch memo is behavior-invisible', () => {
  test('exact, fuzzy, custom, and empty labels resolve identically across repeated calls', () => {
    const labels = [
      'Bulk grain and foodstuffs', // exact alias → grain
      'fresh river fish', // fuzzy (no verbatim alias) → fish
      'salted fish barrels', // fuzzy → fish
      'Dragon-scale kites', // no match → custom
      'Weapons and armour (ceremonial)', // annotation-stripped exact → arms
      '', // empty → null
      null, // null → null
    ];
    const first = labels.map(l => normalizeGood(l));
    const second = labels.map(l => normalizeGood(l));
    expect(second).toEqual(first);
    expect(first.map(g => g?.id ?? null)).toEqual([
      'grain', 'fish', 'fish', 'custom.dragon_scale_kites', 'arms', null, null,
    ]);
  });

  test('memoized fuzzy hits still return FRESH objects — a caller mutation cannot poison later calls', () => {
    const a = normalizeGood('fresh river fish');
    expect(a.id).toBe('fish');
    const b = normalizeGood('fresh river fish');
    expect(b).not.toBe(a);
    expect(b).toEqual(a);

    // Tamper with one result; the next call must be pristine.
    a.criticality = 999;
    a.label = 'tampered';
    a.aliases.length && a.aliases.push('tampered-alias');
    const c = normalizeGood('fresh river fish');
    expect(c.id).toBe('fish');
    expect(c.label).toBe('Fish');
    expect(c.criticality).toBe(0.82);
  });

  test('fuzzy MISSES are memoized without capturing the custom result shape', () => {
    const first = normalizeGood('Dragon-scale kites');
    const second = normalizeGood('Dragon-scale kites');
    expect(first.custom).toBe(true);
    expect(second).toEqual(first);
    expect(second).not.toBe(first);
  });

  test('results stay correct after the bounded memo clears (600 unique labels > the 512 cap)', () => {
    expect(normalizeGood('fresh river fish').id).toBe('fish');
    for (let i = 0; i < 600; i++) {
      // Unique unmatched labels churn the memo past its bound.
      expect(normalizeGood(`unheard-of ware ${i}`).id).toBe(`custom.unheard_of_ware_${i}`);
    }
    expect(normalizeGood('fresh river fish').id).toBe('fish');
    expect(normalizeGood('Bulk grain and foodstuffs').id).toBe('grain');
  });

  test('normalizeGoodsList dedupe by canonical id is unchanged', () => {
    const goods = normalizeGoodsList([
      'Bulk grain and foodstuffs', 'Grain', 'fresh river fish', 'salted fish barrels',
    ]);
    expect(goods.map(g => g.id)).toEqual(['grain', 'fish']);
  });

  test('the frozen pre-feature corpus replays through the restored matcher with zero divergences', () => {
    // Tier 1 — the matcher's DECISION over every corpus input. This is the only
    // thing a result cache can change, and it covers the 323 fuzzy-path labels
    // measured off a 30-settlement, 3-tick run of the live engine.
    const moved = [];
    FIXTURE.corpus.forEach((input, i) => {
      const got = normalizeGood(input);
      const id = got ? got.id : null;
      if (id !== FIXTURE.expectedIds[i]) {
        moved.push({ input, expected: FIXTURE.expectedIds[i], actual: id });
      }
    });
    expect(moved).toEqual([]);
    expect(FIXTURE.corpus.length).toBe(FIXTURE.expectedIds.length);

    // Tier 2 — the FULL returned object over a representative slice, so the
    // result SHAPE (catalog good, service, custom, null) is pinned too.
    // ⚠ `aliases` is excluded on BOTH sides: normalizeGood spreads the catalog
    // entry, so the returned `aliases` is the catalog's own array BY REFERENCE,
    // and the tamper pin above pushes onto it and never pops. Pinning that
    // reference would make this golden depend on a sibling test's deliberate
    // mutation while adding nothing — WHICH entry was selected is pinned exactly
    // by tier 1's id, and aliases follows from the entry.
    const withoutAliases = (g) => {
      if (!g) return g;
      const { aliases, ...rest } = g;
      return rest;
    };
    const reshaped = [];
    FIXTURE.deepCorpus.forEach((input, i) => {
      const got = withoutAliases(normalizeGood(input));
      if (JSON.stringify(got) !== JSON.stringify(FIXTURE.deepExpected[i])) {
        reshaped.push({ input, expected: FIXTURE.deepExpected[i], actual: got });
      }
    });
    expect(reshaped).toEqual([]);
    expect(FIXTURE.deepCorpus.length).toBe(FIXTURE.deepExpected.length);
  });

  // ⛔ KEEP THIS TEST LAST — it mutates a shared catalog entry and restores it in
  // a `finally`. This is the arm that would have reddened at the destroying merge.
  test('a runtime alias push does not move a memo-cold resolution — the candidate snapshot holds', () => {
    // A label the memo has NEVER seen, resolved only AFTER the push. Resolving it
    // beforehand would let FUZZY_MEMO answer from cache and the arm would pass
    // even with FUZZY_CANDIDATES deleted — the vacuity this test exists to avoid.
    const COLD = 'zzq widgetronic doohickey';
    const aliases = normalizeGood('Grain').aliases;
    const before = aliases.length;

    aliases.push('zzq widgetronic thing');
    try {
      // A re-tokenizing matcher reads the pushed alias and returns `grain`
      // (token overlap 2/3 = 0.67, over the 0.42 floor). The restored matcher
      // scans a module-init snapshot, so the mutation is invisible to it.
      expect(normalizeGood(COLD).id).toBe('custom.zzq_widgetronic_doohickey');
    } finally {
      aliases.pop();
    }
    expect(aliases.length).toBe(before);

    // The exact index was ALREADY a module-init snapshot before this cure, so the
    // module's two halves now agree on the one invariant it has always had.
    expect(normalizeGood('zzq widgetronic thing').id).toBe('custom.zzq_widgetronic_thing');
  });
});
