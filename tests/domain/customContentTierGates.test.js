/**
 * customContentTierGates.test.js — THE TIER-GATE ALLOWLIST AGREEMENT SUITE.
 *
 * THE GAP THIS CLOSES (capability-atlas custom-content Gap 7c). `eligibleCustomContent`
 * used to tier-filter EVERY bucket of the custom-content blob with one generic loop.
 * That made a manifest classification and a runtime behaviour disagree in silence:
 * `factions.tierMin` is declared effect:'presentation' with a single consumer
 * (`compendium.attributes`), yet the generic loop was quietly using it to DROP
 * authored factions from the generation-runtime blob. Nothing read the factions
 * bucket during generation, so the drop was invisible — a dormant mechanical effect
 * wearing a presentation label, one future reader away from becoming real drift.
 *
 * THE CURE, and what this suite pins. `src/domain/customContentSchema.js` now filters
 * only `TIER_GATED_BUCKETS`. Four pins make the assumptions underneath that list
 * executable instead of documentary:
 *
 *   PIN 1 — AGREEMENT. The allowlist equals, exactly, the set of manifest categories
 *           declaring a mechanical tierMin/tierMax that names `eligibleCustomContent`
 *           as a consumer. Reclassifying factions.tierMin to 'mechanical' reds until
 *           the allowlist grows; growing the allowlist without the manifest reds too.
 *           Silent reclassification in either direction becomes impossible.
 *   PIN 2 — PASS-THROUGH + POSITIVE CONTROL. A tier-gated custom faction survives a
 *           thorp; an identically gated institution does not. The control is what
 *           proves the filter still discriminates rather than having been disabled.
 *   PIN 3 — NO-READER CENSUS. The factions bucket has exactly one reader in src/,
 *           and it is the Event Composer (a user-action surface), not generation.
 *           This is the standing assumption that makes PIN 2's pass-through
 *           drift-free; it must fail the moment a generation module starts reading.
 *   PIN 4 — COMPOSER TIER-BLINDNESS. Lives in tests/domain/factionCatalog.test.js
 *           (next to the catalog it pins): tier gates never filter composer options.
 *   PIN 5 — NO GENERATED BYTE MOVES. The census is a grep and greps have blind
 *           spots; provenance reads the blob by a COMPUTED key and hashes what it
 *           finds onto the settlement. So the pass-through's drift-freedom is
 *           executed: same seed, over-tier faction present vs absent, byte-identical
 *           settlement and identical provenance receiptHash.
 *
 * WHY THE ALLOWLIST IS HARDCODED IN THE SCHEMA MODULE. customContentSchema.js sits
 * inside the generation-time lazy boundary; importing customContentManifest.generated.js
 * there would drag the generated manifest into its closure. Hardcode-plus-agreement-test
 * is the table-clerk pattern used elsewhere in this repo, and PIN 1 is the agreement half.
 *
 * NOT NAMED *walker*: this is an agreement/census suite, not a registration walker, so
 * it carries no mutation-coverage manifest obligation.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';
import { describe, test, expect } from 'vitest';

import { CUSTOM_CONTENT_MANIFEST } from '../../src/domain/content/customContentManifest.js';
import { TIER_GATED_BUCKETS, eligibleCustomContent } from '../../src/domain/customContentSchema.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const TIER_FIELD_KEYS = new Set(['tierMin', 'tierMax']);

describe('PIN 1 — the tier-gate allowlist agrees with the manifest', () => {
  test('TIER_GATED_BUCKETS == categories with a mechanical tier field consumed by eligibleCustomContent', () => {
    const derived = (CUSTOM_CONTENT_MANIFEST.categories || [])
      .filter(category => (category.fields || []).some(field => (
        TIER_FIELD_KEYS.has(field.key)
        && field.effect === 'mechanical'
        && (field.consumers || []).includes('eligibleCustomContent')
      )))
      .map(category => category.key)
      .sort();

    expect(derived).toEqual([...TIER_GATED_BUCKETS].sort());
  });

  test('a tier field outside the allowlist is presentation-only (factions today)', () => {
    // The negative half of PIN 1: enumerate every tier field the allowlist does NOT
    // cover and assert none of them claims a mechanical effect. This is the assertion
    // that turns "factions.tierMin is just a chip" from a comment into a gate.
    const strays = [];
    for (const category of CUSTOM_CONTENT_MANIFEST.categories || []) {
      if (TIER_GATED_BUCKETS.includes(category.key)) continue;
      for (const field of category.fields || []) {
        if (!TIER_FIELD_KEYS.has(field.key)) continue;
        if (field.effect !== 'presentation') {
          strays.push(`${category.key}.${field.key} declares effect '${field.effect}' but is not tier-gated`);
        }
      }
    }
    expect(strays).toEqual([]);

    // Positive control: the enumeration is not vacuous — factions.tierMin IS seen.
    const factions = (CUSTOM_CONTENT_MANIFEST.categories || []).find(c => c.key === 'factions');
    expect(factions, 'the factions category vanished from the manifest').toBeTruthy();
    expect((factions.fields || []).some(f => f.key === 'tierMin' && f.effect === 'presentation')).toBe(true);
    expect(TIER_GATED_BUCKETS).not.toContain('factions');
  });
});

describe('PIN 2 — ungated buckets pass through; gated buckets still discriminate', () => {
  test('a tier-gated custom faction survives a thorp, an identical institution does not', () => {
    const blob = {
      factions: [{ name: 'Tiered Order', tierMin: 'metropolis' }],
      institutions: [{ name: 'Mage College', tierMin: 'metropolis' }],
    };
    const out = eligibleCustomContent(blob, { tier: 'thorp' });

    // Pass-through: the presentation-classified tierMin gates nothing.
    expect(out.factions.map(f => f.name)).toEqual(['Tiered Order']);
    // Positive control: the filter is still alive on the buckets that own it.
    expect(out.institutions).toEqual([]);
  });

  test('pass-through is identity-preserving and non-mutating', () => {
    const factions = [{ name: 'Tiered Order', tierMin: 'metropolis' }];
    const blob = { factions };
    const out = eligibleCustomContent(blob, { tier: 'thorp' });

    // Untouched buckets are handed back by reference — no copy, no reordering.
    expect(out.factions).toBe(factions);
    expect(blob.factions).toHaveLength(1);
    expect(out).not.toBe(blob);
  });

  test('every gated bucket in the allowlist really is filtered', () => {
    // Guards against an allowlist entry that names a bucket the loop never sees.
    for (const bucket of TIER_GATED_BUCKETS) {
      const out = eligibleCustomContent(
        { [bucket]: [{ name: 'Gated', tierMin: 'metropolis' }] },
        { tier: 'thorp' },
      );
      expect(out[bucket], `${bucket} is allowlisted but was not filtered`).toEqual([]);
    }
  });
});

describe('PIN 3 — nothing but the Event Composer reads the factions bucket', () => {
  // Literal-read patterns. A generation module that starts consuming authored
  // factions will almost certainly spell it one of these ways.
  const READ_PATTERNS = [
    /customContent\s*\?\.\s*factions/,
    /customContent\s*\.\s*factions/,
    /customContent\s*\[\s*['"]factions['"]\s*\]/,
    // Destructuring, narrowed to a customContent right-hand side so an unrelated
    // `const { factions } = powerStructure` in the same file cannot false-red.
    /\{[^}]*\bfactions\b[^}]*\}\s*=\s*[\w?.]*customContent/,
  ];

  // The ONE legitimate reader: a user-action surface, not a generation path.
  const ALLOWED_READERS = ['src/components/settlement/EventComposer.jsx'];

  function walk(dir, out = []) {
    for (const entry of readdirSync(dir)) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) walk(p, out);
      else out.push(p);
    }
    return out;
  }

  const sourceFiles = walk(join(ROOT, 'src'))
    .map(p => relative(ROOT, p).replace(/\\/g, '/'))
    .filter(rel => /\.(js|jsx)$/.test(rel) && !/\.generated\./.test(rel))
    .sort();

  test('the scan itself is not broken (an empty scan is a passing lie)', () => {
    // Bare-minimum floor on the walk, plus a synthetic proof that each pattern
    // actually matches the shape it claims to hunt.
    expect(sourceFiles.length).toBeGreaterThan(500);
    const synthetic = [
      'const a = customContent?.factions || [];',
      'const b = customContent.factions;',
      "const c = customContent['factions'];",
      'const { factions } = customContent;',
    ];
    READ_PATTERNS.forEach((pattern, i) => {
      expect(pattern.test(synthetic[i]), `pattern ${i} no longer matches its own example`).toBe(true);
    });
    expect(sourceFiles).toContain(ALLOWED_READERS[0]);
  });

  test('the factions-bucket reader set is exactly the Event Composer', () => {
    const readers = sourceFiles.filter((rel) => {
      const code = readFileSync(join(ROOT, rel), 'utf8');
      return READ_PATTERNS.some(pattern => pattern.test(code));
    });

    // A new name here means someone wired authored factions into a NEW surface.
    // If that surface is on a generation or advance path, THE PROMISE is at risk:
    // the factions bucket is passed through the tier filter unfiltered precisely
    // because nothing in generation reads it. Re-derive the drift story before
    // adding a row — do not widen this list to make a red go away.
    expect(readers).toEqual(ALLOWED_READERS);
  });

  // RESIDUAL BLIND SPOTS (accepted, documented): a reader that aliases the blob
  // first (`const cc = customContent; cc.factions`), reaches the bucket through a
  // computed key, or receives an already-destructured `factions` array as a
  // parameter, reads as absent here. PIN 1 still blocks the other half of the
  // risk — the manifest can never reclassify factions.tierMin in silence.
  //
  // ONE SUCH READER IS KNOWN AND REAL, which is why PIN 5 exists. Provenance
  // (src/domain/content/settlementContentProvenance.js) indexes the blob by a
  // COMPUTED key — `content[category]` over MATERIALIZED_CATEGORIES, which
  // includes 'factions' — and it runs on the generation path, writing
  // settlement.customContentProvenance. A literal-pattern census cannot see it,
  // so the pass-through's drift-freedom is proven by execution below, not by grep.
});

describe('PIN 5 — the pass-through moves no generated byte (THE PROMISE)', () => {
  // WHY THIS PIN IS NOT REDUNDANT WITH PIN 3. Letting an over-tier faction stay in
  // the generation blob is only safe if nothing downstream turns blob MEMBERSHIP
  // into output. One thing does look: buildSettlementContentProvenance indexes
  // every MATERIALIZED_CATEGORY — factions included — and stamps a hashed receipt
  // onto the settlement. It is inert here for a structural reason worth stating:
  // a receipt row needs a MATERIALIZED custom-marked faction in the settlement,
  // and generation never creates one (nothing reads the bucket). Structural
  // reasoning is how drift gets shipped, so this pin executes it instead.
  test('same seed, blob with vs without an over-tier custom faction — byte-identical', async () => {
    const { generateSettlementPipeline } = await import('../../src/generators/generateSettlementPipeline.js');
    const hash = 'a'.repeat(64);
    // Fully identity-bearing (definitionId + revisionId + sha256 contentHash), so
    // it is exactly the shape provenance CAN admit — the strongest available probe.
    const overTier = {
      name: 'Tiered Order',
      tierMin: 'metropolis',
      definitionId: 'def-faction-pin5',
      revisionId: 'rev-1',
      contentHash: hash,
    };
    const config = { settType: 'thorp' };
    const options = customContent => ({
      seed: 'tier-gate-pin5',
      customContent,
      contentProvenance: { scope: 'standalone', bindingHash: hash },
    });

    // WITHOUT = what the old generic filter produced at a thorp (faction dropped).
    // WITH = what the allowlist produces now (faction passes through).
    const without = generateSettlementPipeline(config, null, options({ factions: [] }));
    const withFaction = generateSettlementPipeline(
      config,
      null,
      options(eligibleCustomContent({ factions: [overTier] }, { tier: 'thorp' })),
    );

    // Positive control: the probe really did carry the faction into generation.
    expect(eligibleCustomContent({ factions: [overTier] }, { tier: 'thorp' }).factions).toHaveLength(1);
    // The receipt is the sharpest single byte — it is a hash over the blob-derived core.
    expect(withFaction.customContentProvenance?.receiptHash)
      .toBe(without.customContentProvenance?.receiptHash);
    expect(withFaction.customContentProvenance?.materializedDefinitions).toEqual([]);
    // And the whole settlement, not just the receipt.
    expect(JSON.stringify(withFaction)).toBe(JSON.stringify(without));
  });
});
