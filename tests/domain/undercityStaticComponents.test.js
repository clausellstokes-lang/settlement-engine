/**
 * tests/domain/undercityStaticComponents.test.js — MF-UC3's acceptance: the undercity's STATIC
 * components (charter draft-UNDERCITY-PLAN.md §4 UC-3; ODQ §311.6.3 / §311.8.2(a), ruled §441,
 * ratified §445.2).
 *
 * THE MEMBER: `src/domain/undercity/staticComponents.js` derives the caverns a settlement's
 * GROUND gives it — licensed by the geography data's own excavation-affinity rows, anchored on
 * the ground's own published natural features, sized by a closed extent bucket the ground's
 * hardness admits, and joined to the surface by a `breach` where the anchor is itself an
 * opening. Nothing is stored; nothing on the generation path imports it.
 *
 * EVERY ARM RUNS OVER REAL GENERATED SETTLEMENTS (generateSettlementPipeline, fixed seeds),
 * never a hand-built fixture, so the terrain and roster the deriver reads are the ones the
 * generator actually writes. The counterfactual arms change ONE stored input and watch the
 * cavern appear or vanish (the §306.2 input-trap law).
 *
 * THE VOCABULARY ARMS ARE PINNED AGAINST THE LIVE DATA, never against themselves: the licensed
 * terrain set, the ground-hardness classes and the opening features are all re-derived from
 * `TERRAIN_DATA` inside the guard-the-guard arm, so a table that drifts away from the geography
 * it claims to read reddens here rather than passing on its own copy.
 *
 * Registration: this member mints no registry row, no flag, no spatial ledger and no
 * coupling-census entry — `src/domain/undercity/**` is outside the coupling census's scope
 * (`src/domain/(worldPulse|spatial)/`). The anchor walker and the test census are the registers
 * it does fire. Every negative below is anchored (§P3).
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { expectPresentThenAbsent } from '../helpers/anchoredNegatives.js';
import { generateSettlementPipeline } from '../../src/generators/generateSettlementPipeline.js';
import { TERRAIN_DATA } from '../../src/data/geographyData.js';
import { JOINT_KINDS, TEMPERAMENTS } from '../../src/domain/undercity/jointVocabulary.js';
import {
  CAVERN_EXTENTS, CAVERN_MOUTH_JOINT, EXCAVATION_AFFINITY_INSTITUTION, EXTENTS_BY_GROUND,
  GROUND_OPENINGS, STATIC_COMPONENT_KINDS, STATIC_COMPONENT_SOURCE_KIND, STATIC_TEMPERAMENT,
  deriveStaticComponents, groundLicenseOf, staticSurfaceJoin, waterloggedResourceKeys,
} from '../../src/domain/undercity/staticComponents.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const LEAF = 'src/domain/undercity/staticComponents.js';

/** The seven terrains paired with their terrain-honest trade route (the golden's own pairing). */
const TERRAIN_ROUTE = Object.freeze({
  plains: 'road', coastal: 'port', riverside: 'river', mountain: 'mountain_pass',
  forest: 'isolated', hills: 'road', desert: 'desert_road',
});

/** A REAL settlement, generated by the pipeline from a fixed seed. */
function realSettlement(terrain, seed, settType = 'town') {
  return generateSettlementPipeline(
    { settType, culture: 'germanic', terrainOverride: terrain, tradeRouteAccess: TERRAIN_ROUTE[terrain], monsterThreat: 'civilized' },
    null,
    { seed, customContent: {} },
  );
}

/** The corpus every arm walks: seven terrains, two tiers, fixed seeds. */
function corpus() {
  const out = [];
  for (const terrain of Object.keys(TERRAIN_ROUTE)) {
    out.push(realSettlement(terrain, `mf-uc3-${terrain}`));
    out.push(realSettlement(terrain, `mf-uc3-${terrain}-thorp`, 'thorp'));
  }
  return out;
}

/** The terrain classes the LIVE geography data licenses, re-derived from the rows themselves. */
function licensedTerrainsFromData() {
  return Object.keys(TERRAIN_DATA).filter((t) => (TERRAIN_DATA[t].institutionModifiers || [])
    .some((r) => r && r.name === EXCAVATION_AFFINITY_INSTITUTION));
}

/** The leaf's source with every comment removed, so prose about a key is not a read of it. */
function codeOnly(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

describe('MF-UC3 — the undercity static components', () => {
  it('guard-the-guard, then totality: the corpus is real and carries both licensing grounds and a waterlogged one; every table is pinned to the live geography data; every row lands in the closed vocabularies', () => {
    const worlds = corpus();
    // POSITIVE CONTROLS FIRST: without these every membership assertion below passes on nothing.
    expect(worlds.length).toBe(14);
    expect(worlds.every((s) => typeof s.id === 'string' && /^s_[0-9a-f]{16}$/.test(s.id))).toBe(true);
    expect(worlds.every((s) => typeof TERRAIN_DATA[s.config.terrainType] === 'object')).toBe(true);
    // THE TABLES ARE NOT SELF-SUPPLIED: each is re-derived from TERRAIN_DATA right here.
    const licensed = licensedTerrainsFromData();
    expect(licensed).toEqual(['mountain', 'hills']);
    expect(Object.keys(EXTENTS_BY_GROUND).sort())
      .toEqual([...new Set(licensed.map((t) => TERRAIN_DATA[t].architectureModifiers.stoneAvailability))].sort());
    expect(GROUND_OPENINGS.every((f) => licensed.some((t) => TERRAIN_DATA[t].naturalFeatures.includes(f)))).toBe(true);
    expect(waterloggedResourceKeys()).toEqual(['fertile_floodplain', 'marshlands']);
    expect(JOINT_KINDS).toContain(CAVERN_MOUTH_JOINT);
    expect(TEMPERAMENTS).toContain(STATIC_TEMPERAMENT);
    // THE CORPUS EXERCISES BOTH SIDES: licensing ground present, and a licensed ground the
    // catalog's own "tunnels flood" list refuses — the fuel the floodplain arm burns.
    const onLicensedGround = worlds.filter((s) => licensed.includes(s.config.terrainType));
    const waterlogged = onLicensedGround.filter((s) => (s.config.nearbyResourcesNative || [])
      .some((r) => waterloggedResourceKeys().includes(r)));
    expect(onLicensedGround.length).toBe(4);
    expect(waterlogged.length).toBe(1);
    // TOTALITY: the ground is one fact, so it gives at most one cavern, every field closed.
    for (const s of worlds) {
      const rows = deriveStaticComponents(s);
      expect(Array.isArray(rows)).toBe(true);
      expect(rows.length).toBeLessThanOrEqual(1);
      for (const row of rows) {
        expect(STATIC_COMPONENT_KINDS).toContain(row.kind);
        expect(CAVERN_EXTENTS).toContain(row.extent);
        expect(TERRAIN_DATA[row.license.terrain].naturalFeatures).toContain(row.anchor);
        expect(EXTENTS_BY_GROUND[row.license.ground]).toContain(row.extent);
      }
    }
  });

  it('epoch invariance (§311.6.3): a settlement aged three centuries — new tier, new population, a long history, plague stamps, a world clock — derives byte-identical caverns, and the leaf reads no epoch key at all', () => {
    const mountain = realSettlement('mountain', 'mf-uc3-mountain');
    const atYearZero = deriveStaticComponents(mountain);
    expect(atYearZero.length).toBe(1);
    const atYear300 = deriveStaticComponents({
      ...mountain,
      tier: 'city',
      population: (mountain.population || 0) * 4,
      history: { ...(mountain.history || {}), age: 300, events: [{ year: 271 }] },
      calamityHistory: [{ type: 'plague', year: 88, tick: 3, deaths: 400 }],
      currentYear: 300,
      tick: 1200,
      epoch: 4,
      stress: 99,
      activeConditions: [{ id: 'x' }],
    });
    expect(atYear300).toEqual(atYearZero);
    // THE STRUCTURAL PROOF behind the behavioural one: the comment-stripped source reads the
    // identity and the ground, and no clock, history, calamity stamp, population or tier of the
    // SETTLEMENT — so no epoch can reach it. The three positives keep the scan honest.
    const code = codeOnly(readFileSync(join(ROOT, LEAF), 'utf8'));
    expect(code).toContain('resolveSettlementTerrain');
    expect(code).toContain('jointVocabulary.js');
    expect(code).toContain('nativeSemanticResourceKeys');
    // anchored: the three positives above prove the comment-stripped source was read and is live.
    expect(code).not.toMatch(/calamityHistory|currentYear|\bepoch\b|\.population\b|\.history\b|\.tick\b|\bs\.tier\b/);
    // anchored: same live scan — the first-paint closure law (§441.5(d)) and the purity law.
    expect(code).not.toMatch(/townMap|Math\.random|\bDate\b|\bIntl\b|performance\.now/);
  });

  it('terrain licensing over REAL settlements: caverns appear on exactly the two grounds the data licenses, and never in the floodplain — the marsh-bearing hill thorp gets none, and draining it gives it one', () => {
    const worlds = corpus();
    const withCaverns = worlds.filter((s) => deriveStaticComponents(s).length > 0)
      .map((s) => `${s.config.terrainType}/${s.tier}`);
    expect(withCaverns).toEqual(['mountain/town', 'mountain/thorp', 'hills/town']);
    // The five unlicensed grounds give nothing, on either tier.
    const unlicensed = worlds.filter((s) => !licensedTerrainsFromData().includes(s.config.terrainType));
    expect(unlicensed.length).toBe(10);
    expect(unlicensed.every((s) => deriveStaticComponents(s).length === 0)).toBe(true);
    // THE FLOODPLAIN REFUSAL, on a REAL settlement: hill country, licensed ground — but its
    // native roster carries marshlands, the catalog's own "tunnels flood" forbiddance.
    const marshHills = realSettlement('hills', 'mf-uc3-hills-thorp', 'thorp');
    expect(marshHills.config.nearbyResourcesNative).toContain('marshlands');
    expect(groundLicenseOf(marshHills)).toBe(null);
    expect(deriveStaticComponents(marshHills)).toEqual([]);
    const drained = {
      ...marshHills,
      config: {
        ...marshHills.config,
        nearbyResources: marshHills.config.nearbyResources.filter((r) => r !== 'marshlands'),
        nearbyResourcesNative: marshHills.config.nearbyResourcesNative.filter((r) => r !== 'marshlands'),
      },
    };
    expect(deriveStaticComponents(drained).map((row) => row.license.terrain)).toEqual(['hills']);
    // …and the counterfactual the other way: flood a mountain town and its cavern goes.
    const mountain = realSettlement('mountain', 'mf-uc3-mountain');
    const flooded = {
      ...mountain,
      config: {
        ...mountain.config,
        nearbyResources: [...mountain.config.nearbyResources, 'fertile_floodplain'],
        nearbyResourcesNative: [...mountain.config.nearbyResourcesNative, 'fertile_floodplain'],
      },
    };
    expectPresentThenAbsent(
      deriveStaticComponents(mountain).map((row) => row.kind),
      deriveStaticComponents(flooded).map((row) => row.kind),
      'cavern',
    );
  });

  it('seed determinism: two worlds from the same seed derive deep-equal caverns, a clone changes nothing, a rename changes nothing — and a new identity moves the ground', () => {
    const first = deriveStaticComponents(realSettlement('mountain', 'mf-uc3-mountain'));
    // A SECOND WORLD from the same seed, generated after the first was derived — not a clone.
    const second = deriveStaticComponents(realSettlement('mountain', 'mf-uc3-mountain'));
    expect(first.length).toBe(1);
    expect(second).toEqual(first);
    const world = realSettlement('mountain', 'mf-uc3-mountain');
    expect(deriveStaticComponents(structuredClone(world))).toEqual(first);
    // A RENAME moves nothing: the cave sits where the seed put it, whatever the town is called.
    expect(deriveStaticComponents({ ...world, name: 'Anderswo' })).toEqual(first);
    // A NEW IDENTITY is a different world's ground — the extent moves (measured: chamber → system).
    const reIdentified = deriveStaticComponents({ ...world, id: 's_0000000000000000' });
    expect(reIdentified[0].extent).toBe('system');
    // anchored: both rows are pinned non-empty above and their extents are read on this line.
    expect(reIdentified[0].extent).not.toBe(first[0].extent);
  });

  it('the general form (§311.8.1): every row declares temperament STATIC, its typed ground license, a published anchor, a closed extent and a surfaceJoins list drawn from the closed joint vocabulary — empty where the ground names no way in', () => {
    const worlds = corpus();
    const rows = worlds.flatMap((s) => deriveStaticComponents(s));
    expect(rows.length).toBe(3);
    for (const row of rows) {
      expect(row.temperament).toBe(STATIC_TEMPERAMENT);
      expect(row.sourceKind).toBe(STATIC_COMPONENT_SOURCE_KIND);
      expect(row.license.kind).toBe('TERRAIN_EXCAVATION_AFFINITY');
      expect(TERRAIN_DATA[row.license.terrain].institutionModifiers
        .some((r) => r.name === EXCAVATION_AFFINITY_INSTITUTION && r.reason === row.license.reason)).toBe(true);
      expect(Array.isArray(row.surfaceJoins)).toBe(true);
      for (const portal of row.surfaceJoins) {
        expect(JOINT_KINDS).toContain(portal.kind);
        expect(portal.anchor).toBe(row.anchor);
      }
      // A join exists exactly where the anchor is itself an opening into the ground.
      expect(row.surfaceJoins.length).toBe(GROUND_OPENINGS.includes(row.anchor) ? 1 : 0);
    }
    // BOTH STATES OCCUR on real worlds: a cave mouth, and a lawful ISOLATED cavern (§311.6.4).
    const joined = rows.filter((row) => row.surfaceJoins.length > 0);
    const isolated = rows.filter((row) => row.surfaceJoins.length === 0);
    expect(joined.map((row) => row.surfaceJoins[0])).toEqual([{ kind: 'breach', anchor: 'cave system' }]);
    expect(isolated.map((row) => row.anchor)).toEqual(['mountain pass', 'terraced fields']);
  });

  it("the deriver's own validation refuses a joint kind outside the closed vocabulary: an invented kind yields no join at all rather than an unlawful row", () => {
    // The constructor the deriver itself routes every join through — the positive first.
    expect(staticSurfaceJoin(CAVERN_MOUTH_JOINT, 'cave system')).toEqual({ kind: 'breach', anchor: 'cave system' });
    expect(staticSurfaceJoin('stair', 'well-house')).toEqual({ kind: 'stair', anchor: 'well-house' });
    // Kinds outside JOINT_KINDS are REFUSED — a component may lack a portal, never carry an
    // invented one. 'tunnel' and 'shaft' read as plausible and are not in the vocabulary.
    expect([...JOINT_KINDS].map(String).includes('tunnel')).toBe(false);
    expect(staticSurfaceJoin('tunnel', 'cave system')).toBe(null);
    expect(staticSurfaceJoin('shaft', 'mine entrance')).toBe(null);
    expect(staticSurfaceJoin('BREACH', 'cave system')).toBe(null);
    expect(staticSurfaceJoin(null, 'cave system')).toBe(null);
    // An anchorless join is refused too: a portal with no surface cause is decoration (§311.2).
    expect(staticSurfaceJoin(CAVERN_MOUTH_JOINT, '')).toBe(null);
    expect(staticSurfaceJoin(CAVERN_MOUTH_JOINT, 42)).toBe(null);
    // And the deriver really uses it: every join a real world produces is vocabulary-legal.
    const produced = corpus().flatMap((s) => deriveStaticComponents(s)).flatMap((row) => row.surfaceJoins);
    expect(produced.length).toBeGreaterThan(0);
    expect(produced.every((portal) => JOINT_KINDS.includes(portal.kind))).toBe(true);
  });

  it('G-43: flip the terrain class and the cavern license flips with it — a plains town gains one on mountain rock, a mountain town loses it on the flat, and hill stone gives a smaller, unentered cave', () => {
    const plains = realSettlement('plains', 'mf-uc3-plains');
    expect(deriveStaticComponents(plains)).toEqual([]);
    const raised = deriveStaticComponents({ ...plains, config: { ...plains.config, terrainType: 'mountain' } });
    expect(raised.map((row) => row.license.terrain)).toEqual(['mountain']);
    expect(raised[0].anchor).toBe('mine entrance');
    expect(raised[0].surfaceJoins).toEqual([{ kind: 'breach', anchor: 'mine entrance' }]);

    const mountain = realSettlement('mountain', 'mf-uc3-mountain');
    const flattened = { ...mountain, config: { ...mountain.config, terrainType: 'plains' } };
    expectPresentThenAbsent(
      deriveStaticComponents(mountain).map((row) => row.license.terrain),
      deriveStaticComponents(flattened).map((row) => row.license.terrain),
      'mountain',
    );
    // Hill stone is licensed too, but its grammar admits only the small forms.
    const hilled = deriveStaticComponents({ ...mountain, config: { ...mountain.config, terrainType: 'hills' } });
    expect(hilled.map((row) => row.license.ground)).toEqual(['high']);
    expect(EXTENTS_BY_GROUND.high).toContain(hilled[0].extent);
    // anchored: the row is pinned to exist by the two assertions immediately above.
    expect(EXTENTS_BY_GROUND['very high']).not.toContain(hilled[0].extent);
  });

  it('refusal and version discipline: garbage, a missing config and an unpublished terrain all yield [] without throwing, and every exported vocabulary is frozen', () => {
    const world = realSettlement('mountain', 'mf-uc3-mountain');
    expect(deriveStaticComponents(null)).toEqual([]);
    expect(deriveStaticComponents(undefined)).toEqual([]);
    expect(deriveStaticComponents({})).toEqual([]);
    expect(deriveStaticComponents({ ...world, config: null })).toEqual([]);
    expect(deriveStaticComponents({ ...world, config: { ...world.config, terrainType: 'nowhere' } })).toEqual([]);
    // The 'auto' UI sentinel is not a terrain — but resolveTerrain's chain falls through to the
    // wizard's override, so both legs must carry it before the ground goes unresolved.
    expect(world.config.terrainOverride).toBe('mountain');
    expect(deriveStaticComponents({ ...world, config: { ...world.config, terrainType: 'auto', terrainOverride: 'auto' } })).toEqual([]);
    expect(groundLicenseOf(null)).toBe(null);
    // An identity-less object still derives from its ground, so the deriver is total, not lucky.
    expect(deriveStaticComponents({ config: { terrainType: 'mountain' } }).length).toBe(1);
    expect(STATIC_COMPONENT_SOURCE_KIND).toBe('DERIVED_V1');
    expect([STATIC_COMPONENT_KINDS, CAVERN_EXTENTS, GROUND_OPENINGS, EXTENTS_BY_GROUND].every(Object.isFrozen)).toBe(true);
    expect(Object.values(EXTENTS_BY_GROUND).every(Object.isFrozen)).toBe(true);
  });
});
