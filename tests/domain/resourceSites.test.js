/**
 * tests/domain/resourceSites.test.js — MF-T2N's acceptance: the resource LOCATION deriver
 * (charter draft-PRODUCERS-PLAN §3; ODQ §433 C2 — a Shape-1 pure deriver at the domain root).
 *
 * THE MEMBER: `src/domain/resourceSites.js` derives `{ resource, bearing, band, terrainAnchor,
 * sourceKind }` for every entry a settlement already carries in `config.nearbyResources`,
 * from stored facts only (the seed-stable `id`, the roster, `config.terrainType`, and the
 * native resource tables). Nothing is stored; nothing on the generation path imports it.
 *
 * EVERY ARM RUNS OVER REAL GENERATED SETTLEMENTS (generateSettlementPipeline, fixed seeds),
 * never a hand-built fixture, so the roster shape the deriver reads is the one the generator
 * actually writes. The counterfactual arm changes ONE stored input and watches the site move
 * (the §306.2 input-trap law) — a write-then-read of the deriver's own output proves nothing.
 *
 * Registration: this member mints no registry row, no flag, no spatial ledger and no
 * coupling-census entry — `src/domain/resourceSites.js` is a domain-ROOT leaf and the
 * coupling census scopes to `src/domain/(worldPulse|spatial)/` only. The anchor walker and the
 * test census are the registers it does fire. Every negative below is anchored (§P3).
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

import { expectAbsentWithAnchor, expectPresentThenAbsent } from '../helpers/anchoredNegatives.js';
import { generateSettlementPipeline } from '../../src/generators/generateSettlementPipeline.js';
import { TERRAIN_DATA } from '../../src/data/geographyData.js';
import { RESOURCE_SEMANTICS } from '../../src/domain/resourceSemantics.js';
import {
  ADMISSIBLE_BANDS_BY_TYPE, RESOURCE_SITE_BANDS, RESOURCE_SITE_BEARINGS,
  RESOURCE_SITE_SOURCE_KIND, RESOURCE_SITE_TERRAIN_ANCHORS, UNANCHORED, UNTYPED_RESOURCE,
  deriveResourceSites,
} from '../../src/domain/resourceSites.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const LEAF = 'src/domain/resourceSites.js';

/** The seven terrains paired with their terrain-honest trade route (the golden's own pairing). */
const TERRAIN_ROUTE = Object.freeze({
  plains: 'road', coastal: 'port', riverside: 'river', mountain: 'mountain_pass',
  forest: 'isolated', hills: 'road', desert: 'desert_road',
});

/** A REAL settlement, generated by the pipeline from a fixed seed. */
function realSettlement(terrain, seed, settType = 'town') {
  return generateSettlementPipeline(
    { settType, culture: 'germanic', terrainOverride: terrain, tradeRouteAccess: TERRAIN_ROUTE[terrain], monsterThreat: 'civilized' },
    null,
    { seed, customContent: {} },
  );
}

/** The corpus every vocabulary arm walks: seven terrains, two tiers, fixed seeds. */
function corpus() {
  const out = [];
  for (const terrain of Object.keys(TERRAIN_ROUTE)) {
    out.push(realSettlement(terrain, `mf-t2n-${terrain}`));
    out.push(realSettlement(terrain, `mf-t2n-${terrain}-thorp`, 'thorp'));
  }
  return out;
}

/** Walk every source file under `src/`. */
function walk(dir, out = []) {
  for (const entry of readdirSync(join(ROOT, dir))) {
    const rel = `${dir}/${entry}`;
    if (statSync(join(ROOT, rel)).isDirectory()) walk(rel, out);
    else if (/\.(?:js|jsx|mjs)$/.test(rel)) out.push(rel);
  }
  return out;
}

/** The leaf's source with every comment removed, so prose about `Date` is not a `Date` read. */
function codeOnly(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

/** Files under `src/` whose code imports the named module basename. */
function importersOf(basename) {
  return walk('src').filter((rel) => new RegExp(`from\\s+'[^']*/${basename}'`).test(codeOnly(readFileSync(join(ROOT, rel), 'utf8'))));
}

const typeOf = (resource) => RESOURCE_SEMANTICS[resource]?.type ?? UNTYPED_RESOURCE;

describe('MF-T2N — the resource location deriver', () => {
  it('guard-the-guard, then totality: every roster entry on a real settlement yields one typed site, every field in its closed vocabulary', () => {
    const worlds = corpus();
    // POSITIVE CONTROLS FIRST: the generator really wrote rosters, and the vocabularies are
    // non-empty — or every membership assertion below would pass on nothing.
    expect(worlds.length).toBe(14);
    expect(worlds.every((s) => Array.isArray(s.config.nearbyResources) && s.config.nearbyResources.length > 0)).toBe(true);
    expect(RESOURCE_SITE_BEARINGS.length).toBe(8);
    expect(RESOURCE_SITE_BANDS.length).toBe(3);
    expect(RESOURCE_SITE_TERRAIN_ANCHORS.length).toBe(Object.keys(TERRAIN_DATA).length + 1);
    const windsUsed = new Set();
    const bandsUsed = new Set();
    let positionalSites = 0;
    for (const s of worlds) {
      const sites = deriveResourceSites(s);
      // TOTALITY: one site per distinct roster entry, in roster order, the key verbatim.
      expect(sites.map((site) => site.resource)).toEqual([...new Set(s.config.nearbyResources)]);
      for (const site of sites) {
        expect(RESOURCE_SITE_BEARINGS).toContain(site.bearing);
        expect(RESOURCE_SITE_BANDS).toContain(site.band);
        expect(RESOURCE_SITE_TERRAIN_ANCHORS).toContain(site.terrainAnchor);
        // The band respects the resource's closed semantic type: a harbour, crossroads, pass,
        // oasis or spring is OCCUPIED (AT_HAND); a seam or quarry is worked from a distance.
        expect(ADMISSIBLE_BANDS_BY_TYPE[typeOf(site.resource)]).toContain(site.band);
        if (typeOf(site.resource) === 'positional') { positionalSites += 1; expect(site.band).toBe('AT_HAND'); }
        // A real settlement always carries a terrain, so the typed gap never fires here —
        // anchored: the refusal arm below PRODUCES `UNANCHORED` on a terrain-less object.
        expect(site.terrainAnchor).not.toBe(UNANCHORED);
        windsUsed.add(site.bearing);
        bandsUsed.add(site.band);
      }
    }
    // The corpus really exercised the positional law (the anchor for the admissible checks).
    expect(positionalSites).toBeGreaterThan(0);
    // The winds and bands SPREAD — a bucketing collapsed to one value is convicted here.
    expect(windsUsed.size).toBeGreaterThan(1);
    expect(bandsUsed.size).toBeGreaterThan(1);
  });

  it('determinism companion: two derivations at distance are deep-equal, and no wall-clock or rng is reachable from the leaf', () => {
    const first = deriveResourceSites(realSettlement('riverside', 'mf-t2n-riverside'));
    // A SECOND WORLD from the same seed, generated after the first was derived — not a clone.
    const second = deriveResourceSites(realSettlement('riverside', 'mf-t2n-riverside'));
    expect(first.length).toBeGreaterThan(0);
    expect(second).toEqual(first);
    expect(deriveResourceSites(structuredClone(realSettlement('riverside', 'mf-t2n-riverside')))).toEqual(first);
    const code = codeOnly(readFileSync(join(ROOT, LEAF), 'utf8'));
    // The scan is live: it sees the hash and the slug import the leaf really uses.
    expect(code).toContain('mixedHash32');
    expect(code).toContain("from './worldPulse/stablePart.js'");
    // anchored: the two positives above prove the comment-stripped source was read.
    expect(code).not.toMatch(/\bDate\b|Math\.random|\bIntl\b|performance\.now/);
  });

  it('counterfactual reach (§306.2): change ONE stored input and the site moves accordingly — a resource swap, a terrain change, a new identity; a rename moves nothing', () => {
    const plains = realSettlement('plains', 'mf-t2n-plains');
    expect(plains.config.nearbyResources).toEqual(['hunting_grounds', 'ancient_grove', 'precious_metals', 'grain_fields']);
    const before = deriveResourceSites(plains);
    const metals = before.find((site) => site.resource === 'precious_metals');
    expect(metals).toEqual({ resource: 'precious_metals', bearing: 'NE', band: 'NEAR', terrainAnchor: 'plains', sourceKind: 'DERIVED_V1' });

    // (i) SWAP ONE RESOURCE: an exhaustible seam becomes a positional crossroads. The band
    // moves to AT_HAND because the TYPE moved (an unconstrained pick over all three bands
    // reads NEAR for this token — measured — so the constraint is what the arm convicts);
    // the bearing moves because the token moved; the untouched sites do not move at all.
    const swapped = { ...plains, config: { ...plains.config, nearbyResources: ['hunting_grounds', 'ancient_grove', 'crossroads_position', 'grain_fields'] } };
    const after = deriveResourceSites(swapped);
    expect(after.find((site) => site.resource === 'crossroads_position'))
      .toEqual({ resource: 'crossroads_position', bearing: 'SW', band: 'AT_HAND', terrainAnchor: 'plains', sourceKind: 'DERIVED_V1' });
    expect(after.filter((site) => site.resource !== 'crossroads_position'))
      .toEqual(before.filter((site) => site.resource !== 'precious_metals'));

    // (ii) CHANGE THE TERRAIN: every tie-less site follows the settlement's terrain family.
    const hills = deriveResourceSites({ ...plains, config: { ...plains.config, terrainType: 'hills' } });
    expect(before.every((site) => site.terrainAnchor === 'plains')).toBe(true);
    expect(hills.every((site) => site.terrainAnchor === 'hills')).toBe(true);
    expect(hills.map(({ terrainAnchor: _anchor, ...rest }) => rest)).toEqual(before.map(({ terrainAnchor: _anchor, ...rest }) => rest));
    // …but a resource's OWN single tie outranks it: a fishery stays coastal on a hills
    // counterfactual while the two-tie salt flats and the tie-less ruins follow the settlement.
    const coastal = realSettlement('coastal', 'mf-t2n-coastal');
    expect(coastal.config.nearbyResources).toContain('fishing_grounds');
    expect(coastal.config.nearbyResources).toContain('salt_flats');
    expect(coastal.config.nearbyResources).toContain('ancient_ruins');
    const inland = deriveResourceSites({ ...coastal, config: { ...coastal.config, terrainType: 'hills' } });
    expect(inland.find((site) => site.resource === 'fishing_grounds')?.terrainAnchor).toBe('coastal');
    expect(inland.find((site) => site.resource === 'salt_flats')?.terrainAnchor).toBe('hills');
    expect(inland.find((site) => site.resource === 'ancient_ruins')?.terrainAnchor).toBe('hills');

    // (iii) A NEW IDENTITY moves the bearings (the seed reaches the hash); (iv) a RENAME with
    // the same id moves NOTHING — the seam sits where the seed put it, whatever the town is called.
    const reIdentified = deriveResourceSites({ ...plains, id: 's_0000000000000000' });
    expect(reIdentified.map((site) => site.resource)).toEqual(before.map((site) => site.resource));
    const movedBearings = before.filter((site, i) => site.bearing !== reIdentified[i].bearing).map((site) => site.resource);
    expect(movedBearings.length).toBeGreaterThan(0);
    expect(deriveResourceSites({ ...plains, name: 'Anderswo' })).toEqual(before);
  });

  it('refusal: an absent resource yields no site; an empty or malformed roster yields [] and never a throw; a custom resource is typed, not invented', () => {
    const hills = realSettlement('hills', 'mf-t2n-hills');
    expect(hills.config.nearbyResources).toContain('grazing_land');
    const withGrazing = deriveResourceSites(hills).map((site) => site.resource);
    const without = deriveResourceSites({ ...hills, config: { ...hills.config, nearbyResources: hills.config.nearbyResources.filter((key) => key !== 'grazing_land') } })
      .map((site) => site.resource);
    // The pasture was sited while on the roster and is gone once the roster drops it.
    expectPresentThenAbsent(withGrazing, without, 'grazing_land');
    expect(without.length).toBe(withGrazing.length - 1);

    expect(deriveResourceSites(null)).toEqual([]);
    expect(deriveResourceSites(undefined)).toEqual([]);
    expect(deriveResourceSites({ ...hills, config: null })).toEqual([]);
    expect(deriveResourceSites({ ...hills, config: { ...hills.config, nearbyResources: [] } })).toEqual([]);
    expect(deriveResourceSites({ ...hills, config: { ...hills.config, nearbyResources: 'iron_deposits' } })).toEqual([]);
    // Non-string and empty entries yield no site; a duplicate collapses to its first occurrence.
    const ragged = deriveResourceSites({ ...hills, config: { ...hills.config, nearbyResources: [42, '', 'iron_deposits', null, 'iron_deposits'] } });
    expect(ragged.map((site) => site.resource)).toEqual(['iron_deposits']);

    // A CUSTOM resource the native table does not know is sited, not refused, and typed as
    // UNTYPED: its band may be any of the three, its anchor is the settlement's own terrain.
    const custom = deriveResourceSites({ ...hills, config: { ...hills.config, nearbyResources: ['Dragonglass'] } });
    expect(custom.length).toBe(1);
    expect(custom[0].resource).toBe('Dragonglass');
    expect(RESOURCE_SITE_BANDS).toContain(custom[0].band);
    expect(custom[0].terrainAnchor).toBe('hills');
    // The typed gap: no terrain on the settlement, no tie on the resource → UNANCHORED, a
    // site still (the roster is the fact), never a guessed family.
    const bare = deriveResourceSites({ config: { nearbyResources: ['ancient_ruins'] } });
    expect(bare).toEqual([{ resource: 'ancient_ruins', bearing: bare[0].bearing, band: bare[0].band, terrainAnchor: UNANCHORED, sourceKind: 'DERIVED_V1' }]);
    expect(RESOURCE_SITE_BEARINGS).toContain(bare[0].bearing);
  });

  it('golden inertness by construction: nothing under src/ imports the leaf, a generated settlement carries no site, and deriving mutates nothing', () => {
    // The scan is live: the sibling table the leaf reads has importers under src/.
    const semanticsImporters = importersOf('resourceSemantics.js');
    expect(semanticsImporters.length).toBeGreaterThan(0);
    expect(semanticsImporters).toContain('src/generators/steps/resolveResources.js');
    // anchored: the positive control above proves the import regex and the walk both work.
    expect(importersOf('resourceSites.js')).toEqual([]);
    // The generator writes NO site: a fresh world's JSON never mentions one, and the deriver
    // leaves the settlement byte-identical — so the golden manifest cannot move.
    const s = realSettlement('forest', 'mf-t2n-forest');
    const frozen = JSON.stringify(s);
    expect(frozen).not.toMatch(/resourceSites|DERIVED_V1/); // anchored: the roster IS in the JSON (next line)
    expect(frozen).toContain('"nearbyResources"');
    expect(deriveResourceSites(s).length).toBeGreaterThan(0);
    expect(JSON.stringify(s)).toBe(frozen);
  });

  it('version discipline: sourceKind is the frozen DERIVED_V1 on every record, the record keys and every vocabulary are asserted exact', () => {
    expect(RESOURCE_SITE_SOURCE_KIND).toBe('DERIVED_V1');
    const sites = deriveResourceSites(realSettlement('desert', 'mf-t2n-desert'));
    expect(sites.length).toBeGreaterThan(0);
    for (const site of sites) {
      expect(site.sourceKind).toBe('DERIVED_V1');
      expect(Object.keys(site)).toEqual(['resource', 'bearing', 'band', 'terrainAnchor', 'sourceKind']);
    }
    expect([...RESOURCE_SITE_BEARINGS]).toEqual(['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW']);
    expect([...RESOURCE_SITE_BANDS]).toEqual(['AT_HAND', 'NEAR', 'DAYS_REACH']);
    expect([...RESOURCE_SITE_TERRAIN_ANCHORS]).toEqual([...Object.keys(TERRAIN_DATA), 'UNANCHORED']);
    // The admissible table covers EXACTLY the semantic types the taxonomy pins, plus UNTYPED,
    // and every set is a non-empty subset of the band vocabulary in nearest-first order.
    const semanticTypes = [...new Set(Object.values(RESOURCE_SEMANTICS).map((row) => row.type))].sort();
    expect(semanticTypes).toEqual(['exhaustible', 'infrastructure', 'magical', 'positional', 'renewable']);
    expect(Object.keys(ADMISSIBLE_BANDS_BY_TYPE).sort()).toEqual([...semanticTypes, UNTYPED_RESOURCE].sort());
    for (const set of Object.values(ADMISSIBLE_BANDS_BY_TYPE)) {
      expect(set.length).toBeGreaterThan(0);
      expect([...set]).toEqual(RESOURCE_SITE_BANDS.filter((band) => set.includes(band)));
    }
    expect([...ADMISSIBLE_BANDS_BY_TYPE[UNTYPED_RESOURCE]]).toEqual([...RESOURCE_SITE_BANDS]);
    // anchored: the exact-key list above pins the record shape, so a stray key is impossible.
    expectAbsentWithAnchor(Object.keys(sites[0]), 'distance', 'band');
  });
});
