    expect(sewerSurfaceJoin('tunnel', 'civic')).toBe(null);
    expect(sewerSurfaceJoin('grate', '')).toBe(null);
    expect([SEWER_CAUSES, CAUSE_DIRECTIONS, RUNG_SOURCES, WELL_EXTENTS, DISTRICT_COVERAGE_KEYS, SEWER_DERIVATION_TUNING]
      .map(Object.isFrozen)).toEqual(Array(6).fill(true));
