    // identity gives the same answer, which is what "ABSENT below the floor" means.
    const thorp = withoutSanitation(world('thorp', 'plains', 'uc1-floor'));
    const floorRungs = [...Array(6).keys()].map((n) => deriveSewerLadder({ ...thorp, id: `s_floor_${n}` }).rung);
    expect(new Set(floorRungs)).toEqual(new Set(['cesspits']));
    expect(deriveSewerLadder(thorp).score).toBeLessThanOrEqual(SEWER_DERIVATION_TUNING.absentFloor);

    // THE CERTAIN THRESHOLD: drive every raising cause to its maximum and the ceiling is reached
    // without a draw — every identity agrees.
    const rich = {
      ...withoutSanitation(world('town', 'hills', 'uc1-certain')),
      economicState: { prosperity: 'Wealthy' },
      config: { terrainType: 'hills', tradeRouteAccess: 'river', peakTier: 'metropolis' },
      calamityHistory: stamps(9, 'x'),
      institutions: [{ name: 'Town hall' }, { name: 'High court' }, { name: 'Grand assembly' }, { name: 'Elders council' }],
    };
    expect(deriveSewerLadder(rich).score).toBeGreaterThanOrEqual(SEWER_DERIVATION_TUNING.certainThreshold);
    const certainRungs = [...Array(6).keys()].map((n) => deriveSewerLadder({ ...rich, id: `s_certain_${n}` }).rung);
    expect(new Set(certainRungs)).toEqual(new Set(['quarter_network']));

    // THE GRAMMAR TABLES ARE PINNED TO THE LIVE ESTATE, not to themselves.
    expect(Object.keys(TIER_LADDER_BOUNDS).sort()).toEqual([...TIER_ORDER].sort());
    expect(Object.keys(WELL_NEED_BY_TIER).sort()).toEqual([...TIER_ORDER].sort());
    expect(FALL_LINE_TERRAINS.every((t) => Object.prototype.hasOwnProperty.call(TERRAIN_DATA, t))).toBe(true);
