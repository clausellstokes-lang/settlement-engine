/**
 * tests/domain/undercitySewerDerivation.test.js — MF-UC1's acceptance: the SANITATION LADDER and
 * the wells/cisterns (charter draft-UNDERCITY-PLAN.md §4 UC-1; ODQ §311.7 / §311.8.2(c), ruled
 * §441, ratified §445.2).
 *
 * THE MEMBER: `src/domain/undercity/sewerDerivation.js` derives the rung a settlement's drains
 * reach, WHY (five typed live causes and one honest zero), WHICH quarters they reach, and the
 * wells/cisterns its water need licenses. Nothing is stored; nothing on the generation path
 * imports it.
 *
 * EVERY ARM RUNS OVER REAL GENERATED SETTLEMENTS (`generateSettlementPipeline`, fixed seeds),
 * never a hand-built fixture, so the roster, terrain, prosperity and population the deriver
 * reads are the ones the generator actually writes. The counterfactual arms change ONE stored
 * input and watch the rung move (the §306.2 input-trap law).
 *
 * THE VOCABULARY ARMS ARE PINNED AGAINST THE LIVE DATA, never against themselves: the roster
 * institution and the water institution are re-read from `institutionalCatalog`, the district
 * 12-enum from the real `DISTRICT_CATEGORIES`, the fall-line classes from `TERRAIN_DATA`, the
 * tier rows from `TIER_ORDER` and the rung names from UC-0's `SANITATION_LADDER` — so a table
 * that drifts away from the estate it claims to read reddens here rather than passing on its
 * own copy.
 *
 * §474: the shared-namespace arms pin INTENT — a positive control plus a named exclusion set —
 * except where the list is this file's own COPY of a list another module owns (the district
 * 12-enum), where an ordered equality is exactly the drift ratchet that copy needs.
 *
 * Registration: this member mints no registry row, no flag, no spatial ledger and no
 * coupling-census entry (`src/domain/undercity/**` is outside the coupling census's scope). The
 * anchor walker and the test census are the registers it fires. Every negative below is
 * anchored (§P3).
 */
