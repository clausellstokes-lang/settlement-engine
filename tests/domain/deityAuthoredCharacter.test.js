describe('W-FAITH F1c · DIVINE IMMUTABILITY, as a refusal (ODQ §800.3 J4)', () => {
  test('the compat validator refuses every drift-state spelling by name', () => {
    const refused = [];
    for (const key of DEITY_REFUSED_DRIFT_KEYS) {
      const result = validateDeity({ ...LEGACY, [key]: { MERCY: { offset: 1 } } });
      if (result.ok || !result.errors.join(' ').includes(key)) refused.push(key);
    }
    expect(refused).toEqual([]);
  });

  test('the canonical admission wall refuses them too, as unregistered fields', () => {
    const admitted = [];
    for (const key of DEITY_REFUSED_DRIFT_KEYS) {
      const result = admitCustomContentDefinitionShape('deities', { ...LEGACY, [key]: {} });
      if (result.ok) admitted.push(key);
      else if (!result.errors.some((e) => e.code === 'unregistered_field' && e.field === key)) {
        admitted.push(`${key} (wrong refusal)`);
      }
    }
    expect(admitted).toEqual([]);
  });

  test('a drift key is refused even when it is empty or null', () => {
    expect(validateDeity({ ...LEGACY, characterDrift: null }).ok).toBe(false);
    expect(validateDeity({ ...LEGACY, drift: {} }).ok).toBe(false);
  });

  test('no drift-shaped field is registered on the deity bucket at all', () => {
    const category = MANIFEST.categories.find((c) => c.key === 'deities');
    const driftish = category.fields
      .map((f) => f.key)
      .filter((key) => /drift/i.test(key));
    expect(driftish).toEqual([]);
  });

  test('the refusal list is the one the module publishes, and it is not empty', () => {
    expect([...DEITY_REFUSED_DRIFT_KEYS]).toEqual([
      'characterDrift', 'drift', 'driftState', 'axisDrift', 'effectiveCharacter',
    ]);
  });
});

