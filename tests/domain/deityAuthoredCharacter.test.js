    expect(manifestSchemaOf('baneChannel').values).toEqual([...DEITY_EFFECT_CHANNEL_KEYS]);
    expect(manifestSchemaOf('boonStrength').values).toEqual([...DEITY_EFFECT_STRENGTH_KEYS]);
    expect(manifestSchemaOf('baneStrength').values).toEqual([...DEITY_EFFECT_STRENGTH_KEYS]);
