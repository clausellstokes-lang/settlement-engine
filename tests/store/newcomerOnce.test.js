/**
 * newcomerOnce.test.js — EM-E8d (U111): A NEWCOMER IS MINTED ONCE. The tick that mints the
 * NEXT one never duplicates the last (design §2.6's head of the tick, §14's regeneration from
 * the layer, §22.3 ruling 9's newcomer; THE PROMISE — lived history is immutable).
 *
 * THE MEASUREMENT THIS FILE WAS WRITTEN FROM. At 2dba3ffa0, over the REAL advance in LOCAL
 * mode on a one-member canon campaign: stage `add-npc` A -> advance -> stage `add-npc` B ->
 * advance left, on the LIVE VIEW, the LIBRARY ROW and the DURABLE SAVE alike,
 *   A twice (2 / 2 / 2) and B once (1 / 1 / 1), the roster 3 -> 4 -> 6:
 * it grew by TWO at a tick that added ONE person. The CONTROL — one decree over two advances —
 * came back exactly one (1 / 1 / 1), roster 3 -> 4 -> 4, which is why the duplicate is the
 * SECOND decree's tick and not the second tick.
 *
 * AND THE SEAM IS NOT A DECREE APPLIED TWICE: A's entry read `applied` once, carrying the FIRST
 * tick's `appliedAt` and `tickRef` after the second. The re-derivation's base is a clone of the
 * live record — which already carries A — and every row of the layer's `minted` was appended to
 * that clone on every run, so the tick that minted B re-appended A beside him.
 *
 * ⛔ NOTHING HERE IS A MOCK OF THE MECHANISM. The settlement is generated by the real pipeline,
 * the advance is the store's own `advanceCampaignWorld` through the real kernel and EM-E1's real
 * tick hook, the registry is EM-C1's, the re-derivation is the real engine, and the library is
 * the REAL save service in local mode — every durable row below has been through `saves.save` ->
 * the advance's own flush -> `saves.list`.
 *
 * ⛔ ONE MEMBER, DELIBERATELY, as EM-E8b case A's suite is: the local save service's `update` is
 * read-modify-write over the whole library array, so a one-member campaign makes the durable read
 * a measurement of THIS mechanism rather than of that fan-out.
 *
 * ⛔ NO ARM ASSERTS INSIDE A LOOP: each matrix is COLLECTED and then asserted once.
 *
 * @enforced-by this test
 */
