import { addOpPayloadFor, stageAddDecreeIntent } from '../../src/store/editSlice.js';

const HOME = 'save-home';
const NOW = '2026-04-04T00:00:00.000Z';
const CONFIG = Object.freeze({ settType: 'thorp', culture: 'germanic', terrain: 'grassland' });

/** ONE real world per seed, generated once, so the suite pays the engine as little as it can. */
const WORLDS = new Map();
function world(seed) {
  if (!WORLDS.has(seed)) {
    WORLDS.set(seed, generateSettlementPipeline({ ...CONFIG }, null, { seed, customContent: {} }));
  }
  return WORLDS.get(seed);
}

const clone = (value) => JSON.parse(JSON.stringify(value));

/** A localStorage double — the save service and the campaign cache reach it and nothing else. */
function installLocalStorage() {
  const data = new Map();
  globalThis.localStorage = {
    getItem: (key) => data.get(String(key)) ?? null,
    setItem: (key, value) => data.set(String(key), String(value)),
    removeItem: (key) => data.delete(String(key)),
    clear: () => data.clear(),
  };
}

const stubSlice = () => ({
  auth: { user: null, tier: 'free', loading: false },
  config: { ...CONFIG }, institutionToggles: {}, categoryToggles: {},
  goodsToggles: {}, servicesToggles: {}, customContent: {}, importedNeighbour: null,
  isTierAllowed: () => true, canSave: () => true, maxSaves: () => 50,
  setPurchaseModalOpen: () => {},
});

/** The three slices the advance, the library and the edit door actually live on. */
const makeStore = () => create(immer((...args) => ({
  ...stubSlice(),
  ...createSettlementSlice(...args),
  ...createCampaignSlice(...args),
  ...createCampaignWorldPulseSlice(...args),
})));

/** A save ENVELOPE a canon member of a campaign carries, with an explicit row id. */
const envelope = (id, record) => ({
  id,
  name: String(record.name),
  tier: String(record.tier),
  seed: String(record._seed),
  settlement: clone(record),
  phase: 'canon',
  campaignState: { phase: 'canon', eventLog: [], locks: {}, systemState: {} },
  config: { ...CONFIG },
  aiData: {},
  versionHistory: [],
});

/** The LIVE pool catalogue for the pools the npc add-op names, read from its producer. */
function poolsFor(cardType, record) {
  return Object.fromEntries(addOpPayloadFor(cardType)
    .filter((row) => typeof row.pool === 'string')
    .map((row) => [row.pool, poolValues(row.pool, record)]));
}

/** Stage ONE add-npc decree on the hydrated save, exactly as a CREATE door would. */
function stageNewcomer(store, name) {
  const record = store.getState().settlement;
  return stageAddDecreeIntent(store.getState, store.setState, {
    cardType: 'npc',
    values: { name, role: poolValues('npc.role', record)[0] },
    pools: poolsFor('npc', record),
    orderedAt: NOW,
  });
}

/**
 * A canonized ONE-MEMBER campaign whose member is a real generated world, seeded into the REAL
 * library first so the durable row below is one the product wrote.
 */
async function seedCampaign(seed) {
  installLocalStorage();
  const record = world(seed);
  await saves.save(envelope(HOME, record));
  const library = await saves.list();
  const store = makeStore();
  store.setState((state) => {
    state.savedSettlements = clone(library).map((row) => ({
      ...row,
      phase: 'canon',
      campaignState: { phase: 'canon', eventLog: [], locks: {}, systemState: {} },
    }));
    state.campaigns = [{
      id: 'camp-1',
      name: 'Realm',
      accessState: 'active',
      settlementIds: [HOME],
      regionalGraph: ensureRegionalGraph({ edges: [] }, { now: NOW }),
      wizardNews: ensureWizardNewsFeed(undefined, { now: NOW }),
      worldState: ensureWorldState(
        { rngSeed: `newcomer-once-${seed}`, tick: 0, canonizedAt: NOW },
        { id: 'camp-1', name: 'Realm' },
      ),
    }];
    state.campaignsLoaded = true;
    state.activeSaveId = HOME;
    state.settlement = clone(record);
    state.phase = 'canon';
  });
  return { store };
}

/** Mirror the live view onto its library row AND its durable row, as a save would. */
async function saveTheView(store) {
  const record = clone(store.getState().settlement);
  store.setState((state) => {
    const idx = state.savedSettlements.findIndex((row) => String(row.id) === HOME);
    state.savedSettlements[idx].settlement = record;
  });
  await saves.update(HOME, { settlement: record });
}

const advance = (store) =>
  store.getState().advanceCampaignWorld('camp-1', 'one_week', { now: NOW });

const npcIdsOf = (record) => (record?.npcs || []).map((npc) => npc.id);
const rowOf = (store) => store.getState().savedSettlements
  .find((row) => String(row.id) === HOME);
const durableRow = async () => (await saves.list()).find((row) => String(row.id) === HOME);
const countOf = (record, id) => npcIdsOf(record).filter((one) => one === id).length;

/** ONE id, counted on the save's THREE homes: the live view, the library row, the durable row. */
async function homesCount(store, id) {
  return [
    countOf(store.getState().settlement, id),
    countOf(rowOf(store).settlement, id),
    countOf((await durableRow()).settlement, id),
  ];
}

/** The roster's SIZE on those same three homes, so a duplicate cannot hide behind a swap. */
async function homesSize(store) {
  return [
    npcIdsOf(store.getState().settlement).length,
    npcIdsOf(rowOf(store).settlement).length,
    npcIdsOf((await durableRow()).settlement).length,
  ];
}

describe('EM-E8d — a newcomer is minted once', () => {
  it('D1 leaves the FIRST newcomer exactly once when a second add-decree falls due at a later tick', async () => {
    const { store } = await seedCampaign('e8d-d1');
    const a = stageNewcomer(store, 'Alda');
    await saveTheView(store);
    const before = await homesSize(store);

    const first = await advance(store);
    const aAfterFirst = await homesCount(store, a.decreeId);
    const sizeAfterFirst = await homesSize(store);

    const b = stageNewcomer(store, 'Bern');
    await saveTheView(store);
    const second = await advance(store);
    const aAfterSecond = await homesCount(store, a.decreeId);
    const bAfterSecond = await homesCount(store, b.decreeId);
    const sizeAfterSecond = await homesSize(store);
    const entries = ((await durableRow()).settlement.decrees || [])
      .map((row) => [row.id === a.decreeId ? 'A' : 'B', row.status, row.tickRef]);

    expect([a.ok, b.ok], 'both doors staged their CREATE intent').toEqual([true, true]);
    expect([first?.tick, second?.tick],
      'and TWO real advances ran to committed results — a dead second advance would pass every'
      + ' count below for the wrong reason').toEqual([1, 2]);
    // anchored: the first advance did put A on all three homes exactly once, so a two below is
    // the second advance adding a copy and not a fixture that was doubled from the start.
    expect(aAfterFirst, 'A is on the live view, the library row and the durable save exactly once'
      + ' after the first advance').toEqual([1, 1, 1]);
    expect(sizeAfterFirst, 'and each roster grew by exactly one')
      .toEqual(before.map((size) => size + 1));
    expect(aAfterSecond, 'THE MEASUREMENT (U111): A is STILL there exactly once after the advance'
      + ' that minted B — measured 2/2/2 at 2dba3ffa0, on all three homes').toEqual([1, 1, 1]);
    expect(bAfterSecond, 'and B is there exactly once, on all three').toEqual([1, 1, 1]);
    expect(sizeAfterSecond, 'so two advances that added two people grew every roster by two')
      .toEqual(before.map((size) => size + 2));
    expect(entries, 'and neither decree was applied twice: A carries the FIRST tick\'s reference'
      + ' still, which is what rules the duplication out as a second application')
      .toEqual([['A', 'applied', 'world_pulse.camp_1.1'], ['B', 'applied', 'world_pulse.camp_1.2']]);
  }, 180000);

  it('D2 CONTROL: one decree over two advances leaves exactly one, on all three homes', async () => {
    const { store } = await seedCampaign('e8d-d2');
    const a = stageNewcomer(store, 'Alda');
    await saveTheView(store);
    const before = await homesSize(store);

    await advance(store);
    const afterFirst = await homesCount(store, a.decreeId);
    const second = await advance(store);
    const afterSecond = await homesCount(store, a.decreeId);
    const sizeAfterSecond = await homesSize(store);

    expect(a.ok, 'the door staged the CREATE intent').toBe(true);
    expect(second?.tick, 'and the SECOND advance ran, or this control measures one tick twice')
      .toBe(2);
    // anchored: the newcomer was there after the first advance, so the one below is the second
    // advance leaving him alone rather than a world that never minted anybody.
    expect(afterFirst, 'one after the first advance').toEqual([1, 1, 1]);
    expect(afterSecond, 'and still exactly one after the second — an applied entry is read at'
      + ' every later tick and the layer is what says he already exists').toEqual([1, 1, 1]);
    expect(sizeAfterSecond, 'the roster grew by exactly one over the two')
      .toEqual(before.map((size) => size + 1));
  }, 180000);
});
