/**
 * tickPersistence.test.js — EM-E8b case A (U48): A TICK-MINTED ROSTER ROW PERSISTS, through
 * the SAME outbox the advance already carries, and through no second writer of the save row.
 *
 * THE MEASUREMENT THIS FILE WAS WRITTEN FROM. At EM-E8's tip (8df38ce91), over the REAL
 * advance in LOCAL mode, a tick that applied an add-decree on the active save left:
 *   the live active view — the newcomer present, `dmLayer.minted` one row;
 *   the library row     — the newcomer ABSENT, `dmLayer.minted` EMPTY;
 *   the DURABLE save    — the newcomer ABSENT, `dmLayer.minted` EMPTY, and the registry
 *                         already reading `applied`.
 * A durable record claiming the table's order had been carried out, over a saved world that
 * held no such person. The roster half ran AFTER `flushWorldPulsePersist`, so the outbox had
 * carried the PRE-MINT record; and it wrote only the view, so the row the outbox reads never
 * moved at all. Both halves are cured here.
 *
 * ⛔ NOTHING HERE IS A MOCK OF THE MECHANISM. The settlement is generated by the real
 * pipeline, the advance is the store's own `advanceCampaignWorld` through the real kernel and
 * EM-E1's real tick hook, the registry is EM-C1's, the re-derivation is the real engine, and
 * the library is the REAL save service in local mode — every durable row below has been
 * through `saves.save` → the advance's own flush → `saves.list`.
 *
 * ⛔ ONE MEMBER, DELIBERATELY. The local save service's `update` is read-modify-write over the
 * WHOLE library array, so two members flushed in parallel lose one another's row (NOTICED at
 * EM-E8b, not this member's to cure). A one-member campaign makes the durable read below a
 * measurement of THIS mechanism rather than of that race. Case B's suite carries the
 * two-member claim and reads the rows and the outbox payload instead.
 *
 * ⛔ NO ARM ASSERTS INSIDE A LOOP: each matrix is COLLECTED and then asserted once.
 *
 * @enforced-by this test
 */
