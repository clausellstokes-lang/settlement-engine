/** The three slices the advance, the library and the edit door actually live on. */
const makeStore = () => create(immer((...args) => ({
  ...stubSlice(),
  ...createSettlementSlice(...args),
  ...createCampaignSlice(...args),
  ...createCampaignWorldPulseSlice(...args),
})));

/** A save ENVELOPE a canon member of a campaign carries, with an explicit row id. */
const envelope = (id, record) => ({
  id,
  name: String(record.name),
  tier: String(record.tier),
  seed: String(record._seed),
  settlement: clone(record),
  phase: 'canon',
  campaignState: { phase: 'canon', eventLog: [], locks: {}, systemState: {} },
  config: { ...CONFIG },
  aiData: {},
  versionHistory: [],
});

/** The LIVE pool catalogue for the pools the npc add-op names, read from its producer. */
function poolsFor(cardType, record) {
  return Object.fromEntries(addOpPayloadFor(cardType)
    .filter((row) => typeof row.pool === 'string')
    .map((row) => [row.pool, poolValues(row.pool, record)]));
}

/** Stage ONE add-npc decree on the hydrated save, exactly as a CREATE door would. */
function stageNewcomer(store, name) {
  const record = store.getState().settlement;
  return stageAddDecreeIntent(store.getState, store.setState, {
    cardType: 'npc',
    values: { name, role: poolValues('npc.role', record)[0] },
    pools: poolsFor('npc', record),
    orderedAt: NOW,
  });
}

/**
 * A canonized ONE-MEMBER campaign whose member is a real generated world, seeded into the
 * REAL library first so the durable row below is one the product wrote.
 * @returns {Promise<{store: any, record: object}>}
 */
async function seedCampaign(seed) {
  installLocalStorage();
  const record = world(seed);
  await saves.save(envelope(HOME, record));
  const library = await saves.list();
  const store = makeStore();
  store.setState((state) => {
    state.savedSettlements = clone(library).map((row) => ({
      ...row,
      phase: 'canon',
      campaignState: { phase: 'canon', eventLog: [], locks: {}, systemState: {} },
    }));
    state.campaigns = [{
      id: 'camp-1',
      name: 'Realm',
      accessState: 'active',
      settlementIds: [HOME],
      regionalGraph: ensureRegionalGraph({ edges: [] }, { now: NOW }),
      wizardNews: ensureWizardNewsFeed(undefined, { now: NOW }),
      worldState: ensureWorldState(
        { rngSeed: `tick-persistence-${seed}`, tick: 0, canonizedAt: NOW },
        { id: 'camp-1', name: 'Realm' },
      ),
    }];
    state.campaignsLoaded = true;
    state.activeSaveId = HOME;
    state.settlement = clone(record);
    state.phase = 'canon';
  });
  return { store, record };
}

/** Mirror the live view onto its library row AND its durable row, as a save would. */
async function saveTheView(store) {
  const record = clone(store.getState().settlement);
  store.setState((state) => {
    const idx = state.savedSettlements.findIndex((row) => String(row.id) === HOME);
    state.savedSettlements[idx].settlement = record;
  });
  await saves.update(HOME, { settlement: record });
}

const advance = (store) =>
  store.getState().advanceCampaignWorld('camp-1', 'one_week', { now: NOW });

/** Every roster id on a record, so "exactly once" is countable. */
const npcIdsOf = (record) => (record?.npcs || []).map((npc) => npc.id);
const mintedKeysOf = (record) => Object.keys(record?.dmLayer?.minted || {});
const durableRow = async () => (await saves.list()).find((row) => String(row.id) === HOME);

describe('EM-E8b A — a tick-minted roster row reaches the durable save through the advance\'s own outbox', () => {
  it('A1 puts the newcomer on the DURABLE save after the tick, with NO manual save, exactly once', async () => {
    const { store } = await seedCampaign('e8b-a1');
    const staged = stageNewcomer(store, 'Alda');
    await saveTheView(store);
    const before = await durableRow();

    const result = await advance(store);
    const after = await durableRow();

    expect(staged.ok, 'the binder staged the CREATE intent').toBe(true);
    expect(result?.ok, 'and the real advance ran to a committed result').not.toBe(false);
    expect((before.settlement.decrees || []).map((row) => row.status),
      'the durable save carried the decree WAITING before the tick').toEqual(['pending']);
    // anchored: the row above holds the same decree as pending, so the status below is this
    // tick applying it rather than a fixture that was always applied.
    expect((after.settlement.decrees || []).map((row) => row.status),
      'and the tick applied it — which is what makes the roster below owed').toEqual(['applied']);
    expect(npcIdsOf(after.settlement).filter((id) => id === staged.decreeId).length,
      'THE MEASUREMENT: the newcomer is on the DURABLE save, exactly once, with no manual save')
      .toBe(1);
    expect(mintedKeysOf(after.settlement),
      'and the durable layer records who exists, or the next tick would mint a second person')
      .toEqual([staged.decreeId]);
    expect(npcIdsOf(after.settlement).length,
      'the durable roster grew by exactly one')
      .toBe(npcIdsOf(before.settlement).length + 1);
    expect(after.settlement.npcs.find((npc) => npc.id === staged.decreeId).name,
      'wearing the name the DM typed').toBe('Alda');
  }, 120000);

  it('A2 leaves the live view, the library row and the durable save as ONE record, never a split', async () => {
    const { store } = await seedCampaign('e8b-a2');
    const staged = stageNewcomer(store, 'Bern');
    await saveTheView(store);

    await advance(store);
    const live = store.getState().settlement;
    const row = store.getState().savedSettlements.find((entry) => String(entry.id) === HOME);
    const durable = await durableRow();
    const rosters = [npcIdsOf(live), npcIdsOf(row.settlement), npcIdsOf(durable.settlement)];
    const layers = [mintedKeysOf(live), mintedKeysOf(row.settlement), mintedKeysOf(durable.settlement)];

    expect(rosters[0].includes(staged.decreeId),
      'the live view holds the newcomer, or the two comparisons below compare nothing').toBe(true);
    expect(rosters, 'all three homes hold the SAME roster: a view and a row that disagreed about'
      + ' who exists is exactly the split design §12\'s finding 5 refuses')
      .toEqual([rosters[0], rosters[0], rosters[0]]);
    expect(layers, 'and the SAME layer, because the layer is what the next tick reads to decide'
      + ' who already exists').toEqual([[staged.decreeId], [staged.decreeId], [staged.decreeId]]);
  }, 120000);

  it('A3 folds the minted record into the outbox payload the advance already carries — one op per save, never a second', () => {
    const state = {
      savedSettlements: [
        { id: HOME, settlement: { npcs: [{ id: 'n1' }] }, campaignState: { phase: 'canon' } },
        { id: 'save-born', settlement: { npcs: [{ id: 'n2' }] }, campaignState: { phase: 'canon' } },
      ],
    };
    const carried = [
      { saveId: HOME, settlement: { npcs: [] }, campaignState: { phase: 'canon' } },
      { saveId: 'save-born', createSave: { id: 'save-born', settlement: { npcs: [] } } },
    ];
    const folded = withMintedRosterState(state, carried, [
      { ok: true, saveId: HOME, minted: ['dm:minted:1'] },
      { ok: true, saveId: 'save-born', minted: ['dm:minted:2'] },
      { ok: true, saveId: 'save-absent', minted: ['dm:minted:3'] },
    ]);
    const dormant = withMintedRosterState(state, carried, { ok: true, saveId: HOME, minted: [] });
    const pushed = withMintedRosterState(state, [], { ok: true, saveId: HOME, minted: ['dm:minted:1'] });

    expect(folded.length, 'the payload still holds ONE op per save — a second op for one row is'
      + ' two writers racing for it').toBe(2);
    expect(folded[0].settlement.npcs.map((npc) => npc.id),
      'the ordinary entry carries the MINTED record off the row').toEqual(['n1']);
    expect(folded[1].createSave.settlement.npcs.map((npc) => npc.id),
      'and a WR-3 birth envelope keeps its upsert shape, minted roster and all').toEqual(['n2']);
    expect(pushed.map((update) => update.saveId),
      'a minting save the pulse itself left alone gets its own op, or its mint would persist'
      + ' nowhere').toEqual([HOME]);
    // anchored: the three folds above all moved their payload, so the identity below is the
    // dormant short-circuit and not a function that never composes anything.
    expect(dormant, 'and a tick that minted nobody returns the payload BY REFERENCE, so a dormant'
      + ' advance carries the identical array').toBe(carried);
  });

  it('A4 runs the tick\'s roster half BEFORE the advance\'s one flush, so the mint rides that same flush', () => {
    const source = readFileSync(join(ROOT, ADVANCE_SESSION), 'utf8');
    const bodyStart = source.indexOf('export async function runAdvanceCampaignWorld');
    const bodyEnd = source.indexOf('export async function runResolveIntervalMajors');
    const body = source.slice(bodyStart, bodyEnd);
    const roster = body.indexOf('applyRosterDecreesAtTick');
    const flush = body.indexOf('await flushWorldPulsePersist({');
    const folds = [...body.matchAll(/withMintedRosterState\(/g)].length;
    const flushes = [...body.matchAll(/await flushWorldPulsePersist\(\{/g)].length;

    expect(bodyStart, 'the advance body is where this arm says it is').toBeGreaterThan(-1);
    expect(roster, 'the advance reaches the tick\'s roster half').toBeGreaterThan(-1);
    expect(flushes, 'and flushes its outbox EXACTLY ONCE, which is why the order below decides'
      + ' whether the mint persists at all').toBe(1);
    expect(roster < flush, 'the roster half runs BEFORE that flush: after it, the outbox had'
      + ' already carried the PRE-MINT record and the durable save read `applied` over a world'
      + ' with nobody on it').toBe(true);
    expect(folds, 'and its receipt is folded into the payload that flush carries, exactly once')
      .toBe(1);
  });

  it('A5 leaves a world with NO decrees exactly as it was — no layer, no registry, nothing minted', async () => {
    const { store } = await seedCampaign('e8b-a5');
    const before = await durableRow();

    const result = await advance(store);
    const after = await durableRow();

    expect(result?.ok, 'the advance ran, or the absences below measure a tick that never happened')
      .not.toBe(false);
    expect(Object.hasOwn(before.settlement, 'decrees'),
      'the fixture carried no registry to begin with').toBe(false);
    // anchored: A1 over the same seedCampaign harness DOES mint both keys, so the two absences
    // below are this world having no decree rather than a durable row nothing ever reaches.
    expect(Object.hasOwn(after.settlement, 'dmLayer'),
      'and the tick mints no layer on it — the save\'s shape is the owner\'s').toBe(false);
    expect(Object.hasOwn(after.settlement, 'decrees'),
      'nor a registry key it never had').toBe(false);
  }, 120000);
});
