/**
 * rosterOpsAtTick.test.js — EM-E8 case C: an applied add-decree mints its row AT THE TICK,
 * once, and the undo path takes it back (design §2.6's head of the tick, §12.1's rewind,
 * §14's regeneration from the layer).
 *
 * THE CLAIM, END TO END AND THROUGH THE REAL PARTS: the store binder stages a CREATE intent
 * (EM-E8 A), EM-E1's own tick hook marks it applied, the store's tick half writes the minted
 * row to the DM layer through the ONE writer and re-derives ONCE through EM-B2a4's scoped
 * seam, and the newcomer is on the record. A second tick adds nobody. E1's
 * `retractDecreesOfTick` plus the snapshot restore takes the newcomer back.
 *
 * ⛔ NOTHING HERE IS A MOCK OF THE MECHANISM. The settlement is generated by the real
 * pipeline, the tick is EM-E1's real `applyDecreesToSaves`, the registry is EM-C1's, and the
 * re-derivation is the real engine reached through the store's own lazy seat.
 *
 * ⛔ NO ARM ASSERTS INSIDE A LOOP: each matrix is COLLECTED and then asserted once.
 *
 * @enforced-by this test
 */

import { describe, expect, it, vi } from 'vitest';
import { create } from 'zustand';
import { immer } from 'zustand/middleware/immer';

// The durable cloud-write seam a hydrated save reaches. Stubbed so this suite is headless.
vi.mock('../../src/lib/saves.js', () => ({
  saves: { update: vi.fn(() => Promise.resolve()), isConfigured: false },
}));

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { compareCodepoint } from '../../src/domain/deterministicSort.js';
import { SAVED_ONLY_KEYS } from '../../src/domain/edit/recordRegister.js';
import { poolValues } from '../../src/domain/edit/pools.js';
import { applyDecreesToSaves, retractDecreesOfTick } from '../../src/domain/worldPulse/decreeHook.js';
import { draftPeaceOffer, withPeaceOffer } from '../../src/domain/worldPulse/peaceTermsDrafting.js';
import { generateSettlementPipeline } from '../../src/generators/generateSettlementPipeline.js';
import { createSettlementSlice } from '../../src/store/settlementSlice.js';
import {
  addOpPayloadFor,
  applyRosterDecreesAtTick,
  selectDecrees,
  stageAddDecreeIntent,
} from '../../src/store/editSlice.js';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const ADVANCE_SESSION = 'src/store/campaignAdvanceSession.js';
const SAVE_ID = 'save-1';
const SEED = 'golden-master-v3';
const NOW = '2026-09-23T12:00:00.000Z';
const TICK_REF = 'world_pulse.campaign-1.1';

const CONFIG = Object.freeze({ settType: 'thorp', culture: 'germanic', terrain: 'grassland' });

const stubSlice = () => ({
  auth: { user: null, tier: 'free', loading: false },
  config: { ...CONFIG }, institutionToggles: {}, categoryToggles: {},
  goodsToggles: {}, servicesToggles: {}, customContent: {}, importedNeighbour: null,
  campaigns: [], campaignsLoaded: true,
  isTierAllowed: () => true, canSave: () => true, maxSaves: () => 50, setPurchaseModalOpen: () => {},
});

/** ONE real world, generated once and cloned per store, so the suite pays the engine once. */
const WORLD = generateSettlementPipeline({ ...CONFIG }, null, { seed: SEED, customContent: {} });

/** A store with the REAL settlement slice, hydrated as opening a DRAFT library save. */
function makeStore() {
  const store = create(immer((...a) => ({ ...stubSlice(...a), ...createSettlementSlice(...a) })));
  store.setState((state) => {
    state.settlement = structuredClone(WORLD);
    state.savedSettlements = [{
      id: SAVE_ID, name: WORLD.name, tier: WORLD.tier, config: { ...CONFIG },
      settlement: structuredClone(WORLD),
      campaignState: { phase: 'draft', eventLog: [], systemState: {}, editedAt: null },
      timestamp: '2020-01-01T00:00:00.000Z',
    }];
    state.activeSaveId = SAVE_ID;
    state.phase = 'draft';
  });
  return store;
}

/** The LIVE pool catalogue for the pools the npc add-op names, read from its producer. */
function poolsFor(cardType, world) {
  return Object.fromEntries(addOpPayloadFor(cardType)
    .filter((row) => typeof row.pool === 'string')
    .map((row) => [row.pool, poolValues(row.pool, world)]));
}

/** Stage ONE add-npc decree on the live save, exactly as a CREATE door would. */
function stageNewcomer(store, name) {
  const world = store.getState().settlement;
  return stageAddDecreeIntent(store.getState, store.setState, {
    cardType: 'npc',
    values: { name, role: poolValues('npc.role', world)[0] },
    pools: poolsFor('npc', world),
    orderedAt: NOW,
  });
}

/**
 * RUN EM-E1'S REAL TICK over the live save and write the amended registry back, which is
 * exactly what `applyWorldPulseResultToState` does with the kernel's own result.
 * @returns {number} the number of causes the hook produced
 */
function runTick(store) {
  const save = { id: SAVE_ID, settlement: { decrees: selectDecrees(store.getState()) } };
  const applied = applyDecreesToSaves({ tick: 1 }, [save], TICK_REF, { now: NOW });
  const rows = applied.saves[0].settlement.decrees;
  store.setState((state) => { state.settlement.decrees = rows; });
  return applied.causes.length;
}

/** Every roster id on a record, so "exactly once" is countable. */
const npcIdsOf = (record) => (record.npcs || []).map((npc) => npc.id);

describe('EM-E8 C — an applied add-decree mints its row at the tick, once, and the undo path takes it back', () => {
  it('C1 puts the newcomer on the record after the tick, EXACTLY ONCE, and a second tick adds nobody', async () => {
    const store = makeStore();
    const staged = stageNewcomer(store, 'Alda');
    const before = npcIdsOf(store.getState().settlement);
    const causes = runTick(store);
    const beforeMint = npcIdsOf(store.getState().settlement);

    const first = await applyRosterDecreesAtTick(store.getState, store.setState, { saveId: SAVE_ID });
    const afterFirst = npcIdsOf(store.getState().settlement);
    const layerAfter = store.getState().settlement.dmLayer;

    const second = await applyRosterDecreesAtTick(store.getState, store.setState, { saveId: SAVE_ID });
    const afterSecond = npcIdsOf(store.getState().settlement);

    expect(staged.ok, 'the binder staged the CREATE intent').toBe(true);
    expect(causes, 'and EM-E1\'s own hook applied exactly one decree at this tick').toBe(1);
    expect(before.includes(staged.decreeId), 'the record carried no newcomer before the tick')
      .toBe(false);
    // anchored: the same read after the hook still finds nobody, so the mint below is THIS
    // member's act and not something the tick hook already did.
    expect(beforeMint.includes(staged.decreeId),
      'and marking a decree applied is not itself a world effect — E1 leaves that to the binder')
      .toBe(false);
    expect(first.ok, 'the tick half accepted the live save').toBe(true);
    expect(first.minted, 'and minted exactly the newcomer the decree named').toEqual([staged.decreeId]);
    expect(first.rederived, 'through ONE re-derivation on the scoped seam').toBe(true);
    expect(afterFirst.filter((id) => id === staged.decreeId).length,
      'the newcomer is on the record EXACTLY ONCE').toBe(1);
    expect(afterFirst.length, 'and the roster grew by exactly one').toBe(before.length + 1);
    expect((store.getState().settlement.npcs || []).find((npc) => npc.id === staged.decreeId).name,
      'wearing the name the DM typed').toBe('Alda');
    expect(Object.keys(layerAfter.minted), 'the layer records who exists, which is what makes the'
      + ' second tick a no-op').toEqual([staged.decreeId]);
    expect(second.minted, 'a SECOND tick over the same registry mints nobody').toEqual([]);
    expect(second.rederived, 'and reaches the re-derivation lane not at all').toBe(false);
    expect(afterSecond, 'so the roster is unchanged, member for member').toEqual(afterFirst);
  });

  it('C2 gives the newcomer back on the undo path: the decree returns to pending and the restored world has nobody', async () => {
    const store = makeStore();
    const staged = stageNewcomer(store, 'Bern');
    const preTick = structuredClone(store.getState().settlement);
    runTick(store);
    await applyRosterDecreesAtTick(store.getState, store.setState, { saveId: SAVE_ID });
    const grown = npcIdsOf(store.getState().settlement);

    // THE REWIND, in its two real halves (design §12.1): E1's own inverse of `markApplied`
    // returns the entry to the waiting sequence, and the pre-pulse snapshot restore puts the
    // settlement back — which is where the layer and its minted row live.
    const retracted = retractDecreesOfTick(selectDecrees(store.getState()), TICK_REF);
    store.setState((state) => {
      state.settlement = structuredClone(preTick);
      state.settlement.decrees = structuredClone(retracted);
    });
    const undone = npcIdsOf(store.getState().settlement);
    const statuses = selectDecrees(store.getState()).map((row) => row.status);
    const afterUndo = await applyRosterDecreesAtTick(store.getState, store.setState, { saveId: SAVE_ID });

    // anchored: the grown roster above does carry the newcomer, so the absence below is the
    // rewind working rather than a mint that never happened.
    expect(grown.filter((id) => id === staged.decreeId).length).toBe(1);
    expect(undone.includes(staged.decreeId), 'the restored world has nobody the tick added')
      .toBe(false);
    expect(Object.keys(store.getState().settlement.dmLayer?.minted || {}),
      'and the layer holds no minted row either — the two came back together').toEqual([]);
    expect(statuses, 'the decree is WAITING again, in its own place, never lost').toEqual(['pending']);
    expect(afterUndo.minted, 'and the tick half mints nobody for a PENDING entry: a rewind that'
      + ' left the mint re-appliable would undo nothing').toEqual([]);
  });

  it('C3 carries every SAVED-ONLY key through the re-derivation, which generation cannot produce', async () => {
    const store = makeStore();
    const staged = stageNewcomer(store, 'Cara');
    store.setState((state) => {
      state.settlement.neighbourNetwork = { edges: ['n1'] };
      state.settlement.interSettlementRelationships = [{ npcName: 'Cara', partnerName: 'Ilsa' }];
      state.settlement.crossSettlementConflicts = [{ id: 'c1' }];
      state.settlement.populationHistory = [{ tick: 0, population: 40 }];
      // ⭐ NOTE-14's key joined SAVED_ONLY_KEYS when the register finally classed it, and the
      //    equality below is over that list, so this fixture has to carry it or the arm would
      //    red on a key nobody seeded rather than on a key the re-derivation dropped. SEEDED
      //    WITH THE PRODUCT'S OWN WRITER, never typed: `withPeaceOffer` is the writer the
      //    register names, so the shape here cannot drift from the shape a real offer has.
      state.settlement.peaceOffers = withPeaceOffer({}, draftPeaceOffer({
        fromId: 'ilsa-town', toId: 'cara-town', terms: [{ kind: 'tribute', years: 3 }],
        budgetSpent: 2, tick: 0,
      })).peaceOffers;
    });
    const before = structuredClone(store.getState().settlement);
    runTick(store);
    const receipt = await applyRosterDecreesAtTick(store.getState, store.setState, { saveId: SAVE_ID });
    const after = store.getState().settlement;
    const survived = [...SAVED_ONLY_KEYS].sort(compareCodepoint)
      .filter((key) => Object.hasOwn(after, key));

    expect(receipt.rederived, 'the record WAS replaced by a fresh re-derivation, or this arm'
      + ' measures a record nothing rebuilt').toBe(true);
    expect(survived, 'every SAVED-ONLY key of EM-R0a\'s register survived — the SEVEN nothing in'
      + ' generation writes, so a re-derivation that simply replaced the record would DELETE them')
      .toEqual([...SAVED_ONLY_KEYS].sort(compareCodepoint));
    expect(after.neighbourNetwork, 'and each one is carried VERBATIM')
      .toEqual(before.neighbourNetwork);
    expect(after.interSettlementRelationships).toEqual(before.interSettlementRelationships);
    expect(after.crossSettlementConflicts).toEqual(before.crossSettlementConflicts);
    expect(after.populationHistory).toEqual(before.populationHistory);
    expect(after.peaceOffers, 'NOTE-14\'s key was dropped by the re-derivation').toEqual(before.peaceOffers);
    expect(after.decrees.map((row) => row.id), 'the REGISTRY above all: losing it would erase the'
      + ' DM\'s own history at the very tick that applied it').toEqual([staged.decreeId]);
    expect(after.dmLayer.minted[staged.decreeId], 'and the layer is THIS member\'s own write, never'
      + ' carried from the pre-run record').toEqual({ kind: 'npc', name: 'Cara', role: after.npcs.find((npc) => npc.id === staged.decreeId).role });
    expect(typeof after._seed, 'the seed survives, which is what keeps the next mint stable')
      .toBe('string');
  });

  it('C5 moves the record and the layer in ONE write, so the two homes can never disagree', async () => {
    const store = makeStore();
    const staged = stageNewcomer(store, 'Dain');
    runTick(store);
    let writes = 0;
    const counted = (updater) => { writes += 1; return store.setState(updater); };
    const dormantStore = makeStore();
    let dormantWrites = 0;
    const dormantCounted = (updater) => { dormantWrites += 1; return dormantStore.setState(updater); };

    const receipt = await applyRosterDecreesAtTick(store.getState, counted, { saveId: SAVE_ID });
    const after = store.getState().settlement;
    const dormant = await applyRosterDecreesAtTick(dormantStore.getState, dormantCounted, { saveId: SAVE_ID });

    expect(receipt.minted, 'the mint landed, or the write count below measures nothing')
      .toEqual([staged.decreeId]);
    expect(writes, 'EXACTLY ONE store write: the layer is the INPUT and the record the OUTPUT, and'
      + ' a write that landed one without the other would be a PERMANENT split — the next tick'
      + ' reads the layer to decide who already exists').toBe(1);
    expect(Object.hasOwn(after.dmLayer.minted, staged.decreeId), 'the layer holds the newcomer')
      .toBe(true);
    expect(npcIdsOf(after).includes(staged.decreeId), 'and so does the record, after that one write')
      .toBe(true);
    // anchored: the write above did happen, so a zero count on the dormant store is the
    // short-circuit and not a function that never writes at all.
    expect(dormant.minted, 'a save with no APPLIED add-decree mints nobody').toEqual([]);
    expect(dormantWrites, 'and touches the store not at all').toBe(0);
  });

  it('C4 is wired at the advance\'s one tick site, behind a DYNAMIC edge and a dormancy guard', () => {
    const source = readFileSync(join(REPO_ROOT, ADVANCE_SESSION), 'utf8');
    const calls = [...source.matchAll(/applyRosterDecreesAtTick/g)].length;
    const dynamic = [...source.matchAll(/await import\('\.\/editSlice\.js'\)/g)].length;
    const staticEdge = [...source.matchAll(/^import[\s\S]*?from '\.\/editSlice\.js';$/gm)].length;

    expect(calls, 'the advance session reaches the tick half at EXACTLY ONE site').toBe(1);
    expect(dynamic, 'by a DYNAMIC import, which is the estate\'s own store idiom and what keeps'
      + ' the edit leaf out of every eager closure').toBe(1);
    // anchored: the dynamic edge above is present, so a zero static count is the absence of a
    // second edge and not a reader that matches nothing.
    expect(staticEdge, 'and never a STATIC one').toBe(0);
    expect(source.includes('Array.isArray(liveDecrees) && liveDecrees.length > 0'),
      'behind the dormancy guard, so a save with no decrees reaches no import at all').toBe(true);
  });
});
