/**
 * hookThemeTotality.walker.test.js — HABITAT REMOVAL for VOCABULARY ROT
 * (wave HK-1, docs/DESIGN_HOOK_NONREDUNDANCY.md §3).
 *
 * THE CLASS: the theme map names the dramatic BEAT of every
 * authored hook template so the retention layer can tell "two actors, one story"
 * from "two stories". A theme map is a PARALLEL structure — nothing in the
 * language ties it to the pools it describes — so it rots in three silent ways:
 *
 *   1. a NEW authored template lands untagged      ⇒ it answers `untyped`, is
 *      exempt from theme retention forever, and the repeat it was written to
 *      avoid comes back invisibly;
 *   2. a template's PROSE is edited (a typo fix is enough)  ⇒ its key no longer
 *      folds to the map's key, and the tag silently detaches from live content;
 *   3. a theme is invented at the tagging site ('mystery', 'trouble')  ⇒ the
 *      closed vocabulary the finite-semantics law requires quietly becomes an
 *      open one, and dedup starts comparing incomparable buckets.
 *
 * None of the three fails anything at runtime: an untagged hook is merely
 * retained, which is the SAFE direction, which is exactly why the rot is
 * invisible. So the vocabulary is held structurally instead — by EXACT SET
 * EQUALITY in both directions against the live pools. Add a template without a
 * tag and this reds; edit a template's prose without moving its tag and this
 * reds; delete a template and leave its tag and this reds.
 *
 * WHY BOTH DIRECTIONS: a one-directional "every tag resolves" check passes
 * happily while half the pool is untagged, and a one-directional "every template
 * is tagged" check passes while the map carries rows for prose that no longer
 * exists. Only equality catches both, and only equality makes the failure
 * message name the exact drifted strings.
 *
 * WHY THIS IS NOT A GENERATION TEST: it reads two authored data tables and one
 * pure lookup. No RNG, no pipeline, no seeds — so the seed-totality and
 * anchored-negative idioms that govern generation trees do not apply here, and
 * every assertion below is a set comparison whose subject is proven live by the
 * non-vacuity floors in the first test.
 *
 * RE-POINTED BY BUILD-THEMES (DEPTH-3, 2026-11-20; the chair's order of 19:28 UTC and its conditions C1-C3).
 * The theme is now AUTHORED beside its line, src/data/npcData.js :: NPC_FACTION_LOYALTY_THEMES (per pool key,
 * index-aligned), and first paint's src/domain/hookThemes.js holds only THEME_DIGEST (theme -> base-36
 * fnv1a32(hookThemeKey(text)) of each line), generated by the door scripts/hook-theme-digest.mjs. So the map's
 * "rows" are now the (pool, index) cells, and this walker holds, at full strength:
 *   - EXACT SET EQUALITY both ways between the pools and the theme arrays: the same pool keys, every array
 *     index-aligned (one theme per line, none spare), every value a HOOK_THEMES member;
 *   - THE DIGEST IS FRESH (C1): the block in hookThemes.js is byte-equal to the one the door computes from the
 *     pools (the door's --check, in-test), so a line added, moved or reworded without the door reds here;
 *   - NO TWO DISTINCT LIVE POOL TEXTS SHARE A HASH, and every live line classifies to ITS OWN cell's theme;
 *   - hookThemes.js imports nothing from src/data/ (the reason the digest exists);
 *   - THE COLLISION WALK (C2) over what is cheap in a test: the live pools and the stored saves under
 *     tests/fixtures/legacy-saves/ (their texts, recomputed here), and the golden master's and the hxd births'
 *     folded texts' hashes as taken at the base (tests/fixtures/hookThemeAnswers.base.json): no stored text
 *     outside the pools hashes to a tagged line, and every typed one keeps its theme. The whole corpus (golden 525,
 *     census 720, hxd, legacy) is walked over its TEXTS by docs/chair/2026-11-20/content/depth/themes/
 *     corpus-scan.mjs --check, too slow for a test; this walker says so rather than pretend.
 */
import { describe, expect, test } from 'vitest';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NPC_FACTION_LOYALTY, NPC_FACTION_LOYALTY_THEMES, STRESS_ECONOMIC_EFFECTS } from '../../src/data/npcData.js';
import {
  HOOK_THEMES,
  UNTYPED,
  THEME_DIGEST,
  THEME_OF_REL_ARCHETYPE,
  hookThemeKey,
  isHookTheme,
  themeOfText,
  themeOfRelArchetype,
} from '../../src/domain/hookThemes.js';
import { lineText } from '../../src/domain/facts/drawDeclared.js';
import { collectPlotHooks } from '../../src/domain/dossier/plotHooks.js';
import { deriveAllStructuredHooks } from '../../src/domain/hookEscalation.js';
import { normalizeSettlement } from '../../src/domain/normalizeSettlement.js';
import {
  DIGEST_FILE,
  computeThemeDigest,
  digestKeyOf,
  digestProblems,
  liveDigestBlock,
  readDigestBlock,
} from '../../scripts/hook-theme-digest.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
/** Every authored loyalty template the generator can draw, in pool order (CENSUS-3e: a declared row is `{ text, needs }`; its text is the template). */
const livePoolTemplates = Object.values(NPC_FACTION_LOYALTY).flat().map(lineText);
/** Every (pool, index) cell with its text and its authored theme. */
const cells = Object.entries(NPC_FACTION_LOYALTY).flatMap(([pool, lines]) => lines.map((line, i) => ({
  pool, i, text: lineText(line), theme: /** @type {Record<string, readonly string[]>} */ (NPC_FACTION_LOYALTY_THEMES)[pool]?.[i],
})));
/** Every relationship archetype the generator can stamp. */
const liveArchetypeKeys = Object.keys(STRESS_ECONOMIC_EFFECTS);
/** The digest's hash -> theme, read straight off the generated block. */
const digestEntries = Object.entries(THEME_DIGEST).flatMap(([theme, keys]) => keys.split(' ').map((h) => /** @type {[string, string]} */ ([h, theme])));
const digestTheme = new Map(digestEntries);

const sortedUnique = (/** @type {string[]} */ xs) => [...new Set(xs)].sort();

describe('HK-1 hook-theme vocabulary — totality against the live pools', () => {
  test('guard-the-guard: the pools, the theme arrays and the digest are all live and populated', () => {
    // Every equality below is vacuously true against empty sets. If an import
    // silently resolved to nothing (a rename, a barrel reshuffle, a data file
    // emptied), these floors red FIRST and name the cause, instead of the set
    // comparisons passing on two empty arrays. Floors are the measured sizes
    // (270 lines at BUILD-THEMES' base 2582075ed); they tighten toward reality
    // and are never lowered to admit a budget.
    expect(livePoolTemplates.length, 'NPC_FACTION_LOYALTY resolved empty or tiny').toBeGreaterThanOrEqual(270);
    expect(Object.values(NPC_FACTION_LOYALTY_THEMES).flat().length, 'NPC_FACTION_LOYALTY_THEMES resolved empty').toBeGreaterThanOrEqual(270);
    expect(digestEntries.length, 'THEME_DIGEST resolved empty').toBeGreaterThanOrEqual(270);
    expect(liveArchetypeKeys.length, 'STRESS_ECONOMIC_EFFECTS resolved empty or tiny').toBeGreaterThanOrEqual(18);
    expect(HOOK_THEMES.length, 'the closed vocabulary resolved empty').toBeGreaterThanOrEqual(20);
  });

  test('TOTALITY: the theme arrays EQUAL the live loyalty pools, both directions, index-aligned', () => {
    const pools = sortedUnique(Object.keys(NPC_FACTION_LOYALTY));
    const tagged = sortedUnique(Object.keys(NPC_FACTION_LOYALTY_THEMES));
    expect(tagged, 'NPC_FACTION_LOYALTY_THEMES must carry exactly the pool keys of NPC_FACTION_LOYALTY').toEqual(pools);
    const misaligned = pools
      .map((pool) => ({ pool, lines: NPC_FACTION_LOYALTY[/** @type {keyof typeof NPC_FACTION_LOYALTY} */ (pool)].length, themes: (/** @type {Record<string, readonly string[]>} */ (NPC_FACTION_LOYALTY_THEMES)[pool] || []).length }))
      .filter(({ lines, themes }) => lines !== themes);
    expect(
      misaligned,
      `\nA pool and its theme array differ in length. Every authored line carries exactly one theme from the closed`
      + ` set at ITS OWN INDEX in src/data/npcData.js NPC_FACTION_LOYALTY_THEMES (a tranche appends a theme where it`
      + ` appends a line), then the door runs: node scripts/hook-theme-digest.mjs\n`,
    ).toEqual([]);
    const untagged = cells.filter((c) => typeof c.theme !== 'string');
    expect(untagged.map((c) => `${c.pool}[${c.i}] ${c.text}`), 'authored line(s) with NO theme').toEqual([]);
  });

  test('THE DIGEST IS FRESH: hookThemes.js THEME_DIGEST is the block the door computes from the pools (the door\'s --check, in-test)', () => {
    expect(digestProblems(NPC_FACTION_LOYALTY, NPC_FACTION_LOYALTY_THEMES), 'the door would refuse').toEqual([]);
    const standing = readDigestBlock(readFileSync(join(ROOT, DIGEST_FILE), 'utf8'));
    expect(standing, `no generated block in ${DIGEST_FILE}`).not.toBeNull();
    expect(
      standing,
      `\n${DIGEST_FILE}'s THEME_DIGEST is not the one the pools ask for: a line was added, moved or reworded, or a`
      + ` theme moved, without the door. Run: node scripts/hook-theme-digest.mjs (never hand-edit the block).\n`,
    ).toBe(liveDigestBlock());
    expect(THEME_DIGEST, 'the module\'s live object').toEqual(computeThemeDigest(NPC_FACTION_LOYALTY, NPC_FACTION_LOYALTY_THEMES));
  });

  test('TOTALITY: the relationship archetype tags EQUAL the live archetype keys, both directions', () => {
    const tagged = sortedUnique(Object.keys(THEME_OF_REL_ARCHETYPE));
    const live = sortedUnique(liveArchetypeKeys);
    expect(
      live.filter((k) => !tagged.includes(k)),
      'relationship archetype(s) in STRESS_ECONOMIC_EFFECTS with no theme in THEME_OF_REL_ARCHETYPE',
    ).toEqual([]);
    expect(
      tagged.filter((k) => !live.includes(k)),
      'THEME_OF_REL_ARCHETYPE row(s) naming an archetype that no longer exists',
    ).toEqual([]);
  });

  test('CLOSURE: every assigned theme is a member of the closed vocabulary', () => {
    const assigned = [
      ...cells.map((c) => c.theme),
      ...digestEntries.map(([, theme]) => theme),
      ...Object.values(THEME_OF_REL_ARCHETYPE),
    ];
    const outsiders = sortedUnique(assigned.filter((theme) => !isHookTheme(theme)).map(String));
    expect(
      outsiders,
      `\nTheme value(s) outside HOOK_THEMES. Closure is the law (finite semantics):`
      + ` a new beat is a VOCABULARY AMENDMENT to HOOK_THEMES, reviewed, never an`
      + ` ad-hoc string at the tagging site:\n${outsiders.join('\n')}\n`,
    ).toEqual([]);
    // The sentinel is not a theme. If it ever became one, `untyped` hooks would
    // start being deduped against each other — the exact thing HK-LAW-3 forbids.
    expect(isHookTheme(UNTYPED), 'UNTYPED must never be a member of the closed vocabulary').toBe(false);
  });

  test('EXACTLY ONE theme per template: no two distinct live pool texts share a hash, and each line classifies to its own cell', () => {
    /** @type {Map<string, string>} */ const foldOf = new Map();
    const shared = [];
    for (const { text } of cells) {
      const fold = hookThemeKey(text);
      const h = digestKeyOf(fold);
      if (foldOf.has(h) && foldOf.get(h) !== fold) shared.push(`${h}: ${foldOf.get(h)} | ${fold}`);
      foldOf.set(h, fold);
    }
    expect(shared, '\nTwo distinct live pool texts share a digest hash, so one would answer the other\'s theme:\n').toEqual([]);
    // The walker's own round-trip through the PUBLIC classifier, not the private map: every live
    // line answers the theme authored at its own index.
    const wrong = cells.filter((c) => themeOfText(c.text) !== c.theme);
    expect(wrong.map((c) => `${c.pool}[${c.i}] wants ${c.theme}, answers ${themeOfText(c.text)}`), 'live line(s) that themeOfText() misclassifies').toEqual([]);
    expect(digestEntries.length, 'the digest carries exactly one hash per live line').toBe(cells.length);
  });

  test('ONE HOME: hookThemes.js imports nothing from src/data/', () => {
    const source = readFileSync(join(ROOT, DIGEST_FILE), 'utf8');
    const specifiers = [...source.matchAll(/(?:^|\n)\s*(?:import|export)\b[^;]*?\bfrom\s*['"]([^'"]+)['"]|\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g)].map((m) => m[1] || m[2]);
    // anchored: the module's one import (the kernel's prose hash) is read, so "none from src/data" is not read over nothing
    expect(specifiers).toContain('../kernel/proseHash.js');
    expect(specifiers.filter((s) => /(^|\/)data\//.test(s)), 'hookThemes.js must not load the data module (first paint)').toEqual([]);
  });

  test('THE COLLISION WALK (C2, the cheap part): no stored text outside the pools hashes to a tagged line, and the typed keep their theme', () => {
    const poolFolds = new Set(cells.map((c) => hookThemeKey(c.text)));
    // the stored saves, their texts recomputed (every text a reader of themeOfText is handed)
    const stored = [];
    for (const file of ['april-2026-v1.json', 'people-car-v1-2026-11-07.json']) {
      for (const entry of JSON.parse(readFileSync(join(ROOT, 'tests/fixtures/legacy-saves', file), 'utf8'))) {
        const town = normalizeSettlement(entry.settlement);
        for (const npc of town?.npcs || []) for (const h of npc?.plotHooks || []) stored.push(typeof h === 'string' ? h : h?.text);
        for (const h of collectPlotHooks(town)) stored.push(h?.text);
        for (const h of deriveAllStructuredHooks(town)) stored.push(h?.text);
      }
    }
    const folds = sortedUnique([...poolFolds, ...stored.filter((t) => typeof t === 'string').map(hookThemeKey)]);
    const outside = folds.filter((f) => !poolFolds.has(f));
    // anchored: the saves yield texts in no pool, so the intruder check is not read over nothing
    expect(outside.length).toBeGreaterThan(0);
    /** @type {Map<string, string>} */ const foldOf = new Map();
    const shared = [];
    for (const f of folds) { const h = digestKeyOf(f); if (foldOf.has(h)) shared.push(h); foldOf.set(h, f); }
    expect(shared, 'two distinct folded texts (pools + stored saves) share a hash').toEqual([]);
    expect(outside.filter((f) => digestTheme.has(digestKeyOf(f))), 'a stored text in no pool hashes to a tagged line').toEqual([]);

    // the golden master's and the hxd births' folded texts' hashes, as taken at the base
    const fixture = JSON.parse(readFileSync(join(ROOT, 'tests/fixtures/hookThemeAnswers.base.json'), 'utf8'));
    for (const part of ['golden', 'hxd', 'legacy']) {
      const answers = /** @type {Record<string, string[]>} */ (fixture.parts[part]);
      const untyped = answers[UNTYPED] || [];
      const typed = Object.entries(answers).filter(([a]) => a !== UNTYPED).flatMap(([a, hs]) => hs.map((h) => [h, a]));
      // anchored: each part holds both kinds
      expect(untyped.length, `${part}: untyped hashes`).toBeGreaterThan(0);
      expect(typed.length, `${part}: typed hashes`).toBeGreaterThan(0);
      expect(untyped.filter((h) => digestTheme.has(h)), `${part}: a text untyped at the base now hashes to a tagged line`).toEqual([]);
      expect(typed.filter(([h, a]) => digestTheme.get(h) !== a), `${part}: a text typed at the base answers another theme`).toEqual([]);
    }
  });

  test('HK-LAW-3: free prose and near-miss prose are UNTYPED — the lookup is exact, never fuzzy', () => {
    // The liveness anchor for every negative below: a real template DOES classify
    // through this same call, so "untyped" here measures exactness rather than a
    // dead lookup table.
    const anchorTemplate = livePoolTemplates[0];
    expect(themeOfText(anchorTemplate), 'anchor: a real template must classify').toBe(cells[0].theme);
    expect(isHookTheme(themeOfText(anchorTemplate)), 'anchor: a real template must classify to a theme').toBe(true);

    // A DM's own sentence.
    expect(themeOfText('The reeve owes my players a favour and knows it.')).toBe(UNTYPED);
    // A PREFIX of a real template: a prefix/substring matcher would classify this.
    expect(themeOfText(anchorTemplate.slice(0, Math.floor(anchorTemplate.length / 2)))).toBe(UNTYPED);
    // A real template with ONE word changed: a similarity matcher would classify this.
    expect(themeOfText(anchorTemplate.replace(/\b\w+\b/, 'Xyzzy'))).toBe(UNTYPED);
    // A real template with EXTRA prose appended — a DM extending an authored hook
    // keeps their edit out of machine taste.
    expect(themeOfText(`${anchorTemplate} My players already know this.`)).toBe(UNTYPED);
    // Empty / non-string input never invents a theme.
    expect(themeOfText('')).toBe(UNTYPED);
    expect(themeOfText(null)).toBe(UNTYPED);
    expect(themeOfText(undefined)).toBe(UNTYPED);
    expect(themeOfRelArchetype('no_such_archetype')).toBe(UNTYPED);
    expect(themeOfRelArchetype(null)).toBe(UNTYPED);
  });

  test('the fold is case/whitespace/edge-punctuation tolerant and nothing more', () => {
    const template = livePoolTemplates[0];
    const theme = themeOfText(template);
    expect(isHookTheme(theme)).toBe(true);
    // The same folding the exact-text dedup layer applies, so a hook the
    // aggregator considers one string is one theme here too.
    expect(themeOfText(template.toUpperCase())).toBe(theme);
    expect(themeOfText(`  ${template.replace(/ /g, '  ')}  `)).toBe(theme);
    expect(themeOfText(`"${template}"`)).toBe(theme);
    // …and NOT more: interior punctuation is content, not noise.
    expect(themeOfText(template.replace(/\./g, ','))).toBe(UNTYPED);
  });
});
