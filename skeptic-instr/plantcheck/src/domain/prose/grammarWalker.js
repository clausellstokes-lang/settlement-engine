/**
 * @typedef {object} CeilingShape
 * @property {number} slack the additive term of the share ceiling (the chair's recommended
 *   value is a tenth)
 * @property {number} ratioCap the multiplicative cap, as a multiple of uniform (the chair's
 *   is one and a half — the 13:22 bar)
 * @property {number} runFloor the floor under arm B1's slack
 * @property {number} successorCeiling arm B3's per-row successor ceiling
 */

/**
 * THE CEILING. `null` means NOT-EXECUTABLE — reported, never scored (arm H, extended by
 * Part B §10 item 9).
 *
 * ⭐ THE SHAPE IS AN ARGUMENT AND HAS NO DEFAULT, and the estate's tuning register is what
 * made this file honour its own header. A first cut wrote `min(1/n + 0.10, 1.5/n)` with the
 * numbers inline; `tests/lint/tuningRegister.walker.test.js` counted four unregistered dials
 * in a module whose docblock says every number is the OWNER'S. A default would be the same
 * fault with a longer fuse — a recommendation made law by shipping — so there is none, and a
 * caller that supplies no shape gets `null`.
 * @param {number} n the ADMISSIBLE order count for the unit
 * @param {CeilingShape} [shape]
 * @returns {number|null}
 */
export function ceilingFor(n, shape) {
  if (!Number.isFinite(n) || n <= 2) return null;
  if (!shape || !Number.isFinite(shape.slack) || !Number.isFinite(shape.ratioCap)) return null;
  return Math.min(1 / n + shape.slack, shape.ratioCap / n);
}

/**
 * ARM B1's slack: `1/n + 2 SE`, floored at `1/n + shape.runFloor` (Part B §10 item 8 — never
 * a fixed slack on a forty-line sample). SE is the binomial standard error of the run rate at
 * the fair-draw probability `1/n` over `samples` consecutive pairs.
 * @param {number} n
 * @param {number} samples
 * @param {CeilingShape} [shape]
 * @returns {number|null}
 */
export function runCeilingFor(n, samples, shape) {
  if (!Number.isFinite(n) || n <= 1 || !Number.isFinite(samples) || samples <= 0) return null;
  if (!shape || !Number.isFinite(shape.runFloor)) return null;
  const p = 1 / n;
  const se = Math.sqrt((p * (1 - p)) / samples);
  // `2` standard errors is the interval's own definition, not a dial: a two-SE band is what
  // "outside the fair draw's ordinary range" MEANS. The FLOOR under it is the tunable part.
  return p + Math.max(2 * se, shape.runFloor);
}

/**
 * Shannon entropy of a distribution, in bits.
 *
 * ⭐ `log2Det`, NEVER `Math.log2`, AND THE ESTATE'S OWN LINT CAUGHT THE DIFFERENCE. The
 * ECMAScript spec leaves the transcendental functions implementation-approximated, so a
 * threshold fed by one can fork same-seed worlds across devices; `src/domain/**` bans them
 * outright and points at the deterministic kernel. This figure is report-only and feeds no
 * seed — and the ban is fail-closed for exactly the case where someone believes that and is
 * wrong later. The kernel's `log2Det` is built from + - * / alone.
 * @param {number[]} shares
 * @returns {number}
 */
export function entropyOf(shares) {
  // `+ 0` normalises the negative zero a single-outcome distribution produces, so a caller
  // comparing against 0 is not defeated by IEEE sign.
  return -shares.filter((s) => s > 0).reduce((a, s) => a + s * log2Det(s), 0) + 0;
}

/** @param {ReadonlyArray<string>} list @returns {Map<string, number>} */
function tally(list) {
  /** @type {Map<string, number>} */
  const counts = new Map();
  for (const item of list) counts.set(item, (counts.get(item) || 0) + 1);
  return counts;
}

/**
 * The opener of a variant — the first two words, slots normalised to one token. Carried from
 * `check-pair.mjs:45` so the estate has one definition of an opener.
 * @param {string} text
 * @returns {string}
 */
export function openerOf(text) {
  return String(text || '').replace(/\{[a-z_0-9]+\}/gi, '{}').trim().split(/\s+/).slice(0, 2)
    .map((w) => w.toLowerCase().replace(/^[^a-z{]+|[^a-z}]+$/g, ''))
    .filter(Boolean)
    .join(' ');
}

/**
 * THE SEGMENT — and it is PINNED here, in writing, because control 4's calibration depends
 * on it and the sitting asked for exactly that (SITTING B.4.7).
 *
 * A SEGMENT is a SENTENCE of a variant, counted by the same rule `check-pair.mjs:43` uses:
 * slots blanked to a single token, split on a terminal `.?!` followed by whitespace and an
 * opening capital or quote. It is NOT a clause and NOT a rendered line. "A pool is uniform
 * in segment count" therefore means: every variant of the pool has the same SENTENCE count.
 * @param {string} text
 * @returns {number}
 */
export function segmentCount(text) {
  return String(text || '').replace(/\{[a-z_0-9]+\}/gi, 'X')
    .split(/(?<=[.?!;])\s+/).filter(Boolean).length;
}

// ── ARM A · the single-order ceiling ────────────────────────────────────────────────

/**
 * @param {ReadonlyArray<string>} orders the order id realised by each unit, in any order
 * @param {string} unit
 * @param {number} [admissible] the admissible order count; defaults to the realised count
 * @param {CeilingShape} [shape] absent ⇒ NOT-EXECUTABLE, never a pass
 * @returns {GrammarReport}
 */
export function armA(orders, unit, admissible, shape) {
  /** @type {GrammarReport} */
  const out = {
    figures: {}, fails: [], withheld: [], notes: [], notExecutable: [],
  };
  const counts = tally(orders);
  const n = Number.isFinite(admissible) ? Number(admissible) : counts.size;
  const ceiling = ceilingFor(n, shape);
  const histogram = [...counts].sort((a, b) => b[1] - a[1])
    .map(([id, k]) => ({ order: id, share: k / orders.length, count: k }));
  out.figures = { unit, n, ceiling, total: orders.length, histogram };
  if (ceiling === null) {
    out.notExecutable.push({
      arm: 'A',
      unit,
      detail: shape
        ? `n = ${n} admissible orders — at n ≤ 2 a share ceiling scores a coin flip, so the arm declares itself not-executable`
        : 'no ceiling shape supplied — the share ceiling is the owner\'s number and this walker bakes none',
      value: n,
    });
    return out;
  }
  for (const row of histogram) {
    if (row.share > ceiling) {
      out.fails.push({
        arm: 'A',
        unit,
        detail: `order ${row.order} holds ${(row.share * 100).toFixed(1)}% of ${orders.length} (ceiling ${(ceiling * 100).toFixed(1)}% at n = ${n})`,
        value: row.share,
        ceiling,
      });
    }
  }
  return out;
}

// ── ARM B1 · the run · B2 · adjacency · B3 · the rota ──────────────────────────────

/**
 * The three sequence arms, over a SIMULATED READING SEQUENCE (never a pool dump).
 * @param {ReadonlyArray<string>} sequence order ids in reading order
 * @param {string} unit
 * @param {number} [admissible]
 * @param {CeilingShape} [shape] absent ⇒ the ceilings are NOT-EXECUTABLE
 * @returns {GrammarReport}
 */
export function armsB(sequence, unit, admissible, shape) {
  /** @type {GrammarReport} */
  const out = {
    figures: {}, fails: [], withheld: [], notes: [], notExecutable: [],
  };
  const pairs = Math.max(0, sequence.length - 1);
  const n = Number.isFinite(admissible) ? Number(admissible) : tally(sequence).size;
  if (pairs === 0 || n <= 1) {
    out.notExecutable.push({
      arm: 'B',
      unit,
      detail: `${sequence.length} reading(s), ${n} order(s) — a run rate needs consecutive pairs and at least two orders`,
    });
    return out;
  }
  let repeats = 0;
  /** @type {Map<string, Map<string, number>>} */
  const transitions = new Map();
  for (let i = 1; i < sequence.length; i++) {
    if (sequence[i] === sequence[i - 1]) repeats += 1;
    const from = sequence[i - 1];
    if (!transitions.has(from)) transitions.set(from, new Map());
    const row = transitions.get(from);
    if (row) row.set(sequence[i], (row.get(sequence[i]) || 0) + 1);
  }
  const runRate = repeats / pairs;
  const runCeiling = runCeilingFor(n, pairs, shape);
  // B2's adjacency is at the CHANCE FLOOR, never zero (Part B §10 item 8; SITTING's own
  // control 5: a fair draw must PASS, and a fair draw repeats at 1/n).
  const chanceFloor = 1 / n;
  const rows = [...transitions].map(([from, row]) => {
    const total = [...row.values()].reduce((a, b) => a + b, 0);
    const shares = [...row.values()].map((v) => v / total);
    const top = [...row].sort((a, b) => b[1] - a[1])[0];
    return {
      from, total, entropy: entropyOf(shares), topSuccessor: top?.[0], topShare: (top?.[1] || 0) / total,
    };
  });
  out.figures = {
    unit, n, pairs, runRate, runCeiling, chanceFloor, transitions: rows,
  };
  if (runCeiling !== null && runRate > runCeiling) {
    out.fails.push({
      arm: 'B1',
      unit,
      detail: `same-order-as-previous ${(runRate * 100).toFixed(1)}% over ${pairs} pairs (ceiling ${(runCeiling * 100).toFixed(1)}% = 1/n + 2 SE at n = ${n})`,
      value: runRate,
      ceiling: runCeiling,
    });
  }
  if (runRate > chanceFloor + chanceFloor && runRate <= (runCeiling ?? Infinity)) {
    out.notes.push({
      arm: 'B2',
      unit,
      detail: `adjacency ${(runRate * 100).toFixed(1)}% is above twice the chance floor ${(chanceFloor * 100).toFixed(1)}% but inside B1's ceiling`,
      value: runRate,
    });
  }
  // B3 — THE ROTA. A deterministic A→B→C→A cycle passes A and B1 with a perfect score and is
  // a metronome at a longer period. The successor distribution is where it shows.
  if (n >= 3) {
    for (const row of rows) {
      if (shape && Number.isFinite(shape.successorCeiling)
        && row.topShare > shape.successorCeiling && row.total >= 3) {
        out.fails.push({
          arm: 'B3',
          unit,
          detail: `after ${row.from}, ${row.topSuccessor} follows ${(row.topShare * 100).toFixed(1)}% of ${row.total} times (ceiling ${(shape.successorCeiling * 100).toFixed(0)}% at n ≥ 3); row entropy ${row.entropy.toFixed(2)} bits`,
          value: row.topShare,
          ceiling: shape.successorCeiling,
        });
      }
    }
  } else {
    out.notExecutable.push({ arm: 'B3', unit, detail: `n = ${n} — the rota arm needs n ≥ 3` });
  }
  return out;
}

// ── ARM E · the spread ──────────────────────────────────────────────────────────────

/**
 * Arm E over one pool: uniform grammar, shared openers, uniform segment count.
 * @param {ReadonlyArray<GrammarEntry>} pool
 * @param {string} unit
 * @returns {GrammarReport}
 */
export function armE(pool, unit) {
  /** @type {GrammarReport} */
  const out = {
    figures: {}, fails: [], withheld: [], notes: [], notExecutable: [],
  };
  if (pool.length < 2) {
    out.notExecutable.push({ arm: 'E', unit, detail: 'a pool of one is not a pool (NL-8b)' });
    return out;
  }
  const orders = pool.map((v) => orderIdOf(classifyMoves(v.text)) || classifyMoves(v.text).join('→'));
  const openers = pool.map((v) => openerOf(v.text));
  const segments = pool.map((v) => segmentCount(v.text));
  const uniformGrammar = new Set(orders).size === 1;
  const uniformSegments = new Set(segments).size === 1;
  const dupOpeners = [...tally(openers)].filter(([, k]) => k > 1);
  out.figures = {
    unit, size: pool.length, orders, openers, segments, uniformGrammar, uniformSegments, dupOpeners,
  };
  if (uniformGrammar) {
    out.notes.push({ arm: 'E', unit, detail: `all ${pool.length} variants realise one grammar (${orders[0]})` });
  }
  for (const [opener, k] of dupOpeners) {
    out.notes.push({ arm: 'E', unit, detail: `${k} variants share the opener "${opener}"` });
  }
  if (uniformSegments) {
    out.notes.push({ arm: 'E', unit, detail: `all ${pool.length} variants carry ${segments[0]} segment(s)` });
  }
  return out;
}

// ── ARM F · the walls, SCOPED ───────────────────────────────────────────────────────

/**
 * @param {GrammarEntry} entry
 * @param {ReadonlyArray<string>} moves
 * @param {string} register
 * @returns {GrammarFinding[]}
 */
export function armF(entry, moves, register) {
  /** @type {GrammarFinding[]} */
  const fails = [];
  const inScope = (wall) => wall.scope.includes('*') || wall.scope.includes(register);
  const wall = (id) => WALLS.find((w) => w.id === id);
  const text = String(entry.text || '');
  // Wall 1 — STATE precedes CAUSE where both appear (estate-wide).
  const iState = moves.indexOf('PRESENT');
  const iCause = moves.findIndex((m) => m === 'HISTORY' || m === 'CONSEQUENCE');
  if (iState >= 0 && iCause >= 0 && iCause < iState) {
    fails.push({ arm: 'F1', unit: entry.id, detail: `${moves.join('→')} puts a cause before the state (wall 1)` });
  }
  // Wall 3 — ABSENCE never opens and never sits beside another ABSENCE (estate-wide).
  if (moves[0] === 'ABSENCE') {
    fails.push({ arm: 'F3', unit: entry.id, detail: 'an ABSENCE opens the variant (wall 3)' });
  }
  for (let i = 1; i < moves.length; i++) {
    if (moves[i] === 'ABSENCE' && moves[i - 1] === 'ABSENCE') {
      fails.push({ arm: 'F3', unit: entry.id, detail: 'two adjacent ABSENCE moves (wall 3)' });
    }
  }
  // Wall 6 — never a third sentence; QUALIFY never as a "which" tail. DOSSIER-SCOPED
  // (SITTING B.4.1: wall 6 does not reach chrome's units or the docent).
  if (inScope(wall(6))) {
    if (segmentCount(text) > 2) {
      fails.push({ arm: 'F6', unit: entry.id, detail: `${segmentCount(text)} sentences — the register is one flowing sentence or two short ones (wall 6)` });
    }
    if (/,\s*which\b/.test(text)) {
      fails.push({ arm: 'F6', unit: entry.id, detail: 'a QUALIFY carried as a "which" tail (wall 6)' });
    }
  }
  // Wall 2 — a threshold or edge is conditional or subjunctive, never a bare future.
  if (/\b(will|shall)\b/i.test(text) && !/\bwould\b/i.test(text)) {
    fails.push({ arm: 'F2', unit: entry.id, detail: 'a bare future indicative where the edge must be subjunctive (wall 2)' });
  }
  return fails;
}

// ── ARM G · the non-moves ───────────────────────────────────────────────────────────

/**
 * @param {GrammarEntry} entry
 * @returns {GrammarFinding[]}
 */
export function armG(entry) {
  /** @type {GrammarFinding[]} */
  const fails = [];
  for (const [name, spec] of Object.entries(NON_MOVES)) {
    if (spec.detect.test(String(entry.text || ''))) {
      fails.push({ arm: `G/${name}`, unit: entry.id, detail: `${name}: ${spec.why}` });
    }
  }
  return fails;
}

// ── THE OWNER'S THREE NUMBERS (§912.3 / Part B §16.1) ───────────────────────────────

/**
 * @typedef {object} ThreeNumbers
 * @property {number} budgetShare an ENTRY exceeding more than this share of the soft rules
 *   measurable on it FAILS (the chair's value: one third)
 * @property {number} expectedShare a pool or tab AVERAGING above this is REPORTED (a sixth)
 * @property {number} depthBandWidths at most this far outside the band on any one rule
 *   (the chair's value: 0.5)
 * @property {ReadonlyArray<string>} [definingFeatures] metrics a register DECLARES as its
 *   defining feature, exempt from the depth rule
 */

/**
 * Score one unit against the bands under the owner's three numbers.
 * @param {ReadonlyArray<string>} paragraphs the unit's prose
 * @param {Record<string, {lo: number, hi: number}>} bands
 * @param {ThreeNumbers} three
 * @param {string} unit
 * @returns {GrammarReport}
 */
export function armThreeNumbers(paragraphs, bands, three, unit) {
  /** @type {GrammarReport} */
  const out = {
    figures: {}, fails: [], withheld: [], notes: [], notExecutable: [],
  };
  if (!bands || Object.keys(bands).length === 0) {
    out.notExecutable.push({
      arm: 'three-numbers',
      unit,
      detail: 'no exemplar bands supplied — the BUDGET, DEPTH and PERFECTION arms all read a band and none was given',
    });
    return out;
  }
  const fp = fingerprint(paragraphs);
  if (fp.sentences < 2) {
    out.notExecutable.push({ arm: 'three-numbers', unit, detail: `${fp.sentences} sentence(s) — too small to fingerprint` });
    return out;
  }
  const { scored, exceeded, unscorable } = scoreAgainstBands(fp.metrics, bands);
  const share = scored.length ? exceeded.length / scored.length : 0;
  const defining = new Set(three.definingFeatures || []);
  out.figures = {
    unit,
    sentences: fp.sentences,
    scored: scored.length,
    unscorable,
    exceeded: exceeded.map((e) => ({ metric: e.metric, depth: Number(e.depth.toFixed(3)), side: e.side })),
    share,
    // SPREAD (§912.3 item 4): WHICH rules this unit exceeds. A register whose units all
    // exceed the same rules is the template wearing imperfection's coat.
    spread: exceeded.map((e) => e.metric).sort(),
  };
  // THE BUDGET.
  if (share > three.budgetShare) {
    out.fails.push({
      arm: 'BUDGET',
      unit,
      detail: `exceeds ${exceeded.length} of ${scored.length} soft rules (${(share * 100).toFixed(0)}%), above the budget ${(three.budgetShare * 100).toFixed(0)}%`,
      value: share,
      ceiling: three.budgetShare,
    });
  } else if (share > three.expectedShare) {
    out.notes.push({
      arm: 'BUDGET',
      unit,
      detail: `exceeds ${exceeded.length} of ${scored.length} (${(share * 100).toFixed(0)}%), above the expected ${(three.expectedShare * 100).toFixed(0)}% and inside the budget`,
      value: share,
    });
  }
  // THE DEPTH.
  for (const e of exceeded) {
    if (e.depth <= three.depthBandWidths) continue;
    if (defining.has(e.metric)) {
      out.notes.push({
        arm: 'DEPTH',
        unit,
        detail: `${e.metric} sits ${e.depth.toFixed(2)} band-widths ${e.side} — exempt as a declared defining feature`,
        value: e.depth,
      });
      continue;
    }
    out.fails.push({
      arm: 'DEPTH',
      unit,
      detail: `${e.metric} sits ${e.depth.toFixed(2)} band-widths ${e.side} the band (ceiling ${three.depthBandWidths})`,
      value: e.depth,
      ceiling: three.depthBandWidths,
    });
  }
  // THE PERFECTION CEILING — a FINDING, never a rewrite trigger. No human record sits at
  // zero; a unit that does is suspect of being a template rather than a record.
  if (exceeded.length === 0 && scored.length > 0) {
    out.notes.push({
      arm: 'PERFECTION',
      unit,
      detail: `zero exceedances across ${scored.length} soft rules — FLAGGED SUSPECT (no exemplar record sits here); a finding for the walk, never a trigger to manufacture a fault`,
      value: 0,
    });
  }
  return out;
}

// ── THE TEN INSTRUMENT GAPS (SITTING §J) ────────────────────────────────────────────

/** The opening SHAPE of a variant — gap (f). @param {string} text @returns {string} */
export function openingShape(text) {
  const t = String(text || '').trim();
  if (/^\{settlement\}/.test(t)) return 'settlement-token';
  if (/^\{[a-z_]+\}/i.test(t)) return 'other-slot';
  if (/^(The|A|An)\b/.test(t)) return 'article';
  if (/^(There|It) (is|was|are|were)\b/.test(t)) return 'expletive';
  if (/^\w+ing\b/.test(t)) return 'participial';
  if (/^(In|On|At|By|For|From|With|After|Before|Under|Between|Across|Along)\b/.test(t)) return 'prepositional';
  if (/^(No|Nobody|Nothing|None|Neither)\b/.test(t)) return 'negative';
  if (/^(What|Whatever|Whoever|Where|When)\b/.test(t)) return 'free-relative';
  return 'other';
}

/** The dominant TENSE of a variant — gap (d). @param {string} text @returns {string} */
export function tenseOf(text) {
  const t = String(text || '');
  if (/\b(will|shall)\b/i.test(t)) return 'future';
  if (/\bwould\b/i.test(t)) return 'subjunctive';
  if (/\b(was|were|had|has been|have been|did)\b/i.test(t)) return 'past';
  return 'present';
}

/**
 * An APPOSITIVE carrying a move — gap (h). A move packed into a nominal appositive is
 * invisible to a clause-structure classifier and reads as an arm-A disagreement with a
 * CORRECT tag (the taste sample's own §8.1 finding, on its own cut sentence).
 * @param {string} text
 * @returns {string[]}
 */
export function appositives(text) {
  return [...String(text || '').matchAll(/,\s+(?:a|an|the)\s+[a-z][^,.;]{3,50},/gi)].map((m) => m[0].trim());
}

/**
 * The ten gaps, measured per entry. Every one is REPORTED — none of them gates.
 * @param {GrammarEntry} entry
 * @returns {Record<string, unknown>}
 */
export function tenGaps(entry) {
  const text = String(entry.text || '');
  return {
    settlementOpener: openingShape(text) === 'settlement-token',
    closeKind: closeKindOf(text),
    contrastShapes: (text.match(CONTRAST_SHAPES) || []).length,
    tense: tenseOf(text),
    openingShape: openingShape(text),
    bareRelatives: bareRelatives(text),
    appositives: appositives(text),
  };
}

// ── THE WALK ────────────────────────────────────────────────────────────────────────

/**
 * @typedef {object} GrammarInput
 * @property {ReadonlyArray<GrammarEntry>} corpus
 * @property {Map<string, GrammarEntry[]>} [cells] pool id → its variants
 * @property {ReadonlyArray<{unit: string, orders: string[]}>} [sequences] simulated reading
 *   sequences; ABSENT ⇒ arms B1/B2/B3 are NOT-EXECUTABLE, never passed
 * @property {Record<string, {lo: number, hi: number}>} [bands]
 * @property {ThreeNumbers} [three]
 * @property {Map<string, ReadonlyArray<string>>} [composedFill] block → the slots the
 *   composer can fill
 * @property {string} [register]
 * @property {Record<string, number>} [admissible] unit → the admissible order count
 * @property {CeilingShape} [ceilings] the owner's ceiling shape; ABSENT ⇒ arms A and B report
 *   NOT-EXECUTABLE rather than scoring against a number this walker invented
 */

/**
 * THE B-GRAMMAR WALK. Every arm reports; the arms that gate say which ceiling they used.
 * @param {GrammarInput} input
 * @returns {GrammarReport}
 */
export function walkGrammar(input) {
  /** @type {GrammarReport} */
  const out = {
    figures: {}, fails: [], withheld: [], notes: [], notExecutable: [],
  };
  const corpus = input.corpus || [];
  const register = input.register || 'dossier';
  /** @param {GrammarReport} r */
  const absorb = (r) => {
    out.fails.push(...r.fails);
    out.withheld.push(...r.withheld);
    out.notes.push(...r.notes);
    out.notExecutable.push(...r.notExecutable);
  };

  // Per entry: the classifier, the walls, the non-moves, the ten gaps.
  const perEntry = corpus.map((entry) => {
    const moves = classifyMoves(entry.text);
    const orderId = orderIdOf(moves);
    out.fails.push(...armF(entry, moves, register));
    out.fails.push(...armG(entry));
    if (typeof entry.grammar === 'string' && entry.grammar !== '' && !orderId.split('|').includes(entry.grammar)) {
      out.withheld.push({
        arm: 'A/tag',
        unit: entry.id,
        detail: `the tag says ${entry.grammar}; the classifier reads ${moves.join('→')}${orderId ? ` (${orderId})` : ' (no member)'} — the classifier is a CHECK, never a source`,
      });
    }
    return {
      entry, moves, orderId, gaps: tenGaps(entry),
    };
  });

  // ARM A over the register, at level 1.
  const orders = perEntry.map((r) => r.orderId || r.moves.join('→'));
  absorb(armA(orders, `${register} · level 1`, input.admissible?.[`${register} · level 1`], input.ceilings));
  out.figures.level1 = {
    orderHistogram: [...tally(orders)].sort((a, b) => b[1] - a[1]),
    // The INDEX-0 histogram: a default that is one order everywhere is fault 9 by the back
    // door (§3.2's own note).
    indexZeroHistogram: [...tally(perEntry.filter((r) => r.entry.idx === 0).map((r) => r.orderId || r.moves.join('→')))]
      .sort((a, b) => b[1] - a[1]),
    untagged: perEntry.filter((r) => !r.entry.grammar).length,
  };

  // ARM E per pool, plus C-sibling's typed-fact coherence.
  const cells = input.cells || new Map();
  /** @type {Array<{pool: string, uniformGrammar: boolean, uniformSegments: boolean, dup: number}>} */
  const poolRows = [];
  for (const [poolId, pool] of cells) {
    const e = armE(pool, poolId);
    absorb(e);
    const f = /** @type {{uniformGrammar?: boolean, uniformSegments?: boolean,
     *   dupOpeners?: ReadonlyArray<[string, number]>}} */ (e.figures);
    if (typeof f.uniformGrammar === 'boolean') {
      poolRows.push({
        pool: poolId,
        uniformGrammar: f.uniformGrammar,
        uniformSegments: f.uniformSegments,
        dup: (f.dupOpeners || []).length,
      });
    }
    // C-SIBLING — imported, never re-written: one definition of a typed fact in the estate.
    for (let i = 1; i < pool.length; i++) {
      const mine = typedFactsOf(pool[i]);
      const theirs = typedFactsOf(pool[0]);
      for (const [noun, band] of Object.entries(mine.bands)) {
        if (theirs.bands[noun] && theirs.bands[noun] !== band) {
          out.fails.push({
            arm: 'C-sibling',
            unit: poolId,
            detail: `variants ${0} and ${i} band "${noun}" differently (${theirs.bands[noun]} vs ${band})`,
          });
        }
      }
    }
  }
  const measurable = poolRows.length;
  out.figures.spread = {
    pools: measurable,
    uniformGrammarShare: measurable ? poolRows.filter((p) => p.uniformGrammar).length / measurable : null,
    uniformSegmentShare: measurable ? poolRows.filter((p) => p.uniformSegments).length / measurable : null,
    repeatedOpenerShare: measurable ? poolRows.filter((p) => p.dup > 0).length / measurable : null,
  };

  // ARM D — the licence, keyed on (block, pool) as gap (e) requires.
  if (!input.composedFill) {
    out.notExecutable.push({ arm: 'D', unit: register, detail: 'no composed fill supplied' });
  } else {
    for (const entry of corpus) {
      const row = input.composedFill.get(String(entry.block));
      // The resolver returns `{slots, conditional, sites}` and a fixture hands a bare array;
      // both are read, because an instrument that only accepts its own shape makes a fixture
      // impossible to write by hand.
      const composed = Array.isArray(row)
        ? row
        : /** @type {{slots?: ReadonlyArray<string>}|undefined} */ (row)?.slots;
      if (!Array.isArray(composed)) {
        out.notExecutable.push({
          arm: 'D',
          unit: entry.id,
          detail: `block ${entry.block} has no composer bag — every variant of it is unreachable, or the block is unmounted`,
        });
        continue;
      }
      const named = [...new Set([...String(entry.text).matchAll(/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/g)].map((m) => m[1]))];
      const missing = named.filter((s) => !composed.includes(s));
      if (missing.length) {
        out.fails.push({
          arm: 'D',
          unit: entry.id,
          detail: `names {${missing.join('}, {')}}, which this block's composer bag does not offer`,
        });
      }
    }
  }

  // ARMS B1/B2/B3 — over the simulated reading sequences ONLY.
  if (!input.sequences || input.sequences.length === 0) {
    out.notExecutable.push({
      arm: 'B',
      unit: register,
      detail: 'no simulated reading sequence supplied — the consecutive-pair statistics are taken over a READING, never over a pool dump (§0\'s caveat), so the arm reports not-executable rather than measuring authoring order',
    });
  } else {
    for (const seq of input.sequences) absorb(armsB(seq.orders, seq.unit, input.admissible?.[seq.unit], input.ceilings));
  }

  // THE THREE NUMBERS, per pool.
  if (!input.bands || !input.three) {
    out.notExecutable.push({
      arm: 'three-numbers',
      unit: register,
      detail: 'no exemplar bands or no owner numbers supplied — BUDGET, DEPTH and PERFECTION all read them',
    });
  } else {
    for (const [poolId, pool] of cells) {
      absorb(armThreeNumbers(pool.map((v) => v.text), input.bands, input.three, poolId));
    }
  }

  // ARM I — the unwritten slot. REPORTED until the rank-form manifest exists (chair C-6:
  // absence class 3 is unavailable until the rank-form is typed).
  out.notExecutable.push({
    arm: 'I',
    unit: register,
    detail: 'the unwritten slot needs a rank-form manifest naming which slots a place of this rank carries; no such manifest is typed today (Part B §0.1 ruling 4, chair C-6)',
  });

  // ARM J — the fact budget, first arm: an entry's sentence count against its count of
  // licensed (move, field, value) triples. Direction stated; the spec deferred the rest.
  for (const row of perEntry) {
    const triples = row.moves.length + (row.entry.slots?.length || 0);
    const sentences = segmentCount(row.entry.text);
    if (sentences > triples) {
      out.notes.push({
        arm: 'J',
        unit: row.entry.id,
        detail: `${sentences} sentence(s) against ${triples} licensed move/field unit(s) — a sentence may exist only to connect two others`,
      });
    }
  }

  // The ten gaps, as a register-level census.
  out.figures.gaps = {
    settlementOpeners: perEntry.filter((r) => r.gaps.settlementOpener).length,
    closeKinds: [...tally(perEntry.map((r) => String(r.gaps.closeKind)))].sort((a, b) => b[1] - a[1]),
    openingShapes: [...tally(perEntry.map((r) => String(r.gaps.openingShape)))].sort((a, b) => b[1] - a[1]),
    tenses: [...tally(perEntry.map((r) => String(r.gaps.tense)))].sort((a, b) => b[1] - a[1]),
    contrastShapes: perEntry.reduce((a, r) => a + Number(r.gaps.contrastShapes), 0),
    bareRelatives: perEntry.filter((r) => /** @type {string[]} */ (r.gaps.bareRelatives).length).length,
    appositives: perEntry.filter((r) => /** @type {string[]} */ (r.gaps.appositives).length).length,
  };
  return out;
}
