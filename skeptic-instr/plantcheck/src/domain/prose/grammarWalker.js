/**
 * domain/prose/grammarWalker.js — THE B-GRAMMAR WALKER (MOVE-GRAMMAR §4, as amended by
 * Part B §10 items 1–13, §9/§9.1, and the chair's three numbers §16.1).
 *
 * ── THE DIVISION FROM THE ENTRY WALKER, AND WHY IT MATTERS ─────────────────────────
 * `entryWalker.js` judges CLAIMS: what a sentence asserts and whether a field holds it.
 * This one judges ORDER: which grammar a variant realises, how the grammars are spread
 * across a pool, and how they run across a reading. The two must not be one instrument, or
 * a claim rule will be mistaken for a shape rule (MOVE-GRAMMAR §4's own closing note). The
 * one arm they share — C-sibling — is imported from the entry walker rather than re-written,
 * so there is one definition of a typed fact in the estate.
 *
 * ── WHAT IT READS (§4.1) ───────────────────────────────────────────────────────────
 *   1. the corpus at a named sha, through the loaders (never the ledger tree);
 *   2. per variant: the `grammar:` tag, the marks, the slot set, the block's fields, the
 *      sentence count and the opener's first two words;
 *   3. the CLASSIFIER, as the CHECK on the tag — an arm-A disagreement is a finding, and the
 *      classifier is never a source;
 *   4. the SIMULATED READING SEQUENCES, generated by the engine's own seeded picks over N
 *      towns. ⚠ The consecutive-pair statistics are taken over THESE and never over a pool
 *      dump: a pool dump has no reader and its "order" is authoring order.
 *
 * ── THE CEILING IS A FUNCTION OF n, AND n IS MEASURED (SITTING B.3, R-DA-17) ───────
 *   ceiling(n) = min(1/n + 0.10, 1.5/n) for n ≥ 3;  NOT-EXECUTABLE at n ≤ 2.
 * The correction that produced it: at n = 6 the old fixed 0.35 is 2.1× uniform, and
 * 1/n + 0.10 is exactly 1.6× — the 13:22 bar — so the two-term minimum holds the ratio down
 * as n grows. n is the ADMISSIBLE order count for the unit AFTER the licensing filter, not
 * the size of the vocabulary: a block that licenses two members has n = 2 and the arm
 * declares itself not-executable rather than scoring a coin flip.
 *
 * ── EVERY NUMBER IS AN INPUT ───────────────────────────────────────────────────────
 * The exemplar BANDS, the owner's three numbers and the per-register ceilings are ARGUMENTS,
 * not constants. Two reasons, both load-bearing. The bands are derived from the fourteen
 * exemplar records, which live outside this repo and are not this lane's to import. And the
 * numbers are the OWNER'S (Q4; §912.3): a walker that baked them would make a recommendation
 * into a law by shipping. A missing input makes its arm NOT-EXECUTABLE and says so.
 *
 * PURE, HEADLESS. No I/O, no clock, no RNG. Nothing here runs at the draw.
 *
 * @enforced-by tests/lint/proseMoveGrammar.walker.test.js
 */
