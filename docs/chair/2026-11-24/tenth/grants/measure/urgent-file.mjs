// GRANTS-1: write FOR-THE-OWNER-URGENT.sql and its check table from out/urgent-checks.json
// (written by urgent.mjs). Only functions that PASSED all three checks are in the file.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = new URL('./out/', import.meta.url);
const GRANTS = new URL('../', import.meta.url);
const rows = JSON.parse(readFileSync(new URL('./urgent-checks.json', OUT), 'utf8'));
const pass = rows.filter((r) => r.pass);
const failed = rows.filter((r) => !r.pass);
const head = (g) => (g === 1 ? 'GROUP 1: functions that hand back a secret or another user\'s data'
  : 'GROUP 2: functions that change another user\'s account, entitlements or money');

const readCheck = (title) => [
  `-- ${title}: READS ONLY. One row per function: does it exist here, and may a visitor (anon) or a`,
  '-- signed-in user (authenticated) execute it? After block 1 every existing row should read false, false.',
  'select s.grp, s.sig, p.oid is not null as exists_here,',
  "       case when p.oid is null then null else has_function_privilege('anon', p.oid, 'execute') end as anon_can_execute,",
  "       case when p.oid is null then null else has_function_privilege('authenticated', p.oid, 'execute') end as authenticated_can_execute",
  '  from (values',
  '    ' + pass.map((r) => `(${r.group}, '${r.sig}')`).join(',\n    '),
  '  ) as s(grp, sig)',
  '  left join pg_proc p on p.oid = to_regprocedure(s.sig)',
  ' order by s.grp, s.sig;',
];

const sql = [
  '-- FOR-THE-OWNER-URGENT.sql — GENERATED by docs/chair/2026-11-24/tenth/grants/measure/urgent-file.mjs',
  '-- from the PGlite catalog of migrations 001-210 and 001-203 (= origin/master, what is live). Do not edit by hand.',
  '--',
  `-- WHAT IT DOES, IN PLAIN WORDS: ${pass.length} database functions that only the server should call can today be`,
  '-- called by anyone who loads the site (the platform grants every new function to visitors and signed-in users',
  '-- unless a migration names them). Block 1 takes that away from visitors and signed-in users, one function at a',
  '-- time. The server (service_role) keeps every right it has. Blocks 0 and 2 only read.',
  '--',
  '-- SAFE TO RUN TWICE: a revoke of a right that is already gone does nothing. A function this database lacks is',
  '-- skipped, never an error. Each function passed three checks, in both trees (table beside this file):',
  '-- no policy, view, default, check or index names it; no function a visitor or user runs as themselves calls it;',
  '-- no call site on origin/master or on the working line reaches it with a visitor\'s or a user\'s token.',
  '--',
  '-- TO UNDO ONE LINE: grant execute on function <the same signature> to anon, authenticated;',
  '', '-- ══ BLOCK 0 ══', ...readCheck('BLOCK 0 (before)'), '',
  '-- Block 0b, READS ONLY: how many users have a stored provider key (a number only).',
  'select count(*) as byok_keys from public.surveyor_byok_keys;', '',
  '-- ══ BLOCK 1: the revokes, each guarded ══',
];
let g = 0;
for (const r of pass) {
  if (r.group !== g) { g = r.group; sql.push('', `-- ── ${head(g)} ──`); }
  sql.push(`do $$ begin if to_regprocedure('${r.sig}') is not null then revoke execute on function ${r.sig} from public, anon, authenticated; end if; end $$;`);
}
sql.push('', '-- ══ BLOCK 2 ══', ...readCheck('BLOCK 2 (after)'), '');
writeFileSync(new URL('./FOR-THE-OWNER-URGENT.sql', GRANTS), sql.join('\n'));

const esc = (s) => String(s).replace(/\|/g, '\\|');
const md = ['# FOR-THE-OWNER-URGENT — the three checks, per function (GENERATED by measure/urgent-file.mjs)', '',
  `Candidates: groups 1 and 2 of \`measure/out/revoke-block.sql\` (${rows.length}). Passed all three checks in both trees: **${pass.length}**. Left out: ${failed.length ? failed.map((r) => '`' + r.sig + '`').join(', ') : 'none'}.`, '',
  'Trees: the working line (`HEAD`, migrations 001–210) and `origin/master` (what is live; its migrations are 001–203, byte-identical to the line\'s). Catalogs: PGlite under the hosted default, replayed to 210 and to 203.', '',
  '(a) names the function in a policy, view, column default, check constraint or index. (b) a SECURITY INVOKER function that anon or authenticated can execute, or an invoker trigger function, calls it. (c) every call site in `src/` and `supabase/functions/` (tests excluded) with the client that makes it. A negative control (`URGENT_CONTROL=1`: `spend_credits`, `toggle_gallery_vote`, `list_my_tickets`) FAILS (c) in both trees, as it must (`out/urgent-control.log`).', '',
  '| grp | function | live (203) | (a) | (b) | (c) call sites: tree, place, client |', '|---|---|---|---|---|---|'];
for (const r of rows) {
  const a = [...new Set([...r.aLine, ...r.aLive])]; const b = [...new Set([...r.bLine, ...r.bLive])];
  const c = r.sites.map((s) => `${s.tree} \`${s.at}\` ${s.client}`).join('<br>') || 'none';
  md.push(`| ${r.group} | \`${r.sig}\` | ${r.live ? 'yes' : 'no'} | ${a.length ? esc(a.join(', ')) : 'none'} | ${b.length ? esc(b.join(', ')) : 'none'} | ${esc(c)} |`);
}
writeFileSync(new URL('./FOR-THE-OWNER-URGENT-CHECKS.md', GRANTS), md.join('\n') + '\n');
console.log('urgent file', pass.length, 'functions;', 'left out', failed.length);
