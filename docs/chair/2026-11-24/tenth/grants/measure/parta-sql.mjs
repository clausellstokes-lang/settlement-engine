// GRANTS-1: generate PART A of migration 211 (ruling G1 §2, amendment G1a) from
// out/parta-checks.json (urgent.mjs with PART_A=1) and out/functions.json (intent).
import { readFileSync, writeFileSync } from 'node:fs';
const OUT = new URL('./out/', import.meta.url);
const checks = JSON.parse(readFileSync(new URL('./parta-checks.json', OUT), 'utf8'));
const F = JSON.parse(readFileSync(new URL('./functions.json', OUT), 'utf8'));
const intent = new Map(F.map((r) => ['public.' + r.regproc, r.intent]));
const pass = checks.filter((r) => r.pass);
const left = checks.filter((r) => !r.pass);
const GH = { 1: 'GROUP 1: hands back a secret or another user\'s data', 2: 'GROUP 2: changes another user\'s account, entitlements or money',
  3: 'GROUP 3: reports, rollups, cleanups, rate limits, crons, workers, internal helpers', 4: 'APART: _audit_action (never granted or revoked before: PUBLIC could call it)' };
const L = ['-- ════ PART A: the functions (GENERATED by docs/chair/2026-11-24/tenth/grants/measure/parta-sql.mjs; do not edit by hand) ════',
  `-- ${pass.length} functions the migrations mean for the server alone (SERVER: granted to service_role only) or for no`,
  '-- role (NOBODY), plus _audit_action. Each is revoked from public, anon and authenticated BY EXACT SIGNATURE;',
  '-- service_role is granted again only where a migration granted it (SERVER). Each passed three checks in the',
  '-- working line and on origin/master: no policy, view, default, check or index names it; no SECURITY INVOKER',
  '-- function a visitor or user can run calls it; no call site uses a visitor\'s or a user\'s token.',
  '-- LEFT OPEN, by name (a user path needs them):',
  '--   _gallery_sanitize_public_json(jsonb,text[])  called by the invoker _gallery_apply_member_overrides',
  '--   _gallery_world_snapshot_is_safe(jsonb)       called by the invoker trigger _saved_maps_world_snapshot_guard',
  ...left.map((r) => `--   ${r.sig.replace(/^public\./, '')}  ${[...r.aLine, ...r.aLive].length ? 'named in ' + [...new Set([...r.aLine, ...r.aLive])].join(', ') : 'call site: ' + r.bad.map((b) => b.at).join(', ')}`)];
let g = 0;
for (const r of pass) {
  if (r.group !== g) { g = r.group; L.push('', '-- ── ' + GH[g] + ' ──'); }
  L.push(`revoke execute on function ${r.sig} from public, anon, authenticated;`);
  if (intent.get(r.sig) === 'SERVER') L.push(`grant execute on function ${r.sig} to service_role;`);
}
writeFileSync(new URL('./211/partA.sql', import.meta.url), L.join('\n') + '\n');
console.log('part A', pass.length, 'functions; service_role re-granted', pass.filter((r) => intent.get(r.sig) === 'SERVER').length, '; left out', left.length);
