// GRANTS-1: generate tests/security/functionGrantClasses.js (ruling G1 §6(i)): every
// function in schema public with its class, from the PGlite catalog's intent
// (out/functions.json) and part A's result (out/parta-checks.json).
// EXTRA_TRIGGERS=name(sig),... adds trigger functions a later part of 211 creates.
import { readFileSync, writeFileSync } from 'node:fs';
const OUT = new URL('./out/', import.meta.url);
const F = JSON.parse(readFileSync(new URL('./functions.json', OUT), 'utf8'));
const A = JSON.parse(readFileSync(new URL('./parta-checks.json', OUT), 'utf8'));
const closed = new Set(A.filter((r) => r.pass).map((r) => r.sig.replace(/^public\./, '')));
const KEPT = {
  '_gallery_sanitize_public_json(jsonb,text[])': 'called by the SECURITY INVOKER _gallery_apply_member_overrides, which a user runs',
  '_gallery_world_snapshot_is_safe(jsonb)': 'called by the SECURITY INVOKER trigger _saved_maps_world_snapshot_guard, which fires as the writing user',
};
for (const r of A.filter((x) => !x.pass)) KEPT[r.sig.replace(/^public\./, '')] = 'named in ' + [...new Set([...r.aLine, ...r.aLive])].join(', ');
const rows = {};
for (const r of F) {
  const k = r.regproc;
  if (KEPT[k]) rows[k] = 'KEPT_OPEN';
  else if (r.intent === 'SERVER' || r.intent === 'NOBODY') { if (!closed.has(k)) throw new Error('unclosed ' + k); rows[k] = r.intent; }
  else if (r.intent === 'UNSTATED') rows[k] = closed.has(k) ? 'NOBODY' : 'ANYONE';
  else rows[k] = r.intent; // USER, ANYONE, TRIGGER
}
for (const t of (process.env.EXTRA_TRIGGERS || '').split(',').filter(Boolean)) rows[t] = 'TRIGGER';
const keys = Object.keys(rows).sort();
const counts = {}; for (const k of keys) counts[rows[k]] = (counts[rows[k]] || 0) + 1;
const src = `/**
 * functionGrantClasses.js — EVERY function in schema \`public\`, with its class (GRANTS-1,
 * ruling G1 §6(i)). GENERATED by docs/chair/2026-11-24/tenth/grants/measure/register.mjs
 * from the PGlite catalog of the chain; not a test file.
 *
 * The classes, from the migrations' own grant statements (a replay without the hosted
 * default privileges):
 *   SERVER    granted to service_role alone: neither anon nor authenticated may execute it.
 *   NOBODY    granted to no role (called only inside SECURITY DEFINER functions): the same.
 *   USER      granted to authenticated by name: a signed-in user may execute it.
 *   ANYONE    granted to anon or left to PUBLIC: a visitor may execute it.
 *   TRIGGER   a trigger function: never called directly.
 *   KEPT_OPEN server-only by grant, but a user path needs it; the reason is in KEPT_OPEN_REASONS.
 * A NEW function with no row turns tests/security/hostedDefaultGrants.pglite.test.js red:
 * class it here (regenerate, or add the row by hand with the class its grants say).
 * Counts: ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}.
 */
export const KEPT_OPEN_REASONS = Object.freeze(${JSON.stringify(KEPT, null, 2)});

export const FUNCTION_CLASSES = Object.freeze({
${keys.map((k) => `  ${JSON.stringify(k)}: '${rows[k]}',`).join('\n')}
});
`;
writeFileSync('tests/security/functionGrantClasses.js', src);
console.log('register', keys.length, JSON.stringify(counts));
