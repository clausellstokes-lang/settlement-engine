// BAR6-AUDIT-D · the tables of LAW 8 from runD.mjs outputs (one per population).
//   node tablesD.mjs <out.md> <label>=<runD out.json> [<label>=<out.json> ...]
// Per population and rule: towns, instances, distinct lines (the town's name folded out), things, and how many sit on a
// line a LAW 2/3 rule already finds; then the thirty commonest distinct lines of each rule with their towns (first
// population that has the rule's instances, normally the 720); with `.traced.json` beside an output (traceB.mjs), the
// writer file of the false line and of the fact it should have read.
import fs from 'node:fs';

const [outMd, ...pairs] = process.argv.slice(2);
if (!outMd || !pairs.length) { console.error('usage: tablesD.mjs <out.md> <label>=<out.json> ...'); process.exit(2); }
const pops = pairs.map((p) => { const [label, f] = p.split('='); return { label, f, xs: JSON.parse(fs.readFileSync(f, 'utf8')) }; });
const rules = [...new Set(pops.flatMap((p) => p.xs.map((x) => x.rule)))].sort();
const tally = (xs) => ({ towns: new Set(xs.map((x) => x.town)).size, n: xs.length, lines: new Set(xs.map((x) => `${x.rule}|${x.form}`)).size, things: new Set(xs.map((x) => `${x.town}|${x.thing}`)).size, held: xs.filter((x) => x.heldBy).length });
const md = [];
md.push('# BAR6-AUDIT-D · LAW 8 · the tables', '', 'Generated by `tablesD.mjs` from `runD.mjs` outputs. "on L2/3" = instances on a line a LAW 2 or LAW 3 rule (seat B, the round in flight) also finds.', '');
md.push('## Counts by rule', '', `| rule | ${pops.map((p) => `${p.label}: towns · inst · lines · things · on L2/3`).join(' | ')} |`, `|---|${pops.map(() => '---').join('|')}|`);
for (const r of [...rules, 'ALL']) {
  const cells = pops.map((p) => { const t = tally(r === 'ALL' ? p.xs : p.xs.filter((x) => x.rule === r)); return `${t.towns} · ${t.n} · ${t.lines} · ${t.things} · ${t.held}`; });
  md.push(`| ${r} | ${cells.join(' | ')} |`);
}
md.push('', `Towns in each population: ${pops.map((p) => `${p.label} (the runner's own count is in its log)`).join(', ')}.`, '');
for (const r of rules) {
  const p = pops.find((q) => q.label === '720' && q.xs.some((x) => x.rule === r)) || pops.find((q) => q.xs.some((x) => x.rule === r));
  const xs = p.xs.filter((x) => x.rule === r);
  const by = new Map();
  for (const x of xs) { const v = by.get(x.form) || { n: 0, towns: new Set(), tab: x.tab, ag: x.against?.line, w: x.writer, fw: x.factWriter }; v.n++; v.towns.add(x.town); by.set(x.form, v); }
  md.push(`## ${r}: the thirty commonest distinct lines (${p.label}; ${by.size} distinct)`, '', '| n | towns | tab | line | against (first) | writer · fact |', '|---|---|---|---|---|---|');
  for (const [form, v] of [...by].sort((a, b) => b[1].n - a[1].n).slice(0, 30)) {
    const towns = [...v.towns].slice(0, 3).join(', ') + (v.towns.size > 3 ? ` +${v.towns.size - 3}` : '');
    md.push(`| ${v.n} | ${towns} | ${v.tab} | ${String(form).slice(0, 110).replace(/\|/g, '/')} | ${String(v.ag || '').slice(0, 90).replace(/\|/g, '/')} | ${v.w || '—'} · ${v.fw || '—'} |`);
  }
  md.push('');
}
// THE OVERLAP WITH THE ROUND IN FLIGHT (BRIEF-BAR5's seat sections): each instance to the BAR5 seat whose named fact holds
// it, else the next wave. heldBy: its line is one a LAW 2/3 rule finds (that rule's seat).
const SEAT_OF_PRIOR = { 'L2.siege.abroad': 'BAR5-MARKS', 'L2.siege.cutgood': 'BAR5-MARKS', 'L2.war.iron': 'BAR5-MARKS', 'L2.war.animals': 'BAR5-MARKS', 'L2.famine.meat': 'BAR5-MARKS', 'L2.famine.work': 'BAR5-MARKS', 'L2.famine.grain': 'BAR5-MARKS', 'L3.needed': 'BAR5-CHAINS', 'L3.outputs': 'BAR5-CHAINS', 'L3.chainOverStopped': 'BAR5-CHAINS', 'L3.failedFood': 'BAR5-FOOD', 'L3.foodLineStopped': 'BAR5-FOOD' };
export function roundOf(x) {
  if (x.heldBy) return `${SEAT_OF_PRIOR[x.heldBy] || 'BAR5'} (on ${x.heldBy})`;
  if (/^8a\./.test(x.rule)) {
    if (x.recordNamed) return 'BAR5-CHAINS (b): the critical imports\' named house';
    if (x.how === 'war') return 'BAR5-MARKS (b): the war\'s iron (WM1)';
    if (x.how === 'cut off' && x.good === 'herbs') return 'BAR5-MARKS: the herbs cut off (L2.siege.cutgood)';
  }
  if (x.rule === '8d.transport') return 'BAR5-MARKS (a): the stables and the beasts that serve travellers';
  if (x.rule === '8c.export' && /Failed this year · Grain/.test(x.against?.line || '')) return 'BAR5-FOOD (a): the failed source on the trade profile';
  return 'NEXT WAVE';
}
md.push('## The overlap with the round in flight (things: a house or a row once a town)', '', `| rule | seat | ${pops.map((p) => p.label).join(' | ')} |`, `|---|---|${pops.map(() => '---').join('|')}|`);
for (const r of rules) {
  const seats = [...new Set(pops.flatMap((p) => p.xs.filter((x) => x.rule === r).map(roundOf)))].sort();
  for (const seat of seats) md.push(`| ${r} | ${seat} | ${pops.map((p) => new Set(p.xs.filter((x) => x.rule === r && roundOf(x) === seat).map((x) => `${x.town}|${x.thing}`)).size).join(' | ')} |`);
}
md.push('');
fs.writeFileSync(outMd, md.join('\n'));
console.log(`wrote ${outMd}: ${rules.length} rules over ${pops.map((p) => `${p.label} (${p.xs.length})`).join(', ')}`);
