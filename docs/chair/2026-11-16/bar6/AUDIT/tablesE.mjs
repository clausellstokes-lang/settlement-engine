// BAR6-AUDIT-E · the tables of the hand-back from runE outputs (and traceE's writers).
//   node docs/chair/2026-11-16/bar6/AUDIT/tablesE.mjs <TABLES-E.md> <label>=<runE out.json>[,<writers.json>] ...
// For each population: counts by rule (towns, instances, distinct lines; counted or apart; the BAR5 seat that holds it);
// for each rule the thirty commonest distinct lines with their towns; and, where a writers file is given, the writer
// file of each distinct line and of the line it is read against.
import fs from 'node:fs';

const [dest, ...pops] = process.argv.slice(2);
if (!dest || !pops.length) { console.error('usage: tablesE.mjs <out.md> <label>=<out.json>[,<writers.json>] ...'); process.exit(2); }
const md = ['# BAR6-AUDIT-E · LAW 9 · TABLES', '', 'Generated by `tablesE.mjs` from `runE.mjs` outputs (and `traceE.mjs` writers). Counted rules exclude the rows reported APART (WEAK or ruled both ways).', ''];
for (const p of pops) {
  const [label, files] = p.split('='); const [file, wfile] = files.split(',');
  const xs = JSON.parse(fs.readFileSync(file, 'utf8'));
  const towns = new Set(xs.map((x) => x.town));
  const counted = xs.filter((x) => x.status !== 'apart');
  md.push(`## ${label}`, '', `Counted: ${counted.length} instances in ${new Set(counted.map((x) => x.town)).size} towns, ${new Set(counted.map((x) => x.rule + '|' + x.form)).size} distinct lines. Held by a BAR5 seat: ${counted.filter((x) => x.held).length} in ${new Set(counted.filter((x) => x.held).map((x) => x.town)).size} towns. Beyond the round: ${counted.filter((x) => !x.held).length} in ${new Set(counted.filter((x) => !x.held).map((x) => x.town)).size} towns. Apart: ${xs.length - counted.length}.`, '',
    '| rule | towns | instances | distinct | held by | counted? |', '|---|---:|---:|---:|---|---|');
  const by = new Map();
  for (const x of xs) { const v = by.get(x.rule) || { n: 0, t: new Set(), f: new Map(), held: x.held, status: x.status }; v.n++; v.t.add(x.town); const f = v.f.get(x.form) || []; f.push(x.town); v.f.set(x.form, f); by.set(x.rule, v); }
  for (const [k, v] of [...by].sort()) md.push(`| ${k} | ${v.t.size} | ${v.n} | ${v.f.size} | ${v.held || '-'} | ${v.status === 'apart' ? 'apart' : 'counted'} |`);
  md.push('');
  const W = wfile ? JSON.parse(fs.readFileSync(wfile, 'utf8')) : [];
  const wOf = (rule, form) => W.find((w) => w.rule === rule && w.form === form);
  md.push(`### ${label} · the commonest distinct lines of each rule${W.length ? ', with the writer of the line and of what it is read against' : ''}`, '');
  for (const [k, v] of [...by].sort()) {
    md.push(`**${k}** (${v.n} in ${v.t.size} towns)`, '');
    for (const [form, ts] of [...v.f].sort((a, b) => b[1].length - a[1].length).slice(0, 30)) {
      const w = wOf(k, form);
      const wr = w ? ` · writer \`${w.writer.file}${w.writer.fn ? ' :: ' + w.writer.fn : ''}\` · against \`${w.againstWriter.file}${w.againstWriter.fn ? ' :: ' + String(w.againstWriter.fn).slice(0, 70) : ''}\`` : '';
      md.push(`- ${ts.length}× "${form.slice(0, 180)}" (e.g. ${[...new Set(ts)].slice(0, 3).join(', ')})${wr}`);
    }
    md.push('');
  }
}
fs.writeFileSync(dest, md.join('\n'));
console.log(`wrote ${dest}`);
