/**
 * Seat A's tables: node tables-a.mjs <out.md> <label>=<run.json>[,<trace hits.json>] ...  (run.json from run-a.mjs; the
 * trace from PAGE-COPY writers2.mjs over the run's distinct lines). Writes the controls (from the first run that has
 * them), the counts by sub-law per population, the two-facts splits, the thirty commonest distinct lines of each law
 * with their towns, and the writer files.
 */
import fs from 'node:fs';
const [, , out, ...args] = process.argv;
const runs = args.map((a) => { const [label, rest] = a.split('='); const [run, trace] = rest.split(','); return { label, j: JSON.parse(fs.readFileSync(run, 'utf8')), tr: trace && fs.existsSync(trace) ? JSON.parse(fs.readFileSync(trace, 'utf8')) : null }; });
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const L = [];
L.push('# BAR5-AUDIT seat A · the tables (generated by `tables-a.mjs`; do not edit by hand)', '');
const withControls = runs.find((r) => r.j.controls);
if (withControls) {
  L.push(`## The controls (${withControls.label})`, '', '| id | want | law | verdict | town | still printed | found as | text |', '|---|---|---|---|---|---|---|---|');
  for (const c of withControls.j.controls) L.push(`| ${c.id} | ${c.expect} | ${c.law} | ${c.verdict} | ${c.town.replace('bar0-', '')} | ${c.printed ? 'yes' : 'no'} | ${c.found ? c.as.join(', ') : '—'} | ${esc(c.text.slice(0, 90))} |`);
  L.push('');
}
const subs = [...new Set(runs.flatMap((r) => Object.keys(r.j.counts)))].sort();
L.push('## The counts by sub-law (towns · instances · distinct lines)', '', `| sub-law | ${runs.map((r) => `${r.label} (${r.j.towns} towns)`).join(' | ')} |`, `|---|${runs.map(() => '---').join('|')}|`);
for (const k of subs.filter((k) => !k.startsWith('4r'))) L.push(`| ${k} | ${runs.map((r) => { const c = r.j.counts[k]; return c ? `${c.towns} · ${c.instances} · ${c.distinct}` : '0'; }).join(' | ')} |`);
const keys = [...new Set(runs.flatMap((r) => Object.keys(r.j.lawTop)))].sort();
L.push('', '**By law** (towns · instances · distinct lines):', '', `| law | ${runs.map((r) => r.label).join(' | ')} |`, `|---|${runs.map(() => '---').join('|')}|`);
for (const k of keys) L.push(`| ${k} | ${runs.map((r) => { const c = r.j.lawTop[k]; return c ? `${c.towns} · ${c.instances} · ${c.distinct}` : '0'; }).join(' | ')} |`);
L.push('');
for (const r of runs) {
  L.push(`## The two-facts splits (${r.label})`, '', '| magic: record reading · shown reading · page word · defenceFlag | towns |', '|---|---|');
  for (const [k, v] of Object.entries(r.j.splits.magic).sort((a, b) => b[1] - a[1])) L.push(`| ${k} | ${v} |`);
  L.push('', '| food: stored label · band · shown word · page word | towns |', '|---|---|');
  for (const [k, v] of Object.entries(r.j.splits.food).sort((a, b) => b[1] - a[1])) L.push(`| ${esc(k)} | ${v} |`);
  L.push('');
}
L.push('## LAW 4 (4n): each thing, named at all and named without (towns naming · distinct lines naming · towns that print one without the thing)', '', `| thing | ${runs.map((r) => r.label).join(' | ')} |`, `|---|${runs.map(() => '---').join('|')}|`);
for (const k of [...new Set(runs.flatMap((r) => Object.keys(r.j.namedAt || {})))].sort()) L.push(`| ${k} | ${runs.map((r) => { const c = (r.j.namedAt || {})[k]; return c ? `${c.townsNaming} · ${c.distinctLines} · ${c.townsWithout}` : '0'; }).join(' | ')} |`);
L.push('');
const big = runs.find((r) => r.label === '720') || runs[runs.length - 1];
L.push(`## The register's vocabulary on the page, 4r, by thing (${big.label}: towns that print a line naming it without it · distinct lines)`, '', '| thing | towns | instances | distinct |', '|---|---|---|---|');
for (const [k, c] of Object.entries(big.j.counts).filter(([k]) => k.startsWith('4r')).sort((a, b) => b[1].towns - a[1].towns)) L.push(`| ${k} | ${c.towns} | ${c.instances} | ${c.distinct} |`);
L.push('');
for (const r of runs.filter((r) => r.label !== 'sixty' || runs.length === 1)) {
  for (const [k, v] of Object.entries(r.j.lawTop).filter(([k]) => !k.startsWith('4r'))) {
    L.push(`## Law ${k} · the commonest distinct lines (${r.label}; towns)`, '', '| towns | line |', '|---|---|');
    for (const t of v.top) L.push(`| ${t.towns} | ${esc(t.line.slice(0, 220))} |`);
    L.push('');
  }
}
for (const r of runs.filter((r) => r.tr)) {
  const m = {};
  for (const h of r.tr) { const k = `${h.pattern.split('/')[0]} | ${h.writer?.file || '(untraced)'} | ${h.writer?.fn || h.writer?.pool || ''}`; m[k] = (m[k] || 0) + 1; }
  L.push(`## By writer file (${r.label}; distinct lines of each sub-law traced by PAGE-COPY writers2.mjs)`, '', '| sub-law | writer file | function or pool | distinct lines |', '|---|---|---|---|');
  for (const [k, v] of Object.entries(m).sort()) L.push(`| ${k.split(' | ').map(esc).join(' | ')} | ${v} |`);
  L.push('');
}
fs.writeFileSync(out, L.join('\n') + '\n');
console.log('wrote', out, L.length, 'lines');
