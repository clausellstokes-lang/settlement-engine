import sys, re, html
src=open(sys.argv[1],encoding='utf-8',errors='replace').read()
src=re.sub(r'(?is)<script.*?</script>',' ',src)
src=re.sub(r'(?is)<style.*?</style>',' ',src)
src=re.sub(r'(?is)<!--.*?-->',' ',src)
src=re.sub(r'(?i)<(br|/p|/div|/h\d|/li|/tr)[^>]*>','\n',src)
src=re.sub(r'(?s)<[^>]+>',' ',src)
src=html.unescape(src)
src=re.sub(r'[ \t\xa0]+',' ',src)
src=re.sub(r'\n\s*\n+','\n',src)
print(src.strip())
