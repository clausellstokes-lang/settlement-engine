/**
 * tests/domain/undercityMonotoneComponents.test.js — MF-UC2's acceptance: the MONOTONE COMPONENTS
 * (charter draft-UNDERCITY-PLAN.md §4 UC-2; ODQ §311.8.2(b) / §311.8.3, ruled §441, dispatched
 * §484).
 *
 * THE MEMBER: `src/domain/undercity/monotoneComponents.js` derives the crypts under what buries,
 * the surge pit a dated year of mass death digs, the undercrofts under what stores, the smuggler
 * subset of those, the workings at the dossier's own seams, and the sealed vaults under what arms
 * and what judges. Nothing is stored; nothing on the generation path imports it.
 *
 * EVERY ARM RUNS OVER REAL GENERATED SETTLEMENTS (`generateSettlementPipeline`, fixed seeds), never
 * a hand-built fixture, so the roster, terrain, resources, defence profile and population the
 * deriver reads are the ones the generator actually writes. The counterfactual arms change ONE
 * stored input and watch the row move (the §306.2 input-trap law).
 *
 * THE VOCABULARY ARMS ARE PINNED AGAINST THE LIVE DATA, never against themselves: the joint kinds
 * and temperaments come from UC-0's `jointVocabulary.js`, the excavation terrains are re-derived
 * from the real `TERRAIN_DATA`, the resource types from the real `RESOURCE_SEMANTICS`, the zones
 * from UC-1's pinned district 12-enum and the anchor keys from UC-0's `institutionAnchorKey` — so a
 * table that drifts away from the estate it claims to read reddens here rather than passing on its
 * own copy.
 *
 * §474: the shared-namespace arms pin INTENT — a positive control plus a named exclusion set —
 * rather than an ordered equality a later car of this train would grow.
 *
 * Registration: this member mints no registry row, no flag, no migration, no spatial ledger and no
 * coupling-census entry (`src/domain/undercity/**` is outside the coupling census's scope). The
 * anchor walker, the ruin-filter roster walker and the test census are the registers it fires.
 * Every negative below is anchored (§P3).
 */
